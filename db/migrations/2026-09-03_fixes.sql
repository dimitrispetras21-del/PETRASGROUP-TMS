-- ═══════════════════════════════════════════════════════════════════════════
-- ΤΙ ΣΥΜΒΑΙΝΕΙ: η εγγραφή κάθεται στην Κεντρική Αφρική και τραβούσε το κάδρο
-- του χάρτη τόσο, ώστε ολόκληρη η Ευρώπη να χωράει σε 200×170px στα 1440.
