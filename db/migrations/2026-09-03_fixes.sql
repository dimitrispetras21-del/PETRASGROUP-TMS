-- ════════════════════════════════════════════════════════════════════════════
-- (Α) maint_history.cost = 0  →  NULL,  ΜΟΝΟ όπου needs_review
-- ════════════════════════════════════════════════════════════════════════════
-- ΤΟ ΠΡΟΒΛΗΜΑ
-- 14 γραμμές ιστορικού συντήρησης έχουν cost = 0. Δεν κόστισαν μηδέν: είναι
-- εγγραφές από import όπου το ποσό δεν διαβάστηκε. Η οθόνη τις δείχνει «€0»
-- και τις προσθέτει στα σύνολα ως ΓΝΩΣΤΟ κόστος — δηλαδή ένα άγνωστο
-- εμφανίζεται ως μετρημένο μηδέν (η ίδια παγίδα με το άγραφο που φαινόταν
-- ξοφλημένο: κανόνας #3 του facade, «άγνωστο ≠ μηδέν»).
--
-- ΓΙΑΤΙ ΤΟ ΦΙΛΤΡΟ ΕΙΝΑΙ needs_review ΚΑΙ ΟΧΙ ΣΚΕΤΟ cost = 0
-- Ένα πραγματικό μηδενικό κόστος (εγγύηση, δωρεάν έλεγχος) είναι έγκυρη τιμή
-- και ΔΕΝ πρέπει να γίνει NULL. Το needs_review ξεχωρίζει «δεν διαβάστηκε»
-- από «ήταν όντως μηδέν».
--
-- ΜΕΤΡΗΣΕΙΣ 3/9/2026 (maint_history WHERE deleted_at IS NULL, 1.091 ζωντανές):
--   cost = 0 AND needs_review IS TRUE      = 14   ← αυτές αλλάζουν
--   cost = 0 AND needs_review IS NOT TRUE  =  0   ← καμία αθώα γραμμή στο φίλτρο
--   από τις 14: με source_ref (import)     = 14
--               με invoice_number          =  0   ← καμία δεν έχει τιμολόγιο
--   cost IS NULL ήδη                       =  0   ← ο μετρητής «μετά» θα δείξει 14
--   needs_review IS TRUE συνολικά          = 91
--
-- ΤΙ ΘΑ ΔΕΙ Ο ΧΡΗΣΤΗΣ ΜΕΤΑ
-- Το κόστος γίνεται NULL. Παγίδα #2 του facade: στήλη με NULL ΔΕΝ εμφανίζεται
-- καθόλου στην απάντηση, οπότε το `f['Cost']` γίνεται undefined. Το
-- modules/maintenance.js πρέπει να δείξει «—» εκεί, όχι «€0» — αν το κάνει
-- `Number(f['Cost']) || 0`, το άγνωστο ξαναγίνεται μηδέν και δεν κερδίσαμε
-- τίποτα. ΕΛΕΓΞΕ ΤΟ ΣΤΗΝ ΟΘΟΝΗ μετά την εκτέλεση.

BEGIN;

-- ── (Α1) ΠΡΙΝ ───────────────────────────────────────────────────────────────
SELECT 'ΠΡΙΝ' AS φάση,
       count(*) FILTER (WHERE cost = 0 AND needs_review IS TRUE)     AS "μηδέν_προς_αλλαγή",
       count(*) FILTER (WHERE cost = 0 AND needs_review IS NOT TRUE) AS "μηδέν_που_μένει",
       count(*) FILTER (WHERE cost IS NULL)                          AS "ήδη_null",
       count(*)                                                      AS "σύνολο_ζωντανών"
  FROM maint_history WHERE deleted_at IS NULL;
-- αναμενόμενο: 14 · 0 · 0 · 1091

-- ── (Α2) Η ΑΛΛΑΓΗ ───────────────────────────────────────────────────────────
UPDATE maint_history
   SET cost = NULL
 WHERE deleted_at IS NULL
   AND cost = 0
   AND needs_review IS TRUE;
-- αναμενόμενο: UPDATE 14

-- ── (Α3) ΜΕΤΑ — έλεγξε ΠΡΙΝ το COMMIT ───────────────────────────────────────
SELECT 'ΜΕΤΑ' AS φάση,
       count(*) FILTER (WHERE cost = 0 AND needs_review IS TRUE)     AS "μηδέν_προς_αλλαγή",
       count(*) FILTER (WHERE cost = 0 AND needs_review IS NOT TRUE) AS "μηδέν_που_μένει",
       count(*) FILTER (WHERE cost IS NULL)                          AS "ήδη_null",
       count(*)                                                      AS "σύνολο_ζωντανών"
  FROM maint_history WHERE deleted_at IS NULL;
-- αναμενόμενο: 0 · 0 · 14 · 1091
-- Αν το «σύνολο_ζωντανών» δεν είναι ξανά 1091, κάτι άλλο έτρεξε: ROLLBACK.

COMMIT;


-- ════════════════════════════════════════════════════════════════════════════
-- (Β) local_moves.legacy_id — η ταυτότητα που απαιτεί ο facade
-- ════════════════════════════════════════════════════════════════════════════
-- ΤΟ ΠΡΟΒΛΗΜΑ
-- Ο Worker μιμείται το Airtable: κάθε εγγραφή έχει id μορφής 'recXXXXXXXXXXXXXX'
-- και ΚΑΘΕ ανάγνωση/εγγραφή μιας εγγραφής περνά από `legacy_id=eq.<recid>`
-- (handleFacadeGetOne / handleFacadeUpdate / handleFacadeDelete). Ο πίνακας
-- local_moves φτιάχτηκε 10/8 χωρίς αυτή τη στήλη, οπότε δεν μπορεί να μπει
-- στον facade όπως είναι.
--
-- ΤΟ ΣΧΗΜΑ ΕΙΝΑΙ ΑΝΤΙΓΡΑΦΟ ΤΩΝ ΑΔΕΛΦΩΝ, ΟΧΙ ΝΕΑ ΕΠΙΝΟΗΣΗ
-- Μετρημένο 3/9 σε national_loads / order_stops / ramp / maint_req:
--   τύπος text · nullable · ΧΩΡΙΣ default · UNIQUE index (<table>_legacy_id_key)
-- Το ίδιο ακριβώς μπαίνει εδώ. Το recid το φτιάχνει ο Worker (mintLegacyId,
-- 'rec' + 14 τυχαίοι χαρακτήρες) τη στιγμή του POST — γι' αυτό ΔΕΝ μπαίνει
-- default στη βάση: δύο γεννήτριες ταυτότητας για τον ίδιο πίνακα είναι δύο
-- πηγές αλήθειας (αρχή 3).
--
-- ΓΙΑΤΙ NULLABLE ΚΑΙ ΟΧΙ NOT NULL
-- Ίδιο με τους αδελφούς. Το UNIQUE στην Postgres επιτρέπει πολλαπλά NULL, άρα
-- μια γραμμή που θα έμπαινε ποτέ από SQL (όχι από τον facade) δεν μπλοκάρει —
-- απλώς δεν θα είναι ορατή μέσω recid. Το NOT NULL θα ήταν αυστηρότερο, αλλά
-- θα διέφερε από τους 4 άλλους πίνακες, και μια διαφορά που κανείς δεν ζήτησε
-- είναι μελλοντική έκπληξη.
--
-- ΓΙΑΤΙ ΔΕΝ ΧΡΕΙΑΖΕΤΑΙ BACKFILL
-- Μετρημένο 3/9: SELECT count(*) FROM local_moves = 0 γραμμές.
-- Δεν υπάρχει τίποτα να γεμίσει· κάθε μελλοντική εγγραφή θα έρθει από τον
-- facade με έτοιμο recid.
--
-- ΔΙΚΑΙΩΜΑΤΑ / RLS — ΤΙΠΟΤΑ ΝΑ ΚΑΝΕΙΣ (επαληθεύτηκε 3/9)
-- local_moves και national_loads έχουν ΤΑΥΤΟΣΗΜΟ προφίλ:
--   relrowsecurity = true, policies = 0 (και στους δύο)
--   service_role: SELECT ✓ INSERT ✓ UPDATE ✓ DELETE ✗ (και στους δύο)
-- Το DELETE λείπει και στους δύο και είναι ΣΩΣΤΟ: ο facade δεν κάνει ποτέ
-- hard delete — γράφει deleted_at μέσω UPDATE. Κανένα GRANT δεν χρειάζεται.

BEGIN;

-- ── (Β1) ΠΡΙΝ ───────────────────────────────────────────────────────────────
SELECT 'ΠΡΙΝ' AS φάση,
       (SELECT count(*) FROM local_moves)                                AS "γραμμές",
       (SELECT count(*) FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'local_moves'
           AND column_name = 'legacy_id')                                AS "στήλη_υπάρχει";
-- αναμενόμενο: 0 · 0

-- ── (Β2) Η ΣΤΗΛΗ ────────────────────────────────────────────────────────────
ALTER TABLE public.local_moves
  ADD COLUMN IF NOT EXISTS legacy_id text;

-- ── (Β3) ΤΟ UNIQUE ──────────────────────────────────────────────────────────
-- Ξεχωριστή δήλωση από την προσθήκη: το ADD COLUMN είναι στιγμιαίο, ο δείκτης
-- είναι που θα κρατούσε κλείδωμα σε μεγάλο πίνακα. Εδώ ο πίνακας είναι άδειος
-- και δεν παίζει ρόλο — αλλά η δήλωση μένει ξεχωριστή ώστε να φαίνεται στο
-- log ποιο βήμα πέτυχε. Το όνομα ακολουθεί τη σύμβαση της Postgres, ίδιο με
-- national_loads_legacy_id_key / order_stops_legacy_id_key / ramp_legacy_id_key.
ALTER TABLE public.local_moves
  ADD CONSTRAINT local_moves_legacy_id_key UNIQUE (legacy_id);

COMMENT ON COLUMN public.local_moves.legacy_id IS
  'Ταυτότητα Airtable-style (recXXXXXXXXXXXXXX) που παράγει ο Worker στο POST (mintLegacyId). ΜΟΝΟ από αυτήν διαβάζει και γράφει ο facade μία εγγραφή — χωρίς αυτήν ο πίνακας δεν είναι προσβάσιμος από το app. Χωρίς default: η γεννήτρια ζει στον Worker, όχι σε δύο σημεία.';

-- ── (Β4) ΜΕΤΑ — έλεγξε ΠΡΙΝ το COMMIT ───────────────────────────────────────
SELECT 'ΜΕΤΑ' AS φάση, column_name, data_type, is_nullable, column_default
  FROM information_schema.columns
 WHERE table_schema = 'public' AND table_name = 'local_moves'
   AND column_name = 'legacy_id';
-- αναμενόμενο: 1 γραμμή — legacy_id · text · YES · NULL

SELECT 'ΜΕΤΑ' AS φάση, indexname, indexdef
  FROM pg_indexes
 WHERE schemaname = 'public' AND tablename = 'local_moves'
   AND indexdef ILIKE '%legacy_id%';
-- αναμενόμενο: 1 γραμμή — local_moves_legacy_id_key, UNIQUE btree (legacy_id)
-- Σύγκρινέ την με το national_loads_legacy_id_key: πρέπει να διαφέρει μόνο
-- στο όνομα πίνακα.

COMMIT;


