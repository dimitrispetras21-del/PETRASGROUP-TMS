-- ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΕΙΚΑΣΙΑ — δύο ανεξάρτητες επιβεβαιώσεις:
--   1. address = 'Thesi Imeros Topos 1 193 00 Aspropyrgos' · city = 'Athens'
--      Ο Ασπρόπυργος Αττικής είναι στις ~38,06°N.
--   2. longitude = 23.556295 είναι ΗΔΗ σωστό για Αττική (~23,5°E) και δεν
--      αγγίζεται. Μόνο το latitude είναι λάθος, και είναι ακριβώς το σωστό
--      χωρίς το πρώτο ψηφίο: 8.102725 → 38.102725.
--
-- Αν το πλάτος 38.102725 δεν είναι το ακριβές σημείο της εγκατάστασης, η
-- διόρθωση εξακολουθεί να είναι σωστότερη από το σημερινό: βάζει την εγγραφή
-- στη σωστή χώρα αντί για άλλη ήπειρο. Ακριβές σημείο = γεωκωδικοποίηση από
-- τη διεύθυνση, που η οθόνη Τοποθεσιών κάνει με ένα κουμπί.

BEGIN;

SELECT id, name, city, latitude, longitude FROM locations WHERE id = 2347;
-- Αναμένεται: VF Hellas · Athens · 8.102725 · 23.556295

UPDATE locations
   SET latitude = 38.102725
 WHERE id = 2347
   AND latitude = 8.102725      -- φρουρός: αν κάποιος το διόρθωσε ήδη, 0 rows
   AND deleted_at IS NULL;

SELECT id, name, city, latitude, longitude FROM locations WHERE id = 2347;
-- Αναμένεται: VF Hellas · Athens · 38.102725 · 23.556295

-- Επαλήθευση ότι δεν έμεινε άλλο σημείο εκτός Ευρώπης:
