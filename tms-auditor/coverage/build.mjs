// Generates the coverage table of docs/tms-auditor/02-χάρτης-κάλυψης.md from PRIMARY inputs only:
// the 42 flows of docs/grok-bot/monitoring-2026-09-22/02a (titles/roles), the check catalog (flows field),
// the local tests (which checks they exercise), and part-z final outcomes (which checks prove an END state).
// Nothing here is typed by hand: re-run after any catalog change (node coverage/build.mjs).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadChecks } from '../checks/load.mjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const A2 = ['docs/grok-bot/monitoring-2026-09-22/02a-ροές-frontend.md', '../../../docs/grok-bot/monitoring-2026-09-22/02a-ροές-frontend.md']
  .map((p) => path.resolve(ROOT, p)).find((p) => fs.existsSync(p));
const src = fs.readFileSync(A2, 'utf8');
const flows = [...src.matchAll(/\*\*(F-\d\d) · ([^*]+?)\.\*\*\s*([^·\n]*)/g)].map((m) => ({ id: m[1], title: m[2].trim(), roles: m[3].trim().slice(0, 60) }));
const { checks } = loadChecks();
const z = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/tms-auditor/graph/part-z.json'), 'utf8'));
const proving = new Set(z.final_outcomes.flatMap((o) => o.proving_checks || []));
// checks exercised by the local tests (grep of the test files — a check named there is run by a test)
const tested = new Set();
for (const f of fs.readdirSync(path.join(ROOT, 'tms-auditor/test')).filter((f) => f.endsWith('.test.mjs')))
  for (const m of fs.readFileSync(path.join(ROOT, 'tms-auditor/test', f), 'utf8').matchAll(/'((?:B|P)-\d\d[a-z]?)'/g)) tested.add(m[1]);
const chainFlows = new Set(['F-14']);   // chain.test.mjs: the full chain
const DETECT = { fast: '≤ 20′', half: '≤ 35′', hourly: '≤ 70′', daily: 'έως 05:10 επομένης', weekly: 'Σάββατο' };
const rows = flows.map((f) => {
  const cs = checks.filter((c) => c.enabled && c.flows.includes(f.id));
  const gaps = checks.filter((c) => !c.enabled && c.flows.includes(f.id)).map((c) => c.id);
  let status = cs.length === 0 ? 'ακάλυπτη' : cs.some((c) => proving.has(c.id)) ? 'καλυμμένη (σχέδιο)' : 'μερικώς';
  if (f.id === 'F-41') status = 'ανεξερεύνητη';
  const fastest = cs.map((c) => c.schedule).sort((a, b) => Object.keys(DETECT).indexOf(a) - Object.keys(DETECT).indexOf(b))[0];
  const sev = cs.some((c) => c.severity === 'P1') ? 'push αμέσως (P1)' : cs.length ? 'σύνοψη 17:00' : '—';
  return { ...f, checks: cs.map((c) => c.id), gaps, status, detect: fastest ? DETECT[fastest] : '—', notify: sev,
           tested: chainFlows.has(f.id) ? 'πλήρης αλυσίδα' : cs.some((c) => tested.has(c.id)) ? 'λογική ελέγχου' : 'μόνο SQL στην παραγωγή' };
});
const n = (fn) => rows.filter(fn).length;
const numbers = {
  analysed: `${rows.length}/${rows.length}`,
  with_check: n((r) => r.checks.length > 0),
  tested_locally_full_chain: n((r) => r.tested === 'πλήρης αλυσίδα'),
  tested_locally_logic: n((r) => r.tested !== 'μόνο SQL στην παραγωγή' && r.checks.length > 0),
  active_automatic: 0, verified_delivery: 0,
  by_status: rows.reduce((a, r) => ((a[r.status] = (a[r.status] || 0) + 1), a), {}),
};
const table = ['| Ροή | Τίτλος (02a) | Έλεγχοι | Κατάσταση | Εντοπισμός (όταν ενεργοποιηθεί) | Ειδοποίηση | Δοκιμή | Κενά/ΓΚΡΙ |', '|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.title.replace(/\|/g, '/')} | ${r.checks.join(', ') || '—'} | ${r.status} | ${r.detect} | ${r.notify} | ${r.tested} | ${r.gaps.join(', ') || ''} |`)].join('\n');
fs.writeFileSync(path.join(ROOT, 'docs/tms-auditor/coverage-table.generated.md'), `<!-- GENERATED by tms-auditor/coverage/build.mjs — do not edit -->\n${table}\n`);
fs.writeFileSync(path.join(ROOT, 'docs/tms-auditor/coverage-numbers.generated.json'), JSON.stringify(numbers, null, 1));
console.log(JSON.stringify(numbers));
