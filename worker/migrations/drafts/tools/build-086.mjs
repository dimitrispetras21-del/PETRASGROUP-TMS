// Generates the dry run, the rollback and the rollback's dry run of 086 FROM its source (086_plan_busy_overlap_ok.sql):
//   node worker/migrations/drafts/tools/build-086.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-086.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 086 applied - it reads them (and the md5 before / after) from the source, never a hand copy. The schema part
// of the rollback (the two full EXCLUDE of 072b, the column, the two triggers, B-54) is written here once.
// tests/sql-086-drafts.test.js fails on drift; tms-auditor/test/plan-086.test.mjs runs them on the production-shaped copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// 086 is a draft: its files live in drafts/ until the owner runs it (CLAUDE.md rule 5), then one up
export const DIR = fs.existsSync(path.resolve(HERE, '..', '086_plan_busy_overlap_ok.sql')) ? path.resolve(HERE, '..') : path.resolve(HERE, '..', '..');
export const SOURCE = '086_plan_busy_overlap_ok.sql';
export const ROLLBACK = '086_plan_busy_overlap_ok_rollback.sql';
const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;
const BUSY = 'public.plan_h_busy(text,bigint,timestamptz,timestamptz,bigint)';
const RESEQ = 'public.plan_h_reseq(bigint,text,text)';

// The facts of the source, read once: the hunk constants, the live md5 (PART 0) and the generated md5 (PART 2)
export function facts(src) {
  const consts = Object.fromEntries([...src.matchAll(/^ {2}([a-z0-9_]+) CONSTANT text := \$h\$([\s\S]*?)\$h\$;$/gm)].map((m) => [m[1], m[2]]));
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part2 = src.slice(src.indexOf('===== PART 2'), src.indexOf('===== PART 3'));
  const live = Object.fromEntries([...part0.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', '([0-9a-f]{32})'\)/g)].map((m) => [m[1], m[2]]));
  const gen = [...part2.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', ARRAY\[([a-z0-9_, ]+)\], ARRAY\[([a-z0-9_, ]+)\], '([0-9a-zA-Z_]+)'\)/g)]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (gen.length !== 6 || gen.some((g) => !live[g.sig] || g.a.length !== g.b.length || [...g.a, ...g.b].some((k) => !(k in consts)))) {
    throw new Error(`${SOURCE}: PART 0 / PART 2 are not the six functions with their hunks`);
  }
  const x = (name) => {
    const m = new RegExp(`conname = '${name}' AND contype = 'x' AND condeferrable AND condeferred\\) IS DISTINCT FROM '([0-9a-f]{32})'`).exec(src);
    if (!m) throw new Error(`${SOURCE}: the proof md5 of ${name} was not found`);
    return m[1];
  };
  const x0 = (name) => {
    const m = new RegExp(`AND conname = '${name}'\\) IS DISTINCT FROM '([0-9a-f]{32})'`).exec(part0);
    if (!m) throw new Error(`${SOURCE}: the live md5 of ${name} was not found`);
    return m[1];
  };
  const a = src.indexOf('  -- the hunks:'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the hunk block was not found`);
  return { consts, live, gen, hunks: src.slice(a, b), xGen: { truck: x('rt_v2_truck_once'), driver: x('rt_v2_driver_once') },
    xLive: { truck: x0('rt_v2_truck_once'), driver: x0('rt_v2_driver_once') } };
}

// The text 086 writes, from a live text (the PGlite test derives the md5 of PART 2 with it)
export function applyHunks(text, g, consts) {
  let out = text;
  g.a.forEach((k, i) => {
    const n = out.split(consts[k]).length - 1;
    if (n !== 1) throw new Error(`${g.sig}: hunk ${k} found ${n} times`);
    out = out.replace(consts[k], () => consts[g.b[i]]);
  });
  return out;
}

export const DRY = {
  source: SOURCE, target: '086_plan_busy_overlap_ok_dryrun.sql', name: 'DRY RUN 086',
  header: `-- 086 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-086.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND (tests/sql-086-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056), the column and the two rebuilt EXCLUDE included. ASCII only.
-- EXPECTED (the red ERROR is deliberate): NOTICE "086 OK: an accepted overlap is allowed pair by pair with a trace ..." and then
--   ERROR: P0001: DRY RUN 086 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  086 ran:
--   busy GEN_BUSY, reseq GEN_RESEQ
--   Anything else (an ERROR from one of 086's guards or proofs): do NOT run 086, copy the message to the coordinator.`,
  epilogue: `  res := format('086 ran: busy %s, reseq %s', ${md5Of(BUSY)}, ${md5Of(RESEQ)});`,
};

export function buildRollback(src) {
  const f = facts(src);
  const blocks = f.gen.map((g) => `  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${g.sig}');
  IF md5(p.prosrc) <> '${g.m}' THEN
    RAISE EXCEPTION '086 rollback: ${g.sig} is not the text 086 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '086 rollback: a hunk of 086 is not in ${g.sig} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live[g.sig]}' THEN
    RAISE EXCEPTION '086 rollback: ${g.sig} would not be its text before 086 (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE plpgsql %s %s SET search_path = public AS %L',
    split_part('${g.sig}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  IF ${md5Of(g.sig)} <> '${f.live[g.sig]}'
     OR (SELECT proacl::text FROM pg_proc WHERE oid = p.oid) IS DISTINCT FROM p.proacl::text THEN
    RAISE EXCEPTION '086 rollback proof: ${g.sig} is not back to its text before 086 with its rights';
  END IF;`).join('\n');
  const xdef = (name) => `SELECT md5(pg_get_constraintdef(oid)) FROM pg_constraint WHERE conrelid = 'public.rt_vehicle_segments'::regclass
        AND conname = '${name}' AND contype = 'x' AND condeferrable AND condeferred`;
  return `-- 086 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-086.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. Everything 086 did, in reverse: the six functions back to their texts before 086 byte for byte
-- (the hunks of 086 in reverse, md5-proven; plan_h_busy and plan_move_pieces back to 084's texts), the two triggers and
-- the three functions it added
-- dropped, the two FULL EXCLUDE of 072b rebuilt (md5 of their definitions proven), the column dropped, B-54 back.
-- It STOPS, with the list of trips, if an accepted overlap is in the base: the full EXCLUDE cannot be rebuilt over it
-- (move or end one trip of each pair, then run it again). The audit_log rows of the marks stay (history).
-- Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "086 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype; v_trg0 int; v_trg1 int; v_b54 int; v_list text;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = 'public.rt_vehicle_segments'::regclass AND attname = 'overlap_rts' AND NOT attisdropped)
     OR to_regprocedure('public.plan_h_accept_busy(jsonb,text,text,text)') IS NULL
     OR to_regprocedure('public.plan_seg_overlap_mark()') IS NULL
     OR to_regprocedure('public.plan_chk_seg_overlap()') IS NULL
     OR (${xdef('rt_v2_truck_once')}) IS DISTINCT FROM '${f.xGen.truck}'
     OR (${xdef('rt_v2_driver_once')}) IS DISTINCT FROM '${f.xGen.driver}' THEN
    RAISE EXCEPTION '086 rollback: 086 is not applied (column, functions or the partial EXCLUDE missing) - stop';
  END IF;
  SELECT count(*) INTO v_trg0 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  SELECT red_value INTO v_b54 FROM monitoring.checks WHERE id = 'B-54';
  IF v_b54 IS DISTINCT FROM v_trg0 THEN
    RAISE EXCEPTION '086 rollback: B-54 holds % but % triggers are enabled - stop, re-measure', v_b54, v_trg0;
  END IF;
  -- the pairs the FULL EXCLUDE would refuse (its own predicate and range): an accepted overlap, or a pair the partial
  -- rule let through beside one - named, never dropped in silence
  SELECT string_agg(DISTINCT ra.code || ' / ' || rb.code || ' (' || x.kind || ')', ', ') INTO v_list
    FROM (SELECT a.rt_id AS ra_id, b.rt_id AS rb_id, CASE WHEN a.truck_id = b.truck_id THEN 'truck' ELSE 'driver' END AS kind
            FROM public.rt_vehicle_segments a JOIN public.rt_vehicle_segments b ON b.id > a.id
           WHERE a.trip_type = 'OWNED' AND b.trip_type = 'OWNED' AND a.deleted_at IS NULL AND b.deleted_at IS NULL
             AND NOT a.rt_cancelled AND NOT b.rt_cancelled
             AND ((a.truck_id IS NOT NULL AND a.truck_id = b.truck_id) OR (a.driver_id IS NOT NULL AND a.driver_id = b.driver_id))
             AND tstzrange(a.from_at, greatest(a.from_at, a.to_at), '[)') && tstzrange(b.from_at, greatest(b.from_at, b.to_at), '[)')) x
    JOIN public.ct_round_trips ra ON ra.id = x.ra_id JOIN public.ct_round_trips rb ON rb.id = x.rb_id;
  IF v_list IS NOT NULL THEN
    RAISE EXCEPTION '086 rollback: trips that overlap are in the base, the full EXCLUDE cannot be rebuilt: % - stop (move or end one trip of each pair, then run again)', v_list;
  END IF;
${blocks}
  DROP TRIGGER plan_seg_overlap_verify ON public.rt_vehicle_segments;
  DROP TRIGGER plan_seg_overlap_mark ON public.rt_vehicle_segments;
  DROP FUNCTION public.plan_chk_seg_overlap();
  DROP FUNCTION public.plan_seg_overlap_mark();
  DROP FUNCTION public.plan_h_accept_busy(jsonb,text,text,text);
  -- the two EXCLUDE exactly as 072b made them, then the column
  ALTER TABLE public.rt_vehicle_segments DROP CONSTRAINT rt_v2_truck_once, DROP CONSTRAINT rt_v2_driver_once,
    ADD CONSTRAINT rt_v2_truck_once EXCLUDE USING gist (truck_id WITH =, tstzrange(from_at, greatest(from_at, to_at), '[)') WITH &&)
      WHERE (trip_type = 'OWNED' AND truck_id IS NOT NULL AND deleted_at IS NULL AND NOT rt_cancelled)
      DEFERRABLE INITIALLY DEFERRED,
    ADD CONSTRAINT rt_v2_driver_once EXCLUDE USING gist (driver_id WITH =, tstzrange(from_at, greatest(from_at, to_at), '[)') WITH &&)
      WHERE (trip_type = 'OWNED' AND driver_id IS NOT NULL AND deleted_at IS NULL AND NOT rt_cancelled)
      DEFERRABLE INITIALLY DEFERRED;
  ALTER TABLE public.rt_vehicle_segments DROP COLUMN overlap_rts;
  SELECT count(*) INTO v_trg1 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  IF v_trg1 <> v_trg0 - 2 THEN RAISE EXCEPTION '086 rollback proof: triggers % -> % (two less)', v_trg0, v_trg1; END IF;
  UPDATE monitoring.checks SET red_value = v_trg1 WHERE id = 'B-54';
  IF (${xdef('rt_v2_truck_once')}) IS DISTINCT FROM '${f.xLive.truck}'
     OR (${xdef('rt_v2_driver_once')}) IS DISTINCT FROM '${f.xLive.driver}' THEN
    RAISE EXCEPTION '086 rollback proof: the full deferred EXCLUDE of 072b is not back';
  END IF;
  RAISE NOTICE '086 ROLLBACK OK';
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '086_plan_busy_overlap_ok_rollback_dryrun.sql', name: 'DRY RUN 086 ROLLBACK',
  header: `-- 086 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-086.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "086 ROLLBACK OK" then ERROR: P0001: DRY RUN 086 ROLLBACK finished - EVERYTHING UNDONE ...
--   busy LIVE_BUSY, reseq LIVE_RESEQ`,
  epilogue: DRY.epilogue.replace('086 ran:', 'rollback ran:'),
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const f = facts(src);
  const rb = buildRollback(src);
  // the dry runs' headers name the md5 the run must end on (one fact each: PART 2 / PART 0 of the source)
  const gen = Object.fromEntries(f.gen.map((g) => [g.sig, g.m]));
  const dry = { ...DRY, header: DRY.header.replace('GEN_BUSY', gen[BUSY]).replace('GEN_RESEQ', gen[RESEQ]) };
  const rbDry = { ...RB_DRY, header: RB_DRY.header.replace('LIVE_BUSY', f.live[BUSY]).replace('LIVE_RESEQ', f.live[RESEQ]) };
  return { [DRY.target]: buildDryRun(src, dry), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, rbDry) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
