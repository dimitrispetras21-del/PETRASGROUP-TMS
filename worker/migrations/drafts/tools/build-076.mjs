// Generates the 076 dry run, rollback AND verify:
//   076_plan_board_speed.sql -> 076_plan_board_speed_dryrun.sql, _rollback.sql, _verify.sql
//   node worker/migrations/drafts/tools/build-076.mjs          (writes the three)
//   node worker/migrations/drafts/tools/build-076.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements; the rollback puts back EXACTLY 071's
// view, read from 071_plan_schema.sql (executed 22/10, the text production holds: md5 of its viewdef f7588271), never
// retyped; the verify checks the md5 the migration measured. tests/sql-076-drafts.test.js fails on any drift.
// ASCII in, ASCII out. Shapes as build-074a.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// 076 is a draft until the owner runs it; then it leaves drafts/ (CLAUDE.md rule 5) and DIR goes one up
export const DIR = path.resolve(HERE, '..');
const DONE = path.resolve(HERE, '..', '..');   // executed migrations (071)
export const SOURCE = '076_plan_board_speed.sql';
export const DRYRUN = '076_plan_board_speed_dryrun.sql';
export const ROLLBACK = '076_plan_board_speed_rollback.sql';
export const VERIFY = '076_plan_board_speed_verify.sql';
const OPEN = '\nDO $do$\n';
const CLOSE = '\nEND $do$;\n';

export function constants(src) {
  const old = /m_view_old CONSTANT text := '([0-9a-f]{32})';/.exec(src);
  const neu = /m_view_new CONSTANT text := '([0-9a-f]{32}|@MV)';/.exec(src);
  const tl = /t_list CONSTANT text\[\] := ARRAY\[([\s\S]*?)\];/.exec(src);
  if (!old || !neu || !tl) throw new Error(`${SOURCE}: m_view_old / m_view_new / t_list not found`);
  if (neu[1] === '@MV') throw new Error(`${SOURCE}: the new view md5 is not measured yet`);
  return { old: old[1], neu: neu[1], tables: [...tl[1].matchAll(/'([a-z_]+)'/g)].map((m) => m[1]) };
}

// 071's view, from 071's own file (the executed text), as CREATE OR REPLACE
export function view071() {
  const src = fs.readFileSync(path.join(DONE, '071_plan_schema.sql'), 'utf8');
  const a = src.indexOf('  CREATE VIEW public.v_rt_stop_state WITH (security_invoker = true) AS');
  const b = a < 0 ? -1 : src.indexOf('  FROM st;\n', a);
  if (a < 0 || b < 0) throw new Error('071_plan_schema.sql: v_rt_stop_state not found');
  return src.slice(a, b + '  FROM st;\n'.length).replace('  CREATE VIEW', '  CREATE OR REPLACE VIEW');
}

const rows = (into) => `SELECT md5(coalesce(string_agg(to_jsonb(v)::text, '|' ORDER BY v.stop_id), '')) INTO ${into} FROM public.v_rt_stop_state v;`;
const TRIGGERS = `(SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = c.relnamespace
      WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public')`;
const analyzed = (tables) => `(SELECT count(*) FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace AND c.reltuples >= 0
      AND c.relname IN (${tables.map((t) => `'${t}'`).join(', ')}))`;

export function buildDryRun(src) {
  const { neu, tables } = constants(src);
  const a = src.indexOf(OPEN);
  const b = src.lastIndexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) throw new Error(`${SOURCE}: the DO $do$ ... END $do$; block was not found`);
  const body = src.slice(a + OPEN.length, b);
  if (body.includes('$dry$')) throw new Error(`${SOURCE}: contains $dry$ - choose other tags`);
  return `-- 076 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-076.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND: edit the source and regenerate (tests/sql-076-drafts.test.js fails on any drift).
-- WHAT: 076's own DO block, statement for statement (guards, the view, ANALYZE, proofs), then a read of the result,
--   ENDING WITH A DELIBERATE ERROR: no row and no definition is kept. One trace stays by PostgreSQL's design:
--   ANALYZE writes the table size estimates of pg_class (relpages / reltuples) in place, outside the transaction;
--   they only inform the planner (no row, no answer changes) - the statistics themselves (pg_statistic) are undone.
-- WHEN: with the owner's yes, BEFORE ${SOURCE}. Same 5 s lock timeout as 076.
-- EXPECTED (the red ERROR is deliberate): a NOTICE "076 OK: ..." and then
--   ERROR: P0001: DRY RUN 076 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  076 ran:
--   view new yes, analyzed ${tables.length}, triggers <T>, B-54 <T>   (the block itself proved the rows before = after)
--   Anything else (an ERROR from one of 076's guards or proofs): do NOT run 076, copy the message to the coordinator.

DO $dry$
DECLARE
  res text;
BEGIN
  -- ===== ${SOURCE}, verbatim =====
${body}
END;
  -- ===== what it did =====
  res := format('076 ran: view new %s, analyzed %s, triggers %s, B-54 %s',
    CASE WHEN md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true)) = '${neu}' THEN 'yes' ELSE 'no' END,
    ${analyzed(tables)},
    ${TRIGGERS},
    (SELECT red_value FROM monitoring.checks WHERE id = 'B-54'));
  RAISE EXCEPTION 'DRY RUN 076 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  %', res;
END
$dry$;
`;
}

export function buildRollback(src) {
  const { old, neu } = constants(src);
  return `-- 076 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-076.mjs from ${SOURCE} and 071_plan_schema.sql.
-- DO NOT EDIT BY HAND (071's view below is read from 071's file; tests/sql-076-drafts.test.js fails on drift).
-- WHAT: v_rt_stop_state back to 071's text (md5 ${old}), proved on the live rows (the same rows before and
--   after). The statistics ANALYZE wrote stay: they change no row and no answer, only the planner's estimates.
-- Only with an explicit yes. ASCII only. ONE DO block.
-- EXPECTED: NOTICE "076 ROLLBACK OK ..." and ONE row "076 ROLLED BACK | ${old} | <T> | <T>".

DO $do$
DECLARE
  v_rows0 text; v_rows1 text; v_acl text; v_trg0 int; v_trg1 int;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true)) <> '${neu}' THEN
    RAISE EXCEPTION '076 rollback: v_rt_stop_state is not 076''s view (md5 %) - nothing to undo, or it changed since',
      md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true));
  END IF;
  SELECT count(*) INTO v_trg0 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace
   WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  ${rows('v_rows0')}
  SELECT coalesce(c.relacl::text, '-') INTO v_acl FROM pg_class c WHERE c.oid = 'public.v_rt_stop_state'::regclass;

${view071()}
  IF md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true)) <> '${old}' THEN
    RAISE EXCEPTION '076 rollback proof: v_rt_stop_state is not 071''s text (md5 %)', md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true));
  END IF;
  ${rows('v_rows1')}
  IF v_rows1 <> v_rows0 THEN RAISE EXCEPTION '076 rollback proof: v_rt_stop_state answers other rows'; END IF;
  IF (SELECT coalesce(c.relacl::text, '-') FROM pg_class c WHERE c.oid = 'public.v_rt_stop_state'::regclass) <> v_acl THEN
    RAISE EXCEPTION '076 rollback proof: v_rt_stop_state lost its grants';
  END IF;
  SELECT count(*) INTO v_trg1 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace
   WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  IF v_trg1 <> v_trg0 THEN RAISE EXCEPTION '076 rollback proof: trigger count % -> %', v_trg0, v_trg1; END IF;
  PERFORM pg_notify('pgrst', 'reload schema');
  RAISE NOTICE '076 ROLLBACK OK: v_rt_stop_state back to 071 (rows equal); triggers % unchanged', v_trg1;
END $do$;

SELECT CASE WHEN md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true)) = '${old}' THEN '076 ROLLED BACK' ELSE '076 STILL IN PLACE' END AS result,
       md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true)) AS view_md5,
       ${TRIGGERS} AS public_triggers,
       (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') AS b54_red_value;
`;
}

export function buildVerify(src) {
  const { neu, tables } = constants(src);
  return `-- 076 VERIFY - GENERATED by worker/migrations/drafts/tools/build-076.mjs from ${SOURCE}. Read-only, one row.
-- DO NOT EDIT BY HAND (the md5 below is the migration's own; tests/sql-076-drafts.test.js fails on drift).
-- EXPECTED after 076: view_in_place = true, analyzed = ${tables.length}, b54_matches = true.
SELECT md5(pg_get_viewdef('public.v_rt_stop_state'::regclass, true)) = '${neu}' AS view_in_place,
       ${analyzed(tables)} AS analyzed,
       ${TRIGGERS} = (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') AS b54_matches;
`;
}

// realpath: through a symlink path.resolve would differ and --check could not fail (principle 1; found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const source = path.join(DIR, SOURCE);
  if (!fs.existsSync(source)) { console.error('no source: ' + SOURCE); process.exit(1); }
  const src = fs.readFileSync(source, 'utf8');
  let drift = false;
  for (const [name, text] of [[DRYRUN, buildDryRun(src)], [ROLLBACK, buildRollback(src)], [VERIFY, buildVerify(src)]]) {
    const target = path.join(DIR, name);
    if (check) {
      const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === text;
      if (!same) { console.error('drift: ' + name); drift = true; }
    } else {
      fs.writeFileSync(target, text);
      console.log('wrote ' + name);
    }
  }
  if (check && !drift) console.log('0 drift');
  process.exitCode = drift ? 1 : 0;
}
