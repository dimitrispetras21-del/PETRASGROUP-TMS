// Generates the dry run, the rollback and the rollback's dry run of 102 FROM its source (102_plan_drafts.sql):
//   node worker/migrations/drafts/tools/build-102.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-102.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback drops EXACTLY what
// 102 created - the function lists are read from the source's own c_acts / c_helpers, never a hand copy.
// tests/sql-102-drafts.test.js fails on drift; tms-auditor/test/plan-102.test.mjs runs them on a PGlite copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// drafts/ until the owner runs 102, then one up (CLAUDE.md rule 5): the builder stays here
const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = '102_plan_drafts.sql';
export const DIR = fs.existsSync(path.join(DRAFTS, SOURCE)) ? DRAFTS : path.resolve(DRAFTS, '..');
export const ROLLBACK = '102_plan_drafts_rollback.sql';

// the source's two lists, as written in its DECLARE (one place)
export function facts(src) {
  const list = (k) => {
    const m = new RegExp(`^ {2}${k} CONSTANT text\\[\\] := ARRAY\\[([\\s\\S]*?)\\];$`, 'm').exec(src);
    if (!m) throw new Error(`${SOURCE}: ${k} not found`);
    return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]);
  };
  const acts = list('c_acts'), helpers = list('c_helpers');
  if (acts.length !== 8 || helpers.length !== 9) throw new Error(`${SOURCE}: expected 8 acts and 9 helpers, got ${acts.length} / ${helpers.length}`);
  return { acts, helpers };
}

const EPI = `  res := format('102 ran: tables %s, acts %s, helpers %s, drafts_table %s, policies %s, triggers %s, b54 %s',
    (SELECT count(*) FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relname IN ('plan_drafts', 'plan_draft_pieces')),
    (SELECT count(*) FROM pg_proc WHERE pronamespace = 'public'::regnamespace AND proname IN ('plan_drafts_read', 'plan_draft_history',
       'plan_draft_create', 'plan_draft_update', 'plan_draft_pieces', 'plan_draft_move', 'plan_draft_delete', 'plan_draft_realize')),
    (SELECT count(*) FROM pg_proc WHERE pronamespace = 'public'::regnamespace AND (proname LIKE 'plan\\_h\\_draft\\_%' OR proname = 'plan_draft_no_delete')),
    (SELECT count(*) FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relname = 'plan_drafts'),
    (SELECT count(*) FROM pg_policies WHERE schemaname = 'public' AND tablename IN ('plan_drafts', 'plan_draft_pieces')),
    (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = c.relnamespace
      WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public'),
    (SELECT red_value FROM monitoring.checks WHERE id = 'B-54'));`;

export const DRY = {
  source: SOURCE, target: '102_plan_drafts_dryrun.sql', name: 'DRY RUN 102',
  header: `-- 102 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-102.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND (tests/sql-102-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056). ASCII only. AFTER 15:00, BEFORE 102_plan_drafts.sql.
-- EXPECTED (the red ERROR is deliberate): NOTICE "102 OK: ..." and then
--   ERROR: P0001: DRY RUN 102 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  102 ran:
--   tables 2, acts 8, helpers 9, drafts_table 1, policies 2, triggers <B-54 + 2>, b54 <the same number>
--   Anything else (an ERROR from one of 102's guards or proofs): do NOT run 102, copy the message to the coordinator.`,
  epilogue: EPI,
};

export function buildRollback(src) {
  const f = facts(src);
  const q = (a) => a.map((s) => `'${s}'`).join(', ');
  return `-- 102 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-102.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. Everything 102 created, dropped: the 8 acts and 9 helpers, the state view, the two tables (their
-- triggers and policies go with them), and B-54 back to the trigger count before 102. No CASCADE: an object that
-- depends on them stops it and nothing is kept.
-- ORDER: the front end reverted and the Worker without /plan/drafts FIRST (after this, its routes answer 500).
-- It STOPS (nothing changed) while a LIVE draft exists: realize or delete them first. Realized and deleted drafts are
-- dropped with the tables; their audit_log rows STAY (who / when / what), and the loads they made stay as they are.
-- Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "102 ROLLBACK OK".
DO $do$
DECLARE
  c_acts CONSTANT text[] := ARRAY[${q(f.acts)}];
  c_helpers CONSTANT text[] := ARRAY[${q(f.helpers)}];
  v_sig text; v_live bigint; v_trg0 int; v_trg1 int; v_k bigint;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  PERFORM set_config('search_path', 'public', true);
  IF to_regclass('public.plan_drafts') IS NULL OR to_regclass('public.plan_draft_pieces') IS NULL THEN
    RAISE EXCEPTION '102 rollback: plan_drafts is not there - 102 has not run, nothing to reverse';
  END IF;
  FOREACH v_sig IN ARRAY c_acts || c_helpers LOOP
    IF to_regprocedure(v_sig) IS NULL THEN RAISE EXCEPTION '102 rollback: % is missing - not the 102 state, stop', v_sig; END IF;
  END LOOP;
  SELECT count(*) INTO v_live FROM public.plan_drafts WHERE deleted_at IS NULL AND realized_at IS NULL;
  IF v_live <> 0 THEN
    RAISE EXCEPTION '102 rollback: % live draft(s) - realize or delete them first (nothing changed)', v_live;
  END IF;
  SELECT count(*) INTO v_trg0 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace
   WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  IF NOT EXISTS (SELECT 1 FROM monitoring.checks WHERE id = 'B-54' AND red_value = v_trg0) THEN
    RAISE EXCEPTION '102 rollback: B-54 red_value is not the live trigger count % - re-measure', v_trg0;
  END IF;

  -- the functions first (plan_h_draft_lock returns the plan_drafts row type), the trigger function after its tables
  FOREACH v_sig IN ARRAY c_acts || c_helpers LOOP
    IF v_sig <> 'public.plan_draft_no_delete()' THEN EXECUTE 'DROP FUNCTION ' || v_sig; END IF;
  END LOOP;
  DROP VIEW public.v_plan_draft_piece_state;
  DROP TABLE public.plan_draft_pieces;
  DROP TABLE public.plan_drafts;
  DROP FUNCTION public.plan_draft_no_delete();

  FOREACH v_sig IN ARRAY c_acts || c_helpers LOOP
    IF to_regprocedure(v_sig) IS NOT NULL THEN RAISE EXCEPTION '102 rollback proof: % is still there', v_sig; END IF;
  END LOOP;
  IF to_regclass('public.plan_drafts') IS NOT NULL OR to_regclass('public.plan_draft_pieces') IS NOT NULL
     OR to_regclass('public.v_plan_draft_piece_state') IS NOT NULL THEN
    RAISE EXCEPTION '102 rollback proof: a table or the view is still there';
  END IF;
  SELECT count(*) INTO v_trg1 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace
   WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  IF v_trg1 <> v_trg0 - 2 THEN RAISE EXCEPTION '102 rollback proof: trigger count % -> % (expected -2)', v_trg0, v_trg1; END IF;
  UPDATE monitoring.checks SET red_value = v_trg1 WHERE id = 'B-54' AND red_value = v_trg0;
  GET DIAGNOSTICS v_k = ROW_COUNT;
  IF v_k <> 1 THEN RAISE EXCEPTION '102 rollback: B-54 not updated (% rows)', v_k; END IF;
  PERFORM pg_notify('pgrst', 'reload schema');
  RAISE NOTICE '102 ROLLBACK OK';
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '102_plan_drafts_rollback_dryrun.sql', name: 'DRY RUN 102 ROLLBACK',
  header: `-- 102 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-102.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "102 ROLLBACK OK" then ERROR: P0001: DRY RUN 102 ROLLBACK finished - EVERYTHING UNDONE ...
--   tables 0, acts 0, helpers 0, drafts_table 0, policies 0, triggers <B-54 before 102>, b54 <the same number>`,
  epilogue: EPI.replace('102 ran:', 'rollback ran:'),
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const rb = buildRollback(src);
  return { [DRY.target]: buildDryRun(src, DRY), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, RB_DRY) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
