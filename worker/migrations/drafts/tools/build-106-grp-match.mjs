// worker/migrations/drafts/tools/build-106-grp-match.mjs - run: node worker/migrations/drafts/tools/build-106-grp-match.mjs
// Generates the two 106 dry runs from their sources: the source DO block verbatim, with its closing NOTICE turned
// into a DELIBERATE ERROR, so ONE statement does everything and the error undoes it (lesson 056).
// tests/sql-106-drafts.test.js regenerates in memory and fails on any drift: edit the source, then rerun this.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DRAFTS = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// drafts/ until the owner runs a file, then one up (CLAUDE.md rule 5): 106 ran 8/11, so its files are one up now
export const dirOf = (f) => (fs.existsSync(path.join(DRAFTS, f)) ? DRAFTS : path.resolve(DRAFTS, '..'));
const SPECS = [
  { src: '106_grp_match_converge.sql', out: '106_grp_match_converge_dryrun.sql', tag: 'DRY RUN 106',
    notice: "  RAISE NOTICE '106 OK: #% matched to #% (%), round trip % unchanged, partly matched groups 0', member_id, imp_id, imp_legacy, rt;",
    expected: '#464 would match #505 (recR5tH3Mw2nLFX0n), round trip 225 unchanged, partly matched groups 0',
    error: "  RAISE EXCEPTION 'DRY RUN 106 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  #% would match #% (%), round trip % unchanged, partly matched groups 0', member_id, imp_id, imp_legacy, rt;" },
  { src: '106_grp_match_converge_rollback.sql', out: '106_grp_match_converge_rollback_dryrun.sql', tag: 'DRY RUN 106 ROLLBACK',
    notice: "  RAISE NOTICE '106 rolled back: #464 matched_import_id NULL again, round trip 225 unchanged';",
    expected: '#464 would be NULL again, round trip 225 unchanged',
    error: "  RAISE EXCEPTION 'DRY RUN 106 ROLLBACK finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  #464 would be NULL again, round trip 225 unchanged';" },
];

export function build(spec, srcText) {
  const start = srcText.indexOf('DO $');
  if (start < 0) throw new Error(`${spec.src}: no DO block`);
  const body = srcText.slice(start);
  if (body.split(spec.notice).length !== 2) throw new Error(`${spec.src}: the closing NOTICE is not there exactly once`);
  return [
    `-- ${spec.tag} - GENERATED by worker/migrations/drafts/tools/build-106-grp-match.mjs from ${spec.src}.`,
    '-- DO NOT EDIT BY HAND: edit the source and regenerate (tests/sql-106-drafts.test.js fails on any drift).',
    '-- WHAT: the source DO block verbatim, its closing NOTICE turned into a DELIBERATE ERROR: ONE DO block = ONE',
    '--   statement, so the error undoes everything (lesson 056). WHEN: after 15:00, right before the source. ASCII only.',
    `-- EXPECTED (the red ERROR is deliberate): ERROR: P0001: ${spec.tag} finished - EVERYTHING UNDONE, nothing kept.`,
    `--   The block ran to its end  ||  ${spec.expected}`,
    '--   Anything else (an ERROR from a guard or proof of the source): do NOT run the source, copy the message.',
    '',
    body.replace(spec.notice, spec.error),
  ].join('\n');
}

export { SPECS, DRAFTS };

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  for (const spec of SPECS) {
    const out = build(spec, fs.readFileSync(path.join(dirOf(spec.src), spec.src), 'utf8'));
    fs.writeFileSync(path.join(dirOf(spec.out), spec.out), out);
    console.log('wrote', spec.out);
  }
}
