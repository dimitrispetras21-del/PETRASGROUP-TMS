const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;

// 071's two CHECKs as written there (the rollback puts them back)
export function checks071() {
  const s = fs.readFileSync(path.resolve(HERE, '..', '..', '071_plan_schema.sql'), 'utf8');
  const a = s.indexOf('    CONSTRAINT shipments_shape CHECK (');
  const b = s.indexOf('    CONSTRAINT shipments_pallets CHECK');
  if (a < 0 || b < a) throw new Error('071: shipments_shape not found');
  const shape = s.slice(a + '    CONSTRAINT shipments_shape '.length, b).replace(/,\n$/, '');
  if (!/pallets IS NOT NULL/.test(shape) || !s.includes('    CONSTRAINT pieces_pallets CHECK (pallets > 0),')) throw new Error('071: the CHECKs moved');
  return { shape, pieces: 'CHECK (pallets > 0)' };
}

// 073's text of a view, comments stripped (a view keeps no comment; 080 embeds the same, the test holds them equal)
export function view073(head) {
  const s = fs.readFileSync(path.resolve(HERE, '..', '..', '073_plan_money.sql'), 'utf8');
  const i = s.indexOf(head);
  if (i < 0) throw new Error('073: ' + head + ' not found');
  const out = [];
  for (const l of s.slice(i + head.length).split('\n')) {
    const code = l.split('--')[0].replace(/\s+$/, '');
    if (code.trim()) out.push(code);
    if (code.endsWith(';')) break;
  }
  return out.join('\n').replace(/;$/, '');
}
export const VIEW_HEADS = { v_v5_0: 'CREATE VIEW public.ct_v_v5_revenue AS\n', v_rev_0: 'CREATE OR REPLACE VIEW public.ct_v_rt_revenue AS\n',
  v_pnl_0: 'CREATE OR REPLACE VIEW public.ct_v_rt_pnl AS\n' };

// The facts of the source, read once: the constant block (hunks + 073's views), the live md5 (PART 0) and the
// generated md5 (PART 2)
export function facts(src) {
  const a = src.indexOf('  -- the function hunks'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the constant block was not found`);
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part2 = src.slice(src.indexOf('===== PART 2'), src.indexOf('===== PART 3'));
  const live = Object.fromEntries([...part0.matchAll(/\('(public\.[a-z_]+\([a-z,\[\]]*\))', '([0-9a-f]{32})'\)/g)].map((m) => [m[1], m[2]]));
  const gen = [...part2.matchAll(/\('(public\.[a-z_]+\([a-z,\[\]]*\))', ARRAY\[([a-z0-9_, ]+)\], ARRAY\[([a-z0-9_, ]+)\], '([0-9a-f]{32})'\)/g)]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (SIGS.some((s) => !live[s]) || gen.length !== SIGS.length || gen.some((g) => !live[g.sig] || g.a.length !== g.b.length)) {
    throw new Error(`${SOURCE}: PART 0 / PART 2 lists are not the ${SIGS.length} functions with their hunks`);
  }
  const views = Object.fromEntries(Object.keys(VIEW_HEADS).map((k) => {
    const m = new RegExp(`  ${k} CONSTANT text := \\$v\\$([\\s\\S]*?)\\$v\\$;`).exec(src);
    if (!m) throw new Error(`${SOURCE}: ${k} not found`);
    return [k, m[1]];
  }));
  return { consts: src.slice(a, b), live, gen, views };
}

