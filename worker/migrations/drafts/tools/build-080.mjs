// Generates the dry run and the rollback of 080 FROM its source (080_plan_optional_price_pallets.sql):
//   node worker/migrations/drafts/tools/build-080.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-080.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY what
// 080 applied - it reads the hunks, the md5 before / after, 073's view texts and 071's two CHECKs from their sources,
// never a hand copy. tests/sql-080-drafts.test.js fails on drift.
