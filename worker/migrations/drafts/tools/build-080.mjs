export function buildRollback(src) {
  const f = facts(src);
  const c = checks071();
  for (const [k, head] of Object.entries(VIEW_HEADS)) {
    if (f.views[k] !== view073(head)) throw new Error(`${SOURCE}: ${k} is not 073's text`);
  }
  const loop = f.gen.map((g) => `      ('${g.sig}', ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}], '${g.m}', '${f.live[g.sig]}')`).join(',\n');
  return `-- 080 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-080.mjs from 080_plan_optional_price_pallets.sql.
-- DO NOT EDIT BY HAND. The 7 functions back to their live text of 28/10 byte for byte (080's hunks in reverse,
-- md5-proven), the 3 money views back to 073's text (ct_v_rt_pnl and ct_v_rt_revenue dropped and made again: CREATE OR
-- REPLACE cannot remove their new last column; their rights are read first and given back), 071's two CHECKs and NOT
-- NULL back, B-100 out of the catalog (results removed, open incidents closed). REFUSES while a national shipment or a
-- piece has unknown pallets (071 would refuse them): write the pallets first (B-100 lists the live ones). Prices left
-- NULL stay NULL (the user's data; B-90 lists them). Only with an explicit yes, after 15:00. ASCII. ONE DO block.
-- EXPECTED: NOTICE "080 ROLLBACK OK".
DO $do$
DECLARE
${f.consts}  v_g record; v_h record; v_new text; v_k int; p pg_proc%rowtype; v_gr text[]; v_x text;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF NOT EXISTS (SELECT 1 FROM monitoring.checks WHERE id = 'B-100')
     OR (SELECT attnotnull FROM pg_attribute WHERE attrelid = 'public.shipment_pieces'::regclass AND attname = 'pallets') THEN
    RAISE EXCEPTION '080 rollback: 080 is not applied';
  END IF;
  SELECT (SELECT count(*) FROM public.shipments WHERE order_stop_id IS NULL AND pallets IS NULL)
       + (SELECT count(*) FROM public.shipment_pieces WHERE pallets IS NULL) INTO v_k;
  IF v_k <> 0 THEN
    RAISE EXCEPTION '080 rollback: % shipment / piece row(s) have unknown pallets - write their pallets first (B-100 lists the live ones)', v_k;
  END IF;
  -- the views that read ct_v_rt_revenue / ct_v_rt_pnl are only each other (measured 28/10): another one would be lost
  IF EXISTS (SELECT 1 FROM pg_depend d JOIN pg_rewrite w ON w.oid = d.objid JOIN pg_class c ON c.oid = w.ev_class
              WHERE d.refobjid IN ('public.ct_v_rt_revenue'::regclass, 'public.ct_v_rt_pnl'::regclass)
                AND c.oid NOT IN ('public.ct_v_rt_revenue'::regclass, 'public.ct_v_rt_pnl'::regclass)) THEN
    RAISE EXCEPTION '080 rollback: a view other than ct_v_rt_pnl reads ct_v_rt_revenue / ct_v_rt_pnl - stop, re-measure';
  END IF;

  -- 1. the 7 functions: 080's hunks out of the LIVE text (080's PART 2 md5), checked against 080's PART 0 md5
  FOR v_g IN SELECT * FROM (VALUES
${loop}) g(sig, b, a, m_now, m_live) LOOP
    SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure(v_g.sig);
    IF md5(p.prosrc) <> v_g.m_now THEN
      RAISE EXCEPTION '080 rollback: % is not the text 080 wrote (md5 %) - stop', v_g.sig, md5(p.prosrc);
    END IF;
    v_new := p.prosrc;
    FOR v_h IN SELECT * FROM unnest(v_g.b, v_g.a) h(b, a) LOOP
      IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
        RAISE EXCEPTION '080 rollback: a hunk of 080 is not in % exactly once - stop', v_g.sig;
      END IF;
      v_new := replace(v_new, v_h.b, v_h.a);
    END LOOP;
    IF md5(v_new) <> v_g.m_live THEN
      RAISE EXCEPTION '080 rollback: % would not be its live text (md5 %)', v_g.sig, md5(v_new);
    END IF;
    EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE %s %s %s SET search_path = public AS %L',
      split_part(v_g.sig, '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
      (SELECT lanname FROM pg_language WHERE oid = p.prolang),
      CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
      CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  END LOOP;

  -- 2. the money views back to 073's text; the rights of the two that are dropped are read first and given back
  SELECT coalesce(array_agg(format('GRANT %s ON %s TO %s%s', a.privilege_type, c.oid::regclass,
                                   CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(a.grantee)) END,
                                   CASE WHEN a.is_grantable THEN ' WITH GRANT OPTION' ELSE '' END)
                            ORDER BY c.oid::regclass::text, a.grantee, a.privilege_type), '{}')
    INTO v_gr
    FROM pg_class c CROSS JOIN LATERAL aclexplode(c.relacl) a
   WHERE c.oid IN ('public.ct_v_rt_revenue'::regclass, 'public.ct_v_rt_pnl'::regclass) AND a.grantee <> c.relowner;
  DROP VIEW public.ct_v_rt_pnl;
  DROP VIEW public.ct_v_rt_revenue;
  EXECUTE 'CREATE OR REPLACE VIEW public.ct_v_v5_revenue AS ' || v_v5_0;
  EXECUTE 'CREATE VIEW public.ct_v_rt_revenue AS ' || v_rev_0;
  EXECUTE 'CREATE VIEW public.ct_v_rt_pnl AS ' || v_pnl_0;
  FOREACH v_x IN ARRAY v_gr LOOP EXECUTE v_x; END LOOP;

  -- 3. 071's two CHECKs and NOT NULL
  ALTER TABLE public.shipments DROP CONSTRAINT shipments_shape;
  ALTER TABLE public.shipments ADD CONSTRAINT shipments_shape ${c.shape};
  ALTER TABLE public.shipment_pieces DROP CONSTRAINT pieces_pallets;
  ALTER TABLE public.shipment_pieces ADD CONSTRAINT pieces_pallets ${c.pieces};
  ALTER TABLE public.shipment_pieces ALTER COLUMN pallets SET NOT NULL;

  -- 4. B-100 out of the catalog (as 074b's rollback)
  UPDATE monitoring.incidents SET state = 'resolved', resolved_verified_at = clock_timestamp(),
         state_changed_by = '080 rollback (check removed)', state_changed_at = clock_timestamp()
   WHERE state IN ('new', 'confirmed', 'recurred')
     AND (check_id = 'B-100' OR incident_key IN ('MECH:check:B-100', 'MECH:stale:B-100'));
  DELETE FROM monitoring.results WHERE check_id = 'B-100';
  DELETE FROM monitoring.checks WHERE id = 'B-100';

  -- 5. proofs: the views read back as 073's, the functions as before 080
  FOR v_g IN SELECT * FROM (VALUES ('ct_v_v5_revenue', v_v5_0), ('ct_v_rt_revenue', v_rev_0), ('ct_v_rt_pnl', v_pnl_0)) g(v, t) LOOP
    EXECUTE format('CREATE TEMP VIEW t080r_%s AS %s', v_g.v, v_g.t);
    IF pg_get_viewdef(format('pg_temp.t080r_%s', v_g.v)::regclass) IS DISTINCT FROM pg_get_viewdef(format('public.%s', v_g.v)::regclass) THEN
      RAISE EXCEPTION '080 rollback proof: public.% is not 073''s view', v_g.v;
    END IF;
    EXECUTE format('DROP VIEW pg_temp.t080r_%s', v_g.v);
  END LOOP;
  IF EXISTS (SELECT 1 FROM (VALUES
${f.gen.map((g) => `      ('${g.sig}', '${f.live[g.sig]}')`).join(',\n')}) g(sig, m) WHERE ${md5Of('x').replace("'x'::regprocedure", 'to_regprocedure(g.sig)')} <> g.m) THEN
    RAISE EXCEPTION '080 rollback proof: a function is not back to its live text';
  END IF;
  RAISE NOTICE '080 ROLLBACK OK';
END $do$;
`;
}

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  return { [FILES[0]]: buildDryRun(src, DRY), [FILES[1]]: buildRollback(src) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
