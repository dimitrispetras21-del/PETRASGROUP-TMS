// Generates the dry run, the rollback and the rollback's dry run of 088 FROM its source (088_plan_split_leave_by.sql):
//   node worker/migrations/drafts/tools/build-088.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-088.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 088 applied - it reads them (and the md5 before / after) from the source, never a hand copy.
// tests/sql-088-drafts.test.js fails on drift; tms-auditor/test/plan-088.test.mjs runs them on the production-shaped copy.
import fs from 'node:fs';
