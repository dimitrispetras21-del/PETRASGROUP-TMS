// Generates the dry run, the rollback, the rollback's dry run and the verify of 099 FROM its source
// (099_plan_transfer.sql):
//   node worker/migrations/drafts/tools/build-099.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-099.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements; the rollback and verify read the md5
// of plan_transfer from the source (PART 3's measured text), never a hand copy. 099 creates (a function, a column, one
// place) and patches nothing: its rollback drops exactly those, refused while any transfer exists.
// tests/sql-099-drafts.test.js fails on drift; tms-auditor/test/plan-099.test.mjs runs them on the production-shaped copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// drafts/ until the owner runs 099, then one up (CLAUDE.md rule 5): the builder stays here
const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = '099_plan_transfer.sql';
export const DIR = fs.existsSync(path.join(DRAFTS, SOURCE)) ? DRAFTS : path.resolve(DRAFTS, '..');
export const ROLLBACK = '099_plan_transfer_rollback.sql';
export const VERIFY = '099_plan_transfer_verify.sql';
export const SIG = 'public.plan_transfer(jsonb,text,text)';
const FN_MD5 = `(SELECT md5(prosrc) FROM pg_proc WHERE oid = to_regprocedure('${SIG}'))`;
const N_PLACE = `(SELECT count(*) FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'rt_stops'
      AND column_name = 'transfer_place')`;
const ANY_TRANSFER = `EXISTS (SELECT 1 FROM public.rt_stops WHERE transfer_reason IS NOT NULL OR transfer_from_stop_id IS NOT NULL
               OR transfer_waits OR transfer_place IS NOT NULL)`;

export function facts(src) {
  const fn = /m_fn CONSTANT text := '([0-9a-f]{32})';/.exec(src);
  if (!fn) throw new Error(`${SOURCE}: m_fn is not measured`);
  const a = src.indexOf('AS $f$'), b = src.indexOf('$f$;', a);
  if (a < 0 || b < 0) throw new Error(`${SOURCE}: the function body was not found`);
  return { fn: fn[1], body: src.slice(a + 'AS $f$'.length, b) };
}

const epilogue = (label) => `  res := format('${label} plan_transfer %s, transfer_place %s, transfer point %s',
    coalesce(${FN_MD5}, 'none'),
    ${N_PLACE},
    (SELECT count(*) FROM public.locations WHERE legacy_id = 'v5_transfer_point'));`;

export function dryPair(src) {
  return {
    source: SOURCE, target: '099_plan_transfer_dryrun.sql', name: 'DRY RUN 099',
    header: `-- 099 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-099.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND (tests/sql-099-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056). ASCII only.
-- EXPECTED (the red ERROR is deliberate): NOTICE "099 OK: plan_transfer (service_role only), rt_stops.transfer_place,
--   the place TRANSFER POINT (id <N>); triggers <T>" and then
--   ERROR: P0001: DRY RUN 099 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  099 ran:
--   plan_transfer ${facts(src).fn}, transfer_place 1, transfer point 1
--   Anything else (an ERROR from one of 099's guards or proofs, e.g. "098 first"): do NOT run 099, copy the message to
--   the coordinator.`,
    epilogue: epilogue('099 ran:'),
  };
}

export function buildRollback(src) {
  const f = facts(src);
  return `-- 099 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-099.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. Drops what 099 created: plan_transfer (only the text 099 wrote, md5 ${f.fn}),
-- rt_stops.transfer_place, the place TRANSFER POINT. REFUSED while any stop holds a transfer value (a transfer written
-- by plan_transfer would lose its text, and the place its stops): move those loads back first. Run BEFORE 098's
-- rollback. Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "099 ROLLBACK OK".
DO $do$
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF ${FN_MD5} IS DISTINCT FROM '${f.fn}' THEN
    RAISE EXCEPTION '099 rollback: plan_transfer is not the text 099 wrote (md5 %) - nothing to undo, or it changed since', ${FN_MD5};
  END IF;
  IF ${ANY_TRANSFER} THEN
    RAISE EXCEPTION '099 rollback: a stop holds a transfer value - move those loads back first, nothing changed';
  END IF;
  IF EXISTS (SELECT 1 FROM public.rt_stops s JOIN public.locations l ON l.id = s.location_id WHERE l.legacy_id = 'v5_transfer_point') THEN
    RAISE EXCEPTION '099 rollback: a stop stands on the place TRANSFER POINT - nothing changed';
  END IF;
  DROP FUNCTION public.plan_transfer(jsonb,text,text);
  ALTER TABLE public.rt_stops DROP COLUMN transfer_place;
  DELETE FROM public.locations WHERE legacy_id = 'v5_transfer_point';
  IF to_regprocedure('${SIG}') IS NOT NULL OR ${N_PLACE} <> 0
     OR EXISTS (SELECT 1 FROM public.locations WHERE legacy_id = 'v5_transfer_point') THEN
    RAISE EXCEPTION '099 rollback proof: plan_transfer, transfer_place or the place is still there';
  END IF;
  PERFORM pg_notify('pgrst', 'reload schema');
  RAISE NOTICE '099 ROLLBACK OK';
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '099_plan_transfer_rollback_dryrun.sql', name: 'DRY RUN 099 ROLLBACK',
  header: `-- 099 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-099.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "099 ROLLBACK OK" then ERROR: P0001: DRY RUN 099 ROLLBACK finished - EVERYTHING UNDONE ...
--   rollback ran: plan_transfer none, transfer_place 0, transfer point 0`,
  epilogue: epilogue('rollback ran:'),
};

export function buildVerify(src) {
  const f = facts(src);
  return `-- 099 VERIFY - GENERATED by worker/migrations/drafts/tools/build-099.mjs from ${SOURCE}. Read only (SELECT), one row.
-- DO NOT EDIT BY HAND (the md5 below is the migration's own; tests/sql-099-drafts.test.js fails on drift).
-- EXPECTED right after 099: applied = '099 in place', rights = service_role only, transfer_place 1, transfer_point 1,
--   transfers 0, waiting_at_point 0, text_points 0, b54_matches true.
--   After the Worker and the screens: transfers = the points where a truck handed loads over; waiting_at_point = those
--   that say "waits there"; text_points = those written as free text.
SELECT CASE WHEN ${FN_MD5} = '${f.fn}' THEN '099 in place' ELSE '099 NOT APPLIED' END AS applied,
       (SELECT proacl::text = '{postgres=X/postgres,service_role=X/postgres}' FROM pg_proc WHERE oid = to_regprocedure('${SIG}')) AS rights,
       ${N_PLACE} AS transfer_place,
       (SELECT count(*) FROM public.locations WHERE legacy_id = 'v5_transfer_point' AND deleted_at IS NULL) AS transfer_point,
       (SELECT count(*) FROM public.rt_stops WHERE transfer_reason IS NOT NULL AND deleted_at IS NULL) AS transfers,
       (SELECT count(*) FROM public.rt_stops WHERE transfer_waits AND deleted_at IS NULL) AS waiting_at_point,
       (SELECT count(*) FROM public.rt_stops WHERE transfer_place IS NOT NULL AND deleted_at IS NULL) AS text_points,
       (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = c.relnamespace
         WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public') = (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') AS b54_matches;
`;
}

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const rb = buildRollback(src);
  return {
    [dryPair(src).target]: buildDryRun(src, dryPair(src)),
    [ROLLBACK]: rb,
    [RB_DRY.target]: buildDryRun(rb, RB_DRY),
    [VERIFY]: buildVerify(src),
  };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
