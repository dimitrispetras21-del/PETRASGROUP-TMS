// Generates the dry run, the rollback and the rollback's dry run of 093 FROM its source (093_plan_hours_relaxed.sql):
//   node worker/migrations/drafts/tools/build-093.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-093.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 093 applied - it reads them (and the md5 before / after) from the source, never a hand copy. The shape is
// 092's (build-092.mjs); the rollback also drops the two functions 093 creates, and first proves that no live trip or
// leg holds an order the restored rules would refuse (093 allowed it: the old rules would refuse its next write).
// tests/sql-093-drafts.test.js fails on drift; tms-auditor/test/plan-093.test.mjs runs them on the production-shaped copy.
