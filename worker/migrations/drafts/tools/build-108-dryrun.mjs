// 108 dry run = 108 verbatim + three proofs inside the transaction + a deliberate error, so NOTHING is kept.
// Generated, never hand-edited: a test compares the file with this output.
//   1. a re-save of every order of the missing list writes NOTHING (the old stops stay the accountant's, owner 4b);
//   2. a real transition (exchange off -> on on one listed order) writes its deliveries, each with its audit row;
//   3. the writer called again writes nothing (one per stop, pl_mov_stop_once).
export function build108Dryrun(main) {
  const tail = "  RAISE NOTICE '108 OK:";
  if (!main.includes(tail)) throw new Error('108: tail not found');
  const proofs = `  -- DRY RUN ONLY: the proofs, then everything is undone.
  SELECT count(*), count(DISTINCT order_id) INTO v_m0, v_ord0 FROM public.pl_v_missing_delivery;
  UPDATE public.orders SET pallet_exchange = pallet_exchange WHERE id IN (SELECT order_id FROM public.pl_v_missing_delivery);
  SELECT count(*) INTO v_m1 FROM public.pl_v_missing_delivery;
  SELECT count(*) INTO v_a1 FROM public.audit_log WHERE actor = 'system' AND after_data ->> 'source' = 'trigger:108';
  IF v_m1 <> v_m0 OR v_a1 <> 0 THEN RAISE EXCEPTION '108 DRY RUN FAILED: a re-save wrote (missing % -> %, audit %)', v_m0, v_m1, v_a1; END IF;
  SELECT order_id INTO v_oid FROM public.pl_v_missing_delivery ORDER BY delivered_on DESC, order_stop_id LIMIT 1;
  IF v_oid IS NOT NULL THEN
    SELECT count(*) INTO v_stops FROM public.pl_v_missing_delivery WHERE order_id = v_oid;
    UPDATE public.orders SET pallet_exchange = false WHERE id = v_oid;
    UPDATE public.orders SET pallet_exchange = true WHERE id = v_oid;
    SELECT count(*) INTO v_m2 FROM public.pl_v_missing_delivery;
    SELECT count(*) INTO v_a2 FROM public.audit_log WHERE actor = 'system' AND after_data ->> 'source' = 'trigger:108';
    IF v_m2 <> v_m0 - v_stops OR v_a2 <> v_stops THEN
      RAISE EXCEPTION '108 DRY RUN FAILED: the transition of order % wrote % (audit %), expected %', v_oid, v_m0 - v_m2, v_a2, v_stops;
    END IF;
    IF public.pl_h_delivery_write(v_oid, NULL, 'status') <> 0 THEN RAISE EXCEPTION '108 DRY RUN FAILED: a second write on order %', v_oid; END IF;
  END IF;
  RAISE EXCEPTION 'DRY RUN 108 finished: re-save of % listed orders wrote 0; transition of order % wrote % deliveries (audit %); triggers % -> %; % ms - NOTHING kept',
    v_ord0, coalesce(v_oid::text, 'none'), coalesce(v_stops, 0), coalesce(v_a2, 0),
    v_trg0, v_trg1, round(extract(epoch FROM clock_timestamp() - v_t0) * 1000);
`;
  return main
    .replace(/^-- 108 - /, '-- 108 DRY RUN (generated by drafts/tools/build-108-dryrun.mjs: 108 + three proofs + a deliberate error) - ')
    .replace('  v_trg0 int; v_trg1 int; v_k int; v_t0 timestamptz := clock_timestamp();',
      '  v_trg0 int; v_trg1 int; v_k int; v_t0 timestamptz := clock_timestamp();\n  v_m0 int; v_ord0 int; v_m1 int; v_m2 int; v_a1 int; v_a2 int; v_oid bigint; v_stops int;')
    .replace(/  RAISE NOTICE '108 OK:[\s\S]*?v_t0\) \* 1000\);\n/, () => proofs);
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const fs = await import('node:fs');
  const path = await import('node:path');
  const dir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
  fs.writeFileSync(path.join(dir, '108_pl_delivery_trigger_dryrun.sql'), build108Dryrun(fs.readFileSync(path.join(dir, '108_pl_delivery_trigger.sql'), 'utf8')));
  console.log('108 dry run written');
}
