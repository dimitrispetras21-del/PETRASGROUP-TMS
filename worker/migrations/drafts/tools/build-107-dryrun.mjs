// 107 dry run = 107 verbatim + one real «no exchange» act on a live candidate (checked inside the transaction) +
// a deliberate error, so NOTHING is kept. Generated, never hand-edited: a test compares the file with this output.
export function build107Dryrun(main) {
  const tail = '  SELECT count(*) INTO v_missing FROM public.pl_v_missing_delivery;';
  if (!main.includes(tail)) throw new Error('107: tail not found');
  const exercise = `${tail}
  -- DRY RUN ONLY: one candidate with one delivery stop and no national leg, switched off and checked, then undone.
  SELECT order_id, order_stop_id INTO v_oid, v_sid FROM public.pl_v_missing_delivery
   WHERE unloading_stops = 1 AND NOT has_nat_leg ORDER BY delivered_on DESC, order_stop_id LIMIT 1;
  IF v_oid IS NOT NULL THEN
    SELECT count(*) INTO v_pend FROM public.pl_movements WHERE order_id = v_oid AND status = 'pending';
    SELECT count(*) INTO v_audit0 FROM public.audit_log;
    v_res := public.pl_no_exchange(jsonb_build_object('order_id', v_oid, 'order_stop_id', v_sid, 'reason', 'dry run 107'), 'dryrun-107', 'owner');
    IF (SELECT pallet_exchange FROM public.orders WHERE id = v_oid) IS NOT FALSE THEN RAISE EXCEPTION '107 DRY RUN FAILED: exchange still on'; END IF;
    IF EXISTS (SELECT 1 FROM public.pl_movements WHERE order_id = v_oid AND status = 'pending') THEN RAISE EXCEPTION '107 DRY RUN FAILED: pending left'; END IF;
    IF (SELECT count(*) FROM public.audit_log) - v_audit0 <> v_pend + 1 THEN RAISE EXCEPTION '107 DRY RUN FAILED: audit rows % expected %', (SELECT count(*) FROM public.audit_log) - v_audit0, v_pend + 1; END IF;
    IF EXISTS (SELECT 1 FROM public.pl_v_missing_delivery WHERE order_stop_id = v_sid) THEN RAISE EXCEPTION '107 DRY RUN FAILED: stop still listed'; END IF;
  END IF;
  RAISE EXCEPTION 'DRY RUN 107 finished: % stops listed, act checked on order % (% pending deleted), % ms - NOTHING kept',
    v_missing, coalesce(v_oid::text, 'none'), coalesce(v_pend, 0), round(extract(epoch FROM clock_timestamp() - v_t0) * 1000);`;
  return main
    .replace(/^-- 107 - /, '-- 107 DRY RUN (generated by drafts/tools/build-107-dryrun.mjs: 107 + one checked act + a deliberate error) - ')
    .replace('  v_missing int; v_t0 timestamptz := clock_timestamp();', '  v_missing int; v_t0 timestamptz := clock_timestamp();\n  v_oid bigint; v_sid bigint; v_pend int; v_audit0 bigint; v_res jsonb;')
    .replace(tail, () => exercise)
    .replace(/  RAISE NOTICE '107 OK:[\s\S]*?v_t0\) \* 1000\);\n/, '');
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const fs = await import('node:fs');
  const path = await import('node:path');
  const dir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
  fs.writeFileSync(path.join(dir, '107_pl_missing_delivery_dryrun.sql'), build107Dryrun(fs.readFileSync(path.join(dir, '107_pl_missing_delivery.sql'), 'utf8')));
  console.log('107 dry run written');
}
