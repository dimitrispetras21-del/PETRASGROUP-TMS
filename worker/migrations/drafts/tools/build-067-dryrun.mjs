// Generates worker/migrations/drafts/067_stop_delay_reason_dryrun.sql FROM 067_stop_delay_reason.sql.
//   node worker/migrations/drafts/tools/build-067-dryrun.mjs          (writes the file)
//   node worker/migrations/drafts/tools/build-067-dryrun.mjs --check  (exit 1 if the committed file drifted)
// Why generated, never hand-copied (principle 3): the dry run is only worth anything if it runs EXACTLY the
// statements 067 will run. A hand copy drifts the first time 067 is edited and then "proves" a migration nobody
// will execute. tms-auditor/test/dryrun-067.test.mjs fails when the committed file differs.
// Same shape as build-066-dryrun.mjs: ONE DO $dry$ block - a prologue that fingerprints data 067 must not touch,
// 067's DO block VERBATIM as a nested block (its guards and proofs raise their own messages and stop everything),
// an epilogue of scenarios that each report ok / FAIL / ERROR without stopping the others, and a final RAISE
// EXCEPTION that carries the result line and undoes all of it. 067 is ASCII only, so the whole file is.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = path.join(DRAFTS, '067_stop_delay_reason.sql');
export const TARGET = path.join(DRAFTS, '067_stop_delay_reason_dryrun.sql');

const OPEN = '\nDO $do$\n';
const CLOSE = '\nEND $do$;\n';

const HEADER = `-- 067 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-067-dryrun.mjs from 067_stop_delay_reason.sql.
-- DO NOT EDIT BY HAND: edit 067 and regenerate (tms-auditor/test/dryrun-067.test.mjs fails on any drift).
--
-- WHAT: 067's own DO block, statement for statement (every guard, the ALTER TABLE, every proof, B-54 run as
--   tms_check_runner), wrapped in ONE outer DO block that first fingerprints data 067 must not touch, then
--   checks the result, and ENDS WITH A DELIBERATE ERROR. The error rolls the whole block back: NOTHING it did
--   is kept (no column, no CHECK).
-- WHEN: the same evening, AFTER 15:00 (the team works 05:30-14:30), BEFORE 067_stop_delay_reason.sql. It
--   uses the same lock_timeout as 067 (5 s, then it gives up - run it again a little later).
-- WHY ONE DO BLOCK: the Supabase SQL editor is NOT atomic across statements (lesson 056), but ONE DO
--   block is ONE statement: its final error undoes everything inside it.
-- EXPECTED (the red ERROR is deliberate):
--   ERROR: P0001: DRY RUN 067 finished - EVERYTHING UNDONE, nothing kept. Result: 4 OK, 0 FAIL  ||  A ok ... | B ok triggers 35 = 35, B-54 35 | C ok ... | D ok ...
--   Anything with FAIL or ERROR in it: do NOT run 067, copy the panel to the coordinator.
--   ONE exception: "3 OK, 1 FAIL" where the FAIL is C alone (A, B, D ok). C fingerprints every order stop, the
--   auditor rows and every public sequence while the block runs, so ONE stop saved by someone else in those
--   seconds turns it red - it fails closed, nothing was kept. Wait 5 minutes and run the dry run once more;
--   if C fails again, copy the panel to the coordinator.
--   A different message altogether ("067: ...", "067 proof: ...", a lock timeout) is the guard or proof of
--   067 that stopped - exactly what 067 itself would have said. Do NOT run 067.
-- AFTER: SELECT that nothing was kept - order_stops has no column named delay_reason.
-- Scenarios: A 067's columns and CHECKs exist inside the block; B the trigger count did not move and B-54
--   equals it; C data 067 must not touch is unchanged (every order stop minus the three new keys, every
--   auditor row, every public sequence's last_value); D one probe stop (id -6799, OVERRIDING SYSTEM VALUE: no
--   sequence moves; undone inside D) takes "loading_wait" with responsibility "client" and refuses an unknown
--   code and "other" without a note.
`;

// Whole rows (to_jsonb) minus the three keys 067 adds, not a column list: the fingerprint must not name a
// column 067 does not guard, or a renamed column would kill the dry run before 067's own guard could speak.
// Before the ALTER the three keys do not exist, and subtracting a missing key is a no-op.
const FP = `(SELECT md5(
    coalesce((SELECT string_agg(md5((to_jsonb(x) - 'delay_reason' - 'delay_note' - 'delay_responsibility')::text), ',' ORDER BY x.id) FROM public.order_stops x), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, md5(sql_text), md5(coalesce(ids_sql, '')), red_value, baseline, enabled), ',' ORDER BY id) FROM monitoring.checks), '')
 || coalesce((SELECT string_agg(s.sequencename || '=' || coalesce(s.last_value::text, '-'), ',' ORDER BY s.sequencename) FROM pg_sequences s WHERE s.schemaname = 'public'), '')))`;

const PROLOGUE = `DO $dry$
DECLARE
  ok int := 0; bad int := 0; res text[] := '{}';
  dry_fp_before text; dry_b54_before int; dry_trg_before int; dry_n int; dry_got text; dry_tries text;
BEGIN
  -- the B-54 value and the trigger count 067 will meet, and the data it must leave alone
  SELECT red_value INTO dry_b54_before FROM monitoring.checks WHERE id = 'B-54';
  SELECT count(*) INTO dry_trg_before FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  SELECT ${FP} INTO dry_fp_before;

  -- ===== 067_stop_delay_reason.sql, its DO block verbatim (a nested block: its errors stop everything) =====
`;

const EPILOGUE = `  -- ===== end of 067 =====

  -- A: what 067 adds is there (its own proofs already raised if not; this names it in the result)
  BEGIN
    IF (SELECT count(*) FROM pg_attribute WHERE attrelid = 'public.order_stops'::regclass AND NOT attisdropped
          AND attname IN ('delay_reason', 'delay_note', 'delay_responsibility')) = 3
       AND (SELECT count(*) FROM pg_constraint WHERE conrelid = 'public.order_stops'::regclass AND convalidated
             AND conname IN ('order_stops_delay_reason_check', 'order_stops_delay_other_note_check', 'order_stops_delay_only_delayed_check')) = 3 THEN
      ok := ok + 1; res := res || 'A ok 3 delay columns (responsibility generated) + 3 CHECKs'::text;
    ELSE bad := bad + 1; res := res || 'A FAIL a delay column or CHECK is missing'::text; END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('A ERROR ' || SQLERRM);
  END;

  -- B: no trigger was added or dropped: the count and B-54 did not move
  BEGIN
    SELECT count(*) INTO dry_n FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
      JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
    IF dry_n = dry_trg_before AND (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') = dry_n AND dry_b54_before = dry_trg_before THEN
      ok := ok + 1; res := res || format('B ok triggers %s = %s, B-54 %s', dry_trg_before, dry_n, dry_b54_before);
    ELSE bad := bad + 1; res := res || format('B FAIL triggers %s -> %s, B-54 %s -> %s', dry_trg_before, dry_n, dry_b54_before,
                                             (SELECT red_value FROM monitoring.checks WHERE id = 'B-54')); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('B ERROR ' || SQLERRM);
  END;

  -- C: data 067 must not touch - same fingerprint after the block as before it. A save by someone
  --    else during these seconds also changes it (fails closed): the FAIL text says what to do.
  BEGIN
    IF ${FP} = dry_fp_before THEN
      ok := ok + 1; res := res || 'C ok order stops (minus the new keys), auditor rows, sequences unchanged'::text;
    ELSE bad := bad + 1; res := res || 'C FAIL data changed during the dry run - 067 itself, or a save by someone else in those seconds: if A, B and D are ok, wait 5 minutes and run the dry run once more; if C fails again, stop and copy the panel to the coordinator'::text; END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('C ERROR ' || SQLERRM);
  END;

  -- D: the rules act on a real write - one probe stop, undone by the inner error (C was read before it)
  BEGIN
    dry_tries := '';
    BEGIN
      INSERT INTO public.order_stops (id, legacy_id, performance, delay_reason) OVERRIDING SYSTEM VALUE
        VALUES (-6799, 'recTEST067-DRY', 'Delayed', 'loading_wait') RETURNING delay_responsibility INTO dry_got;
      IF dry_got IS DISTINCT FROM 'client' THEN dry_tries := dry_tries || ' loading_wait->' || coalesce(dry_got, 'NULL'); END IF;
      BEGIN
        UPDATE public.order_stops SET delay_reason = 'lost_keys' WHERE id = -6799;
        dry_tries := dry_tries || ' unknown code accepted';
      EXCEPTION WHEN check_violation THEN NULL;
      END;
      BEGIN
        UPDATE public.order_stops SET delay_reason = 'other', delay_note = NULL WHERE id = -6799;
        dry_tries := dry_tries || ' other without note accepted';
      EXCEPTION WHEN check_violation THEN NULL;
      END;
      RAISE EXCEPTION USING ERRCODE = 'P0067', MESSAGE = 'dry run probe undone';
    EXCEPTION WHEN SQLSTATE 'P0067' THEN NULL;
    END;
    IF dry_tries = '' AND NOT EXISTS (SELECT 1 FROM public.order_stops WHERE id = -6799) THEN
      ok := ok + 1; res := res || 'D ok probe: loading_wait -> client; unknown code and other without note refused; probe undone'::text;
    ELSE bad := bad + 1; res := res || ('D FAIL' || dry_tries); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('D ERROR ' || SQLERRM);
  END;

  RAISE EXCEPTION 'DRY RUN 067 finished - EVERYTHING UNDONE, nothing kept. Result: % OK, % FAIL  ||  %', ok, bad, array_to_string(res, '  |  ');
END
$dry$;
`;

export function buildDryRun(src) {
  const a = src.indexOf(OPEN), b = src.lastIndexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) throw new Error('067 DO $do$ ... END $do$; not found');
  const body = src.slice(a + OPEN.length, b);                          // DECLARE ... BEGIN ... (no END)
  if (!/^DECLARE\n/.test(body)) throw new Error('067 body does not start with DECLARE - not found where measured');
  if (body.includes('$dry$')) throw new Error('067 uses $dry$ - choose other tags');
  if (/\bdry_(fp_before|b54_before|trg_before|n|got|tries)\b|\b(ok|bad|res)\b\s*(int|text\[\])/.test(body)) throw new Error('067 declares a name the dry run uses - choose other tags');
  if (body.includes('P0067')) throw new Error('067 uses the dry run\'s probe SQLSTATE P0067');
  const out = HEADER + '\n' + PROLOGUE + body + '\nEND;\n' + EPILOGUE;
  const bad = [...out].findIndex((c) => c.charCodeAt(0) > 127);
  if (bad >= 0) throw new Error('non-ASCII at ' + bad);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = buildDryRun(fs.readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (cur !== out) { console.error('067_stop_delay_reason_dryrun.sql drifted from 067 - regenerate'); process.exit(1); }
    console.log('067 dry run matches 067');
  } else {
    fs.writeFileSync(TARGET, out);
    console.log('wrote', path.relative(process.cwd(), TARGET), out.length, 'chars');
  }
}
