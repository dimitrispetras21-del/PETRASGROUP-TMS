// Generates worker/migrations/drafts/060_local_relay_dryrun.sql FROM 060_local_relay.sql.
//   node worker/migrations/drafts/tools/build-060-dryrun.mjs          (writes the file)
//   node worker/migrations/drafts/tools/build-060-dryrun.mjs --check  (exit 1 if the committed file drifted)
// Why generated, never hand-copied (principle 3): the dry run is only worth anything if it runs EXACTLY the
// statements 060 will run that evening. A hand copy drifts the first time 060 is edited and then "proves" a
// migration nobody will execute. tms-auditor/test/dryrun-060.test.mjs fails when the committed file differs.
// Same shape as the 057 dry run (build-057-dryrun.mjs, review round 3 asked for the pair): ONE DO $dry$
// block - a prologue that fingerprints data 060 must not touch, 060's DO block VERBATIM as a nested block
// (its guards and proofs raise their own messages and stop everything), an epilogue of scenarios that each
// report ok / FAIL / ERROR without stopping the others, and a final RAISE EXCEPTION that carries the result
// line and undoes all of it. 060 is ASCII only, so the whole file is.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = path.join(DRAFTS, '060_local_relay.sql');
export const TARGET = path.join(DRAFTS, '060_local_relay_dryrun.sql');

const OPEN = '\nDO $do$\n';
const CLOSE = '\nEND $do$;\n';

const HEADER = `-- 060 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-060-dryrun.mjs from 060_local_relay.sql.
-- DO NOT EDIT BY HAND: edit 060 and regenerate (tms-auditor/test/dryrun-060.test.mjs fails on any drift).
--
-- WHAT: 060's own DO block, statement for statement (every guard, change and proof, the B-54 bump, the
--   auditor rows run as tms_check_runner), wrapped in ONE outer DO block that first fingerprints data 060
--   must not touch, then checks the result, and ENDS WITH A DELIBERATE ERROR. The error rolls the whole
--   block back: NOTHING it did is kept (no column, constraint, index, function, trigger, view change,
--   auditor row, B-54 edit).
-- WHEN: the same evening, AFTER 15:00 (the team works 05:30-14:30), BEFORE 060_local_relay.sql - and
--   after 057 when both go out together (060 then measures the triggers 057 added). It takes the same
--   locks as 060 (lock_timeout 5 s, then it gives up - run it again a little later).
-- WHY ONE DO BLOCK: the Supabase SQL editor is NOT atomic across statements (lesson 056), but ONE DO
--   block is ONE statement: its final error undoes everything inside it.
-- EXPECTED (the red ERROR is deliberate):
--   ERROR: P0001: DRY RUN 060 finished - EVERYTHING UNDONE, nothing kept. Result: 3 OK, 0 FAIL  ||  A ok ... | B ok B-54 T -> T+5 ... | C ok ...
--   (T = the live trigger count: 31 after 057, 27 without it.)
--   Anything with FAIL or ERROR in it: do NOT run 060, copy the panel to the coordinator.
--   A different message altogether ("060: ...", "060 proof: ...", a lock timeout) is the guard or proof
--   of 060 that stopped - exactly what 060 itself would have said. Do NOT run 060.
-- AFTER: SELECT that nothing was kept - local_moves has no move_kind column, B-63..B-65 do not exist,
--   B-54 red_value is still T (060_local_relay_verify.sql is for AFTER 060, not here).
-- Scenarios: A 060's objects exist inside the block; B B-54 moved by exactly +5 and equals the live
--   count; C data 060 must not touch is unchanged (orders, payroll lines, round trips, local_moves,
--   drivers, every auditor row but B-09/B-54/B-63..B-65, the last_value of every public sequence).
`;

const FP = `(SELECT md5(
    coalesce((SELECT string_agg(concat_ws(':', id, status, driver_id, truck_id, trailer_id, partner_id, loading_datetime, delivery_datetime, deleted_at), ',' ORDER BY id) FROM public.orders), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, driver_id, entry_type, entry_date, rt_id, trip_value, advance, expenses, amount, deleted_at, needs_review, review_note), ',' ORDER BY id) FROM public.dl_entries), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, status, driver_id, truck_id, trailer_id, date_start, date_end), ',' ORDER BY id) FROM public.ct_round_trips), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, status, driver_id, parent_order_id, parent_nat_load_id, move_date, deleted_at), ',' ORDER BY id) FROM public.local_moves), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, full_name, active, deleted_at), ',' ORDER BY id) FROM public.drivers), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, md5(sql_text), md5(coalesce(ids_sql, '')), red_value, baseline, enabled), ',' ORDER BY id) FROM monitoring.checks
              WHERE id NOT IN ('B-09', 'B-54', 'B-63', 'B-64', 'B-65')), '')
 || coalesce((SELECT string_agg(s.sequencename || '=' || coalesce(s.last_value::text, '-'), ',' ORDER BY s.sequencename) FROM pg_sequences s WHERE s.schemaname = 'public'), '')))`;

const PROLOGUE = `DO $dry$
DECLARE
  ok int := 0; bad int := 0; res text[] := '{}';
  dry_fp_before text; dry_b54_before int; dry_trg_before int; dry_n int;
BEGIN
  -- the B-54 value and the trigger count 060 will meet, and the data it must leave alone
  SELECT red_value INTO dry_b54_before FROM monitoring.checks WHERE id = 'B-54';
  SELECT count(*) INTO dry_trg_before FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  SELECT ${FP} INTO dry_fp_before;

  -- ===== 060_local_relay.sql, its DO block verbatim (a nested block: its errors stop everything) =====
`;

const EPILOGUE = `  -- ===== end of 060 =====

  -- A: what 060 creates is there (its own proofs already raised if not; this names it in the result)
  BEGIN
    SELECT count(*) INTO dry_n FROM information_schema.columns WHERE table_schema = 'public'
       AND ((table_name = 'local_moves' AND column_name = 'move_kind') OR (table_name = 'drivers' AND column_name = 'pay_basis')
         OR (table_name = 'dl_entries' AND column_name = 'local_move_id') OR (table_name = 'dl_v_entries' AND column_name = 'relay_info'));
    IF dry_n = 4 AND (SELECT count(*) FROM monitoring.checks WHERE id IN ('B-63', 'B-64', 'B-65')) = 3 THEN
      ok := ok + 1; res := res || 'A ok columns, view column and B-63..B-65 in place'::text;
    ELSE bad := bad + 1; res := res || format('A FAIL columns %s/4', dry_n); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('A ERROR ' || SQLERRM);
  END;

  -- B: B-54 moved by exactly the five triggers 060 adds, and equals the live count
  BEGIN
    SELECT count(*) INTO dry_n FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
      JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
    IF dry_n = dry_trg_before + 5 AND (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') = dry_n AND dry_b54_before = dry_trg_before THEN
      ok := ok + 1; res := res || format('B ok B-54 %s -> %s (= live triggers)', dry_b54_before, dry_n);
    ELSE bad := bad + 1; res := res || format('B FAIL triggers %s -> %s, B-54 %s -> %s', dry_trg_before, dry_n, dry_b54_before,
                                             (SELECT red_value FROM monitoring.checks WHERE id = 'B-54')); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('B ERROR ' || SQLERRM);
  END;

  -- C: data 060 must not touch - same fingerprint after the block as before it
  BEGIN
    IF ${FP} = dry_fp_before THEN
      ok := ok + 1; res := res || 'C ok orders, payroll, round trips, local_moves, drivers, other checks, sequences unchanged'::text;
    ELSE bad := bad + 1; res := res || 'C FAIL 060 changed data it must not touch'::text; END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('C ERROR ' || SQLERRM);
  END;

  RAISE EXCEPTION 'DRY RUN 060 finished - EVERYTHING UNDONE, nothing kept. Result: % OK, % FAIL  ||  %', ok, bad, array_to_string(res, '  |  ');
END
$dry$;
`;

export function buildDryRun(src) {
  const a = src.indexOf(OPEN), b = src.lastIndexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) throw new Error('060 DO $do$ ... END $do$; not found');
  const body = src.slice(a + OPEN.length, b);                          // DECLARE ... BEGIN ... (no END)
  if (!/^DECLARE\n/.test(body)) throw new Error('060 body does not start with DECLARE - not found where measured');
  if (body.includes('$dry$')) throw new Error('060 uses $dry$ - choose other tags');
  if (/\bdry_(fp_before|b54_before|trg_before|n)\b|\b(ok|bad|res)\b\s*(int|text\[\])/.test(body)) throw new Error('060 declares a name the dry run uses - choose other tags');
  const out = HEADER + '\n' + PROLOGUE + body + '\nEND;\n' + EPILOGUE;
  const bad = [...out].findIndex((c) => c.charCodeAt(0) > 127);
  if (bad >= 0) throw new Error('non-ASCII at ' + bad);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = buildDryRun(fs.readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (cur !== out) { console.error('060_local_relay_dryrun.sql drifted from 060 - regenerate'); process.exit(1); }
    console.log('060 dry run matches 060');
  } else {
    fs.writeFileSync(TARGET, out);
    console.log('wrote', path.relative(process.cwd(), TARGET), out.length, 'chars');
  }
}
