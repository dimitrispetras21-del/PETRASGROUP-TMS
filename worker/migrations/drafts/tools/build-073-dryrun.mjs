// Generates the 073 dry run FROM its source:
//   073_plan_money.sql -> 073_plan_money_dryrun.sql
//   node worker/migrations/drafts/tools/build-073-dryrun.mjs          (writes it)
//   node worker/migrations/drafts/tools/build-073-dryrun.mjs --check  (exit 1 if the committed file drifted)
// Why generated, never hand-copied (principle 3): a dry run is only worth anything if it runs EXACTLY the
// statements the owner will run. tests/sql-073-drafts.test.js fails when the committed dry run differs.
// Shape (as 072): ONE DO $dry$ block - 073's DO block VERBATIM as a nested block (its guards and proofs raise their
// own messages and stop everything), a read of what it did, and a final RAISE EXCEPTION that carries the result
// line and undoes all of it (pg_notify included: a NOTIFY is sent only at COMMIT). ASCII in, ASCII out.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// The folder that holds the 073 files. 073 was executed 26/10 and left drafts/ (CLAUDE.md rule 5): the source and
// the generated dry run are one up.
export const DIR = path.resolve(HERE, '..', '..');
const OPEN = '\nDO $do$\n';
const CLOSE = '\nEND $do$;\n';

export const PAIR = {
  source: '073_plan_money.sql', target: '073_plan_money_dryrun.sql', name: 'DRY RUN 073',
  header: `-- 073 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-073-dryrun.mjs from 073_plan_money.sql.
-- DO NOT EDIT BY HAND: edit the source and regenerate (tests/sql-073-drafts.test.js fails on any drift).
-- WHY ONE DO BLOCK: the Supabase SQL editor is NOT atomic across statements (lesson 056), but ONE DO block is
--   ONE statement: its final error undoes everything inside it. ASCII only.
-- WHAT: 073's own DO block, statement for statement (the guards, the helper, the 5 hooks in 072, the 7 views, the
--   index, the rights, the before = after proof), then a read of the result, ENDING WITH A DELIBERATE ERROR:
--   NOTHING is kept.
-- WHEN: AFTER 15:00 (the team works 05:30-14:30), AFTER 072 and 072b ran (order 072 -> 072b -> 073), BEFORE
--   073_plan_money.sql. Same 5 s lock timeout.
-- EXPECTED (the red ERROR is deliberate): a NOTICE "073 OK: ..." and then
--   ERROR: P0001: DRY RUN 073 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  073 ran:
--   v5 revenue view yes, helper yes, stop index yes, pnl rows <as before>, route rows <as before>, v5 rows 0, triggers <B-54>
--   Anything else (an ERROR from one of 073's guards or proofs): do NOT run 073, copy the message to the coordinator.`,
  epilogue: `  res := format('073 ran: v5 revenue view %s, helper %s, stop index %s, pnl rows %s, route rows %s, v5 rows %s, triggers %s',
    CASE WHEN to_regclass('public.ct_v_v5_revenue') IS NOT NULL THEN 'yes' ELSE 'NO' END,
    CASE WHEN to_regprocedure('public.plan_h_pallet_sync(bigint[],text,text)') IS NOT NULL THEN 'yes' ELSE 'NO' END,
    CASE WHEN to_regclass('public.pl_mov_stop_once') IS NOT NULL THEN 'yes' ELSE 'NO' END,
    (SELECT count(*) FROM public.ct_v_rt_pnl), (SELECT count(*) FROM public.dl_v_rt_route),
    (SELECT count(*) FROM public.shipments) + (SELECT count(*) FROM public.shipment_pieces)
      + (SELECT count(*) FROM public.rt_stops) + (SELECT count(*) FROM public.piece_legs)
      + (SELECT count(*) FROM public.plan_notices) + (SELECT count(*) FROM public.pl_movements WHERE piece_leg_id IS NOT NULL),
    (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = c.relnamespace
      WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public'));`,
};

export function buildDryRun(src, pair = PAIR) {
  const a = src.indexOf(OPEN);
  const b = src.lastIndexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) throw new Error(`${pair.source}: the DO $do$ ... END $do$; block was not found`);
  const body = src.slice(a + OPEN.length, b);   // "DECLARE ... BEGIN ... " of the source, verbatim
  if (body.includes('$dry$')) throw new Error(`${pair.source}: contains $dry$ - choose other tags`);
  return `${pair.header}

DO $dry$
DECLARE
  res text;
BEGIN
  -- ===== ${pair.source}, verbatim =====
${body}
END;
  -- ===== what it did =====
${pair.epilogue}
  RAISE EXCEPTION '${pair.name} finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  %', res;
END
$dry$;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const source = path.join(DIR, PAIR.source);
  if (!fs.existsSync(source)) { console.error('no source: ' + PAIR.source); process.exit(1); }
  const out = buildDryRun(fs.readFileSync(source, 'utf8'));
  const target = path.join(DIR, PAIR.target);
  if (check) {
    const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === out;
    if (!same) console.error('drift: ' + PAIR.target);
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(target, out);
  console.log('wrote ' + PAIR.target);
}
