// node worker/migrations/drafts/tools/build-078-dryrun.mjs
// 078's dry run = 078's DO block verbatim + a deliberate error, so nothing is kept. Generated, never edited by hand:
// worker/test/migration-078.test.mjs fails when the two drift (principle 3).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function build078Dryrun(main) {
  // from the statement_timeout line: the dry run is bounded like 078
  const at = main.indexOf("\nSET statement_timeout = '5s';\nDO $m$");
  if (at < 0) throw new Error('078: SET statement_timeout must precede the block');
  const block = main.slice(at + 1);
  const end = 'END\n$m$;';
  if (!block.includes(end + '\n') || !block.endsWith('RESET statement_timeout;\n')) throw new Error('078: the block must end with END $m$; then RESET');
  return [
    "-- 078 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-078-dryrun.mjs. DO NOT EDIT BY HAND.",
    "-- 078's block verbatim (SET statement_timeout, the DO block, RESET), ending with a deliberate error: NOTHING is kept. ASCII.",
    '-- EXPECTED: NOTICE "078 OK | ..." then ERROR: P0001: DRY RUN 078 finished - EVERYTHING UNDONE, nothing kept.',
    '',
  ].join('\n') + block.replace(end, "  RAISE EXCEPTION 'DRY RUN 078 finished - EVERYTHING UNDONE, nothing kept';\n" + end);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const main = fs.readFileSync(path.join(DIR, '078_audit_actions.sql'), 'utf8');
  fs.writeFileSync(path.join(DIR, '078_audit_actions_dryrun.sql'), build078Dryrun(main));
  console.log('078_audit_actions_dryrun.sql written');
}
