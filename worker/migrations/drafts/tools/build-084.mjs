// Generates the dry run, the rollback and the rollback's dry run of 084 FROM its source (084_plan_move_busy_skip.sql):
//   node worker/migrations/drafts/tools/build-084.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-084.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 084 applied - it reads them (and the md5 before / after) from the source, never a hand copy.
// tests/sql-084-drafts.test.js fails on drift; tms-auditor/test/plan-084.test.mjs runs them on the production-shaped copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// 084 is a draft: its files live in drafts/ until the owner runs it (CLAUDE.md rule 5), then one up
export const DIR = fs.existsSync(path.resolve(HERE, '..', '084_plan_move_busy_skip.sql')) ? path.resolve(HERE, '..') : path.resolve(HERE, '..', '..');
export const SOURCE = '084_plan_move_busy_skip.sql';
export const ROLLBACK = '084_plan_move_busy_skip_rollback.sql';
const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;

// The facts of the source, read once: the hunk constants, the live md5 (PART 0) and the generated md5 (PART 1 + 2)
export function facts(src) {
  const consts = Object.fromEntries([...src.matchAll(/^ {2}([a-z0-9_]+) CONSTANT text := \$h\$([\s\S]*?)\$h\$;$/gm)].map((m) => [m[1], m[2]]));
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part12 = src.slice(src.indexOf('===== PART 1'), src.indexOf('===== PART 3'));
  const live = Object.fromEntries([...part0.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', '([0-9a-f]{32})'\)/g)].map((m) => [m[1], m[2]]));
  const gen = [...part12.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', ARRAY\[([a-z0-9_, ]+)\], ARRAY\[([a-z0-9_, ]+)\], '([0-9a-zA-Z_]+)'\)/g)]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (gen.length !== 2 || gen.some((g) => !live[g.sig] || g.a.length !== g.b.length || [...g.a, ...g.b].some((k) => !(k in consts)))) {
    throw new Error(`${SOURCE}: PART 0 / PART 1 + 2 are not the two functions with their hunks`);
  }
  const a = src.indexOf('  -- the hunks:'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the hunk block was not found`);
  return { consts, live, gen, hunks: src.slice(a, b) };
}

// The text 084 writes, from a live text (the PGlite test derives the md5 of PART 1 + 2 with it)
export function applyHunks(text, g, consts) {
  let out = text;
  g.a.forEach((k, i) => {
    const n = out.split(consts[k]).length - 1;
    if (n !== 1) throw new Error(`${g.sig}: hunk ${k} found ${n} times`);
    out = out.replace(consts[k], () => consts[g.b[i]]);
  });
  return out;
}

