// Generates the dry run, the rollback and the rollback's dry run of 096 FROM its source (096_plan_handover_accept_busy.sql):
//   node worker/migrations/drafts/tools/build-096.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-096.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 096 applied - it reads them (and the md5 before / after) from the source, never a hand copy. The shape is
// 082's (build-082.mjs).
// tests/sql-096-drafts.test.js fails on drift; tms-auditor/test/plan-096.test.mjs runs them on the production-shaped copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// drafts/ until the owner runs 096, then one up (CLAUDE.md rule 5): the builder stays here
const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = '096_plan_handover_accept_busy.sql';
export const DIR = fs.existsSync(path.join(DRAFTS, SOURCE)) ? DRAFTS : path.resolve(DRAFTS, '..');
export const ROLLBACK = '096_plan_handover_accept_busy_rollback.sql';
const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;
// a signature with its argument types (plan_vs_state takes bigint[])
const SIG = String.raw`public\.[a-z_]+\([a-z,\[\]]*\)`;
export const PATCHED = ['public.plan_seg_change(jsonb,text,text)', 'public.plan_seg_fix(jsonb,text,text)'];

// The facts of the source, read once: the hunk constants, the live md5 (PART 0) and the generated md5 (PART 1 + 2)
export function facts(src) {
  const consts = Object.fromEntries([...src.matchAll(/^ {2}([a-z0-9_]+) CONSTANT text := \$h\$([\s\S]*?)\$h\$;$/gm)].map((m) => [m[1], m[2]]));
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part12 = src.slice(src.indexOf('===== PART 1'), src.indexOf('===== PART 2'));
  const live = Object.fromEntries([...part0.matchAll(new RegExp(`\\('(${SIG})', '([0-9a-f]{32})'\\)`, 'g'))].map((m) => [m[1], m[2]]));
  const gen = [...part12.matchAll(new RegExp(`\\('(${SIG})', ARRAY\\[([a-z0-9_, ]+)\\], ARRAY\\[([a-z0-9_, ]+)\\], '([0-9a-zA-Z_]+)'\\)`, 'g'))]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (gen.length !== PATCHED.length || gen.some((g, i) => g.sig !== PATCHED[i] || !live[g.sig] || g.a.length !== g.b.length
                                      || [...g.a, ...g.b].some((k) => !(k in consts)))) {
    throw new Error(`${SOURCE}: PART 0 / PART 1 are not the two functions with their hunks`);
  }
  const a = src.indexOf('  -- the hunks:'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the hunk block was not found`);
  return { consts, live, gen, hunks: src.slice(a, b) };
}

// The text 096 writes, from a live text (the PGlite test derives the md5 of PART 1 with it)
export function applyHunks(text, g, consts) {
  let out = text;
  g.a.forEach((k, i) => {
    const n = out.split(consts[k]).length - 1;
    if (n !== 1) throw new Error(`${g.sig}: hunk ${k} found ${n} times`);
    out = out.replace(consts[k], () => consts[g.b[i]]);
  });
  return out;
}

export const DRY = {
  source: SOURCE, target: '096_plan_handover_accept_busy_dryrun.sql', name: 'DRY RUN 096',
  header: `-- 096 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-096.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND (tests/sql-096-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056). ASCII only.
-- EXPECTED (the red ERROR is deliberate): NOTICE "096 OK: the vehicle change and the segment correction take accept_busy ..."
--   and then ERROR: P0001: DRY RUN 096 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  096 ran:
--   seg_change GEN_C, seg_fix GEN_F
--   Anything else (an ERROR from one of 096's guards or proofs): do NOT run 096, copy the message to the coordinator.`,
  epilogue: `  res := format('096 ran: seg_change %s, seg_fix %s',
    ${md5Of(PATCHED[0])}, ${md5Of(PATCHED[1])});`,
};

export function buildRollback(src) {
  const f = facts(src);
  const blocks = f.gen.map((g) => `  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${g.sig}');
  IF md5(p.prosrc) <> '${g.m}' THEN
    RAISE EXCEPTION '096 rollback: ${g.sig} is not the text 096 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '096 rollback: a hunk of 096 is not in ${g.sig} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live[g.sig]}' THEN
    RAISE EXCEPTION '096 rollback: ${g.sig} would not be its live text (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE plpgsql %s %s SET search_path = public AS %L',
    split_part('${g.sig}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  IF ${md5Of(g.sig)} <> '${f.live[g.sig]}'
     OR (SELECT proacl::text FROM pg_proc WHERE oid = p.oid) IS DISTINCT FROM p.proacl::text THEN
    RAISE EXCEPTION '096 rollback proof: ${g.sig} is not back to its live text with its rights';
  END IF;`).join('\n');
  return `-- 096 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-096.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. plan_seg_change and plan_seg_fix back to the texts 095 wrote, byte for byte (the hunks of 096
-- in reverse, md5-proven): a vehicle change refuses a busy truck / driver again (accept_busy an unknown key). Overlaps
-- already accepted (overlap_rts, audit rows) STAY: the COMMIT pair rule of 086 keeps them. Run BEFORE 095's rollback.
-- Only with an explicit yes.
-- ASCII. ONE DO block.
-- EXPECTED: NOTICE "096 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
${blocks}
  RAISE NOTICE '096 ROLLBACK OK';
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '096_plan_handover_accept_busy_rollback_dryrun.sql', name: 'DRY RUN 096 ROLLBACK',
  header: `-- 096 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-096.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "096 ROLLBACK OK" then ERROR: P0001: DRY RUN 096 ROLLBACK finished - EVERYTHING UNDONE ...
--   seg_change LIVE_C, seg_fix LIVE_F`,
  epilogue: DRY.epilogue.replace('096 ran:', 'rollback ran:'),
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const rb = buildRollback(src);
  // the dry runs' headers name the md5 the run must end on (one fact: PART 1 of the source, PART 0 for the rollback)
  const f = facts(src);
  const [c, x] = f.gen.map((g) => g.m);
  const dry = { ...DRY, header: DRY.header.replace('GEN_C', c).replace('GEN_F', x) };
  const rbd = { ...RB_DRY, header: RB_DRY.header.replace('LIVE_C', f.live[PATCHED[0]]).replace('LIVE_F', f.live[PATCHED[1]]) };
  return { [DRY.target]: buildDryRun(src, dry), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, rbd) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
