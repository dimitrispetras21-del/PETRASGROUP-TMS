// Generates worker/migrations/drafts/063_local_line_guard_dryrun.sql FROM 063_local_line_guard.sql.
//   node worker/migrations/drafts/tools/build-063-dryrun.mjs          (writes the file)
//   node worker/migrations/drafts/tools/build-063-dryrun.mjs --check  (exit 1 if the committed file drifted)
// Why generated, never hand-copied (principle 3): the dry run is only worth anything if it runs EXACTLY the
// statements 063 will run. A hand copy drifts the first time 063 is edited and then "proves" a migration nobody
// will execute. tms-auditor/test/dryrun-063.test.mjs fails when the committed file differs.
// Same shape as build-060-dryrun.mjs: ONE DO $dry$ block - a prologue that fingerprints data 063 must not touch,
// 063's DO block VERBATIM as a nested block (its guards and proofs raise their own messages and stop everything),
// an epilogue of scenarios that each report ok / FAIL / ERROR without stopping the others, and a final RAISE
// EXCEPTION that carries the result line and undoes all of it. 063 is ASCII only, so the whole file is.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = path.join(DRAFTS, '063_local_line_guard.sql');
export const TARGET = path.join(DRAFTS, '063_local_line_guard_dryrun.sql');

const OPEN = '\nDO $do$\n';
const CLOSE = '\nEND $do$;\n';

const HEADER = `-- 063 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-063-dryrun.mjs from 063_local_line_guard.sql.
-- DO NOT EDIT BY HAND: edit 063 and regenerate (tms-auditor/test/dryrun-063.test.mjs fails on any drift).
--
-- WHAT: 063's own DO block, statement for statement (every guard, change and proof, B-54 run as
--   tms_check_runner), wrapped in ONE outer DO block that first fingerprints data 063 must not touch, then
--   checks the result, and ENDS WITH A DELIBERATE ERROR. The error rolls the whole block back: NOTHING it did
--   is kept (no function text, no function setting, no trigger change).
-- WHEN: the same evening, AFTER 15:00 (the team works 05:30-14:30), BEFORE 063_local_line_guard.sql. It
--   takes the same lock as 063 (lock_timeout 5 s, then it gives up - run it again a little later).
-- WHY ONE DO BLOCK: the Supabase SQL editor is NOT atomic across statements (lesson 056), but ONE DO
--   block is ONE statement: its final error undoes everything inside it.
-- EXPECTED (the red ERROR is deliberate):
--   ERROR: P0001: DRY RUN 063 finished - EVERYTHING UNDONE, nothing kept. Result: 3 OK, 0 FAIL  ||  A ok ... | B ok triggers T = T, B-54 T | C ok ...
--   (T = the live trigger count = B-54: 35 after 057 + 060.)
--   Anything with FAIL or ERROR in it: do NOT run 063, copy the panel to the coordinator.
--   ONE exception: "2 OK, 1 FAIL" where the FAIL is C alone (A ok, B ok). C fingerprints the payroll lines,
--   the local moves, the auditor rows and every public sequence while the block runs, so ONE save by
--   someone else in those seconds turns it red - it fails closed, nothing was kept. Wait 5 minutes and run
--   the dry run once more; if C fails again, copy the panel to the coordinator.
--   A different message altogether ("063: ...", "063 proof: ...", a lock timeout) is the guard or proof of
--   063 that stopped - exactly what 063 itself would have said. Do NOT run 063.
-- AFTER: SELECT that nothing was kept - the trigger dl_local_line_guard is still on deleted_at only and
--   dl_local_day_sync's config is still only its search_path.
-- Scenarios: A 063's changes exist inside the block; B the trigger count did not move and B-54 equals it;
--   C data 063 must not touch is unchanged (payroll lines, local moves, every auditor row, every public
--   sequence's last_value).
`;

// Whole rows (to_jsonb), not a column list: the fingerprint must not name a 060 column, or on a base without
// 060 the dry run would die on "column does not exist" before 063's own guard could say "060 is not applied".
const FP = `(SELECT md5(
    coalesce((SELECT string_agg(to_jsonb(x)::text, ',' ORDER BY x.id) FROM public.dl_entries x), '')
 || coalesce((SELECT string_agg(to_jsonb(x)::text, ',' ORDER BY x.id) FROM public.local_moves x), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, md5(sql_text), md5(coalesce(ids_sql, '')), red_value, baseline, enabled), ',' ORDER BY id) FROM monitoring.checks), '')
 || coalesce((SELECT string_agg(s.sequencename || '=' || coalesce(s.last_value::text, '-'), ',' ORDER BY s.sequencename) FROM pg_sequences s WHERE s.schemaname = 'public'), '')))`;

const PROLOGUE = `DO $dry$
DECLARE
  ok int := 0; bad int := 0; res text[] := '{}';
  dry_fp_before text; dry_b54_before int; dry_trg_before int; dry_n int;
BEGIN
  -- the B-54 value and the trigger count 063 will meet, and the data it must leave alone
  SELECT red_value INTO dry_b54_before FROM monitoring.checks WHERE id = 'B-54';
  SELECT count(*) INTO dry_trg_before FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  SELECT ${FP} INTO dry_fp_before;

  -- ===== 063_local_line_guard.sql, its DO block verbatim (a nested block: its errors stop everything) =====
`;

const EPILOGUE = `  -- ===== end of 063 =====

  -- A: what 063 changes is there (its own proofs already raised if not; this names it in the result)
  BEGIN
    SELECT cardinality(tgattr::int2[]) INTO dry_n FROM pg_trigger
     WHERE tgrelid = 'public.dl_entries'::regclass AND tgname = 'dl_local_line_guard';
    IF dry_n = 8
       AND EXISTS (SELECT 1 FROM pg_proc p, unnest(p.proconfig) c
                    WHERE p.oid = 'public.dl_local_day_sync(bigint,date)'::regprocedure AND c = 'tms.local_day_sync=on')
       AND position('local_relay:line_locked' IN (SELECT prosrc FROM pg_proc WHERE oid = 'public.dl_local_line_guard()'::regprocedure)) > 0 THEN
      ok := ok + 1; res := res || 'A ok trigger on 8 columns, sync flag, guard rule line_locked in place'::text;
    ELSE bad := bad + 1; res := res || format('A FAIL trigger columns %s/8 or flag/rule missing', dry_n); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('A ERROR ' || SQLERRM);
  END;

  -- B: the trigger was dropped and created under the same name: the count and B-54 did not move
  BEGIN
    SELECT count(*) INTO dry_n FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
      JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
    IF dry_n = dry_trg_before AND (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') = dry_n AND dry_b54_before = dry_trg_before THEN
      ok := ok + 1; res := res || format('B ok triggers %s = %s, B-54 %s', dry_trg_before, dry_n, dry_b54_before);
    ELSE bad := bad + 1; res := res || format('B FAIL triggers %s -> %s, B-54 %s -> %s', dry_trg_before, dry_n, dry_b54_before,
                                             (SELECT red_value FROM monitoring.checks WHERE id = 'B-54')); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('B ERROR ' || SQLERRM);
  END;

  -- C: data 063 must not touch - same fingerprint after the block as before it. A save by someone
  --    else during these seconds also changes it (fails closed): the FAIL text says what to do.
  BEGIN
    IF ${FP} = dry_fp_before THEN
      ok := ok + 1; res := res || 'C ok payroll lines, local moves, auditor rows, sequences unchanged'::text;
    ELSE bad := bad + 1; res := res || 'C FAIL data changed during the dry run - 063 itself, or a save by someone else in those seconds: if A and B are ok, wait 5 minutes and run the dry run once more; if C fails again, stop and copy the panel to the coordinator'::text; END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('C ERROR ' || SQLERRM);
  END;

  RAISE EXCEPTION 'DRY RUN 063 finished - EVERYTHING UNDONE, nothing kept. Result: % OK, % FAIL  ||  %', ok, bad, array_to_string(res, '  |  ');
END
$dry$;
`;

export function buildDryRun(src) {
  const a = src.indexOf(OPEN), b = src.lastIndexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) throw new Error('063 DO $do$ ... END $do$; not found');
  const body = src.slice(a + OPEN.length, b);                          // DECLARE ... BEGIN ... (no END)
  if (!/^DECLARE\n/.test(body)) throw new Error('063 body does not start with DECLARE - not found where measured');
  if (body.includes('$dry$')) throw new Error('063 uses $dry$ - choose other tags');
  if (/\bdry_(fp_before|b54_before|trg_before|n)\b|\b(ok|bad|res)\b\s*(int|text\[\])/.test(body)) throw new Error('063 declares a name the dry run uses - choose other tags');
  const out = HEADER + '\n' + PROLOGUE + body + '\nEND;\n' + EPILOGUE;
  const bad = [...out].findIndex((c) => c.charCodeAt(0) > 127);
  if (bad >= 0) throw new Error('non-ASCII at ' + bad);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = buildDryRun(fs.readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (cur !== out) { console.error('063_local_line_guard_dryrun.sql drifted from 063 - regenerate'); process.exit(1); }
    console.log('063 dry run matches 063');
  } else {
    fs.writeFileSync(TARGET, out);
    console.log('wrote', path.relative(process.cwd(), TARGET), out.length, 'chars');
  }
}
