// Generates the two dry runs of 090 FROM their sources (090_locations_clean_merge.sql and its rollback):
//   node worker/migrations/drafts/tools/build-090.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-090.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): a dry run is worth something only if it runs EXACTLY the owner's statements.
// tests/sql-090-drafts.test.js fails on drift; tms-auditor/test/plan-090.test.mjs runs them on the production-shaped copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// 090 is a draft: its files live in drafts/ until the owner runs it (CLAUDE.md rule 5), then one up
export const DIR = fs.existsSync(path.resolve(HERE, '..', '090_locations_clean_merge.sql')) ? path.resolve(HERE, '..') : path.resolve(HERE, '..', '..');
export const SOURCE = '090_locations_clean_merge.sql';
export const ROLLBACK = '090_locations_clean_merge_rollback.sql';

// what the block left, read the same way after 090 and after its rollback (loc_090_before may be gone)
const RAN = `format('trigger %s, check %s, merge %s, kept %s, not code %s',
    (SELECT count(*) FROM pg_trigger WHERE tgname = 'locations_clean'),
    (SELECT count(*) FROM pg_constraint WHERE conname = 'locations_country_iso'),
    CASE WHEN to_regprocedure('public.entity_merge(text,bigint,bigint,text)') IS NULL THEN 'no' ELSE 'yes' END,
    CASE WHEN to_regclass('public.loc_090_before') IS NULL THEN 'none' ELSE
      (xpath('//n/text()', query_to_xml('SELECT count(*) AS n FROM public.loc_090_before', false, false, '')))[1]::text END,
    (SELECT count(*) FROM public.locations WHERE country IS NOT NULL AND country !~ '^[A-Z]{2}$'))`;

export const DRY = {
  source: SOURCE, target: '090_locations_clean_merge_dryrun.sql', name: 'DRY RUN 090',
  header: `-- 090 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-090.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND (tests/sql-090-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056). ASCII only. RUN after 15:00, before ${SOURCE}.
-- EXPECTED (the red ERROR is deliberate): NOTICE "090 OK | kept ... rows in loc_090_before | ..." and then
--   ERROR: P0001: DRY RUN 090 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  090 ran:
--   trigger 1, check 1, merge yes, kept <rows>, not code 0
--   Anything else (an ERROR from one of 090's guards or proofs): do NOT run 090, copy the message to the coordinator.`,
  epilogue: `  res := '090 ran: ' || ${RAN};`,
};

export const RB_DRY = {
  source: ROLLBACK, target: '090_locations_clean_merge_rollback_dryrun.sql', name: 'DRY RUN 090 ROLLBACK',
  header: `-- 090 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-090.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "090 ROLLBACK OK | ..." then ERROR: P0001: DRY RUN 090 ROLLBACK finished - EVERYTHING UNDONE ...
--   rollback ran: trigger 0, check 0, merge no, kept none, not code <the full names are back>`,
  epilogue: `  res := 'rollback ran: ' || ${RAN};`,
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const rb = fs.readFileSync(path.join(DIR, ROLLBACK), 'utf8');
  return { [DRY.target]: buildDryRun(src, DRY), [RB_DRY.target]: buildDryRun(rb, RB_DRY) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
