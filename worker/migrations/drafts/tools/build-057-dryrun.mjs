// Scenario H reads the sequences with D's own definition (one entry of FP, never a second copy).
function seqFpIntoTmp() {
  const e = FP.find(([name]) => name === 'sequences');
  if (!e) throw new Error('FP has no «sequences» entry — scenario H needs it');
  return `execute $fp$${e[2]}$fp$ into fp_tmp;`;
}

// The md5 R2 accepts as «the text 057 wrote» (its v_057_md5 constant): ONE literal, in R2.
export function r2Md5(r2src) {
  const m = /v_057_md5 constant text := '([0-9a-f]{32})';/.exec(r2src);
  if (!m) throw new Error('R2: v_057_md5 constant not found — the builder must be updated with R2');
  return m[1];
}

export function buildDryRun(src, r2src = fs.readFileSync(R2, 'utf8')) {
  const open = src.indexOf('\ndo $mig$\n');
  const close = src.lastIndexOf('\nend\n$mig$;');
  if (open < 0 || close < 0 || close < open) throw new Error('057: «do $mig$ … end $mig$;» not found — the builder must be updated with 057');
  // «declare … begin … end» of 057, untouched, closed as a nested block
  const body = src.slice(open + '\ndo $mig$\n'.length, close) + '\nend;';
  if (/\$mig\$|\$dry\$|\$fp\$/.test(body)) throw new Error('057 uses $mig$ / $dry$ / $fp$ inside its block — choose other tags');
  return HEADER + `
DO $dry$
DECLARE
  ok            int := 0;
  bad           int := 0;
  res           text[] := '{}';
  fp_before     text[] := '{}';
  fp_after      text[] := '{}';
  fp_tmp        text;
  fp_rev_before text;
  fp_rev_after  text;
  b54_sql       text;
  b54_before    bigint;
  b54_after     bigint;
  b54_red       numeric;
  f_client      bigint;
  f_loc1        bigint;
  f_loc2        bigint;
  f_txt         text;
  f_hint        text;
BEGIN` + PROLOGUE + body + '\n' + EPILOGUE.replaceAll('__R2_057_MD5__', r2Md5(r2src)).replace('__SEQ_FP_INTO_TMP__', seqFpIntoTmp()) + `END
$dry$;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = buildDryRun(fs.readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (cur !== out) { console.error('057_stock_lots_dryrun.sql drifted from 057 — run: node worker/migrations/drafts/tools/build-057-dryrun.mjs'); process.exit(1); }
    console.log('057 dry run: in sync with 057');
  } else {
    fs.writeFileSync(TARGET, out);
    console.log(`057 dry run: ${out.split('\n').length} lines → ${path.relative(process.cwd(), TARGET)}`);
  }
}
