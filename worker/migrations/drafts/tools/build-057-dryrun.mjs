//   node worker/migrations/drafts/tools/build-057-dryrun.mjs          (writes the file)
//   node worker/migrations/drafts/tools/build-057-dryrun.mjs --check  (exit 1 if the committed file drifted)
// Why generated, never hand-copied (principle 3): the dry run is only worth anything if it runs EXACTLY the
