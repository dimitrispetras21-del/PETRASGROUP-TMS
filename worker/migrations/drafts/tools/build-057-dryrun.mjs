// scenarios that each report OK / FAIL / ERROR without stopping the others, and a final RAISE EXCEPTION
// that carries the result line and undoes all of it. ASCII outside 057's body: the owner pastes it from a
// clipboard that has mangled Greek before (pbcopy without UTF-8); 057's own texts stay as written.
