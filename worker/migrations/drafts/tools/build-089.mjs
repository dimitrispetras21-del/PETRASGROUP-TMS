// Generates the dry run, the rollback and the rollback's dry run of 089 FROM its source (089_plan_partner_rate_anodos.sql):
//   node worker/migrations/drafts/tools/build-089.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-089.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 089 applied - it reads them (and the md5 before / after) from the source, never a hand copy. The schema part
// of the rollback (the trigger, its function, the CHECK, the column, B-54) is written here once.
// tests/sql-089-drafts.test.js fails on drift; tms-auditor/test/plan-089.test.mjs runs them on the production-shaped copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// 089 is a draft: its files live in drafts/ until the owner runs it (CLAUDE.md rule 5), then one up
export const DIR = fs.existsSync(path.resolve(HERE, '..', '089_plan_partner_rate_anodos.sql')) ? path.resolve(HERE, '..') : path.resolve(HERE, '..', '..');
export const SOURCE = '089_plan_partner_rate_anodos.sql';
export const ROLLBACK = '089_plan_partner_rate_anodos_rollback.sql';
const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;
export const UPDATE = 'public.plan_rt_update(jsonb,text,text)';
export const SEGJSON = 'public.plan_h_seg_json(bigint)';

// The facts of the source, read once: the hunk constants, the live md5 (PART 0) and the generated md5 (PART 2)
export function facts(src) {
  const consts = Object.fromEntries([...src.matchAll(/^ {2}([a-z0-9_]+) CONSTANT text := \$h\$([\s\S]*?)\$h\$;$/gm)].map((m) => [m[1], m[2]]));
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part2 = src.slice(src.indexOf('===== PART 2'), src.indexOf('===== PART 3'));
  const live = Object.fromEntries([...part0.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', '([0-9a-f]{32})'\)/g)].map((m) => [m[1], m[2]]));
  const gen = [...part2.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', ARRAY\[([a-z0-9_, ]+)\], ARRAY\[([a-z0-9_, ]+)\], '([0-9a-zA-Z_]+)'\)/g)]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (gen.length !== 2 || gen.some((g) => !live[g.sig] || g.a.length !== g.b.length || [...g.a, ...g.b].some((k) => !(k in consts)))) {
    throw new Error(`${SOURCE}: PART 0 / PART 2 are not the two functions with their hunks`);
  }
  const a = src.indexOf('  -- the hunks:'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the hunk block was not found`);
  return { consts, live, gen, hunks: src.slice(a, b) };
}

// The text 089 writes, from a live text (the PGlite test derives the md5 of PART 2 with it)
export function applyHunks(text, g, consts) {
  let out = text;
  g.a.forEach((k, i) => {
    const n = out.split(consts[k]).length - 1;
    if (n !== 1) throw new Error(`${g.sig}: hunk ${k} found ${n} times`);
    out = out.replace(consts[k], () => consts[g.b[i]]);
  });
  return out;
}

export const DRY = {
  source: SOURCE, target: '089_plan_partner_rate_anodos_dryrun.sql', name: 'DRY RUN 089',
  header: `-- 089 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-089.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND (tests/sql-089-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056), the column, the CHECK and the trigger included. ASCII only.
-- EXPECTED (the red ERROR is deliberate): NOTICE "089 OK: rt_vehicle_segments.partner_rate_anodos ..." and then
--   ERROR: P0001: DRY RUN 089 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  089 ran:
--   update GEN_UPDATE, seg_json GEN_SEGJSON
--   Anything else (an ERROR from one of 089's guards or proofs): do NOT run 089, copy the message to the coordinator.`,
  epilogue: `  res := format('089 ran: update %s, seg_json %s', ${md5Of(UPDATE)}, ${md5Of(SEGJSON)});`,
};

export function buildRollback(src) {
  const f = facts(src);
  const blocks = f.gen.map((g) => `  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${g.sig}');
  IF md5(p.prosrc) <> '${g.m}' THEN
    RAISE EXCEPTION '089 rollback: ${g.sig} is not the text 089 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '089 rollback: a hunk of 089 is not in ${g.sig} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live[g.sig]}' THEN
    RAISE EXCEPTION '089 rollback: ${g.sig} would not be its text before 089 (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE %s %s %s SET search_path = public AS %L',
    split_part('${g.sig}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
    (SELECT lanname FROM pg_language WHERE oid = p.prolang),
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  IF ${md5Of(g.sig)} <> '${f.live[g.sig]}'
     OR (SELECT proacl::text FROM pg_proc WHERE oid = p.oid) IS DISTINCT FROM p.proacl::text THEN
    RAISE EXCEPTION '089 rollback proof: ${g.sig} is not back to its text before 089 with its rights';
  END IF;`).join('\n');
  return `-- 089 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-089.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. Everything 089 did, in reverse: plan_rt_update and plan_h_seg_json back to their texts before
-- 089 byte for byte (the hunks of 089 in reverse, md5-proven), the trigger and its function dropped, the CHECK and the
-- column dropped, B-54 back. The ANODOS parts typed since 089 are LOST (the fees stay: partner_rate is the whole fee,
-- so the money of every trip is unchanged); the NOTICE names each trip with its part, to type it again if 089 runs
-- again. The audit_log rows stay (history).
-- Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "089 ROLLBACK OK: ... splits dropped".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype; v_trg0 int; v_trg1 int; v_b54 int; v_lost int; v_list text;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = 'public.rt_vehicle_segments'::regclass AND attname = 'partner_rate_anodos' AND NOT attisdropped)
     OR to_regprocedure('public.plan_seg_rate_split()') IS NULL THEN
    RAISE EXCEPTION '089 rollback: 089 is not applied (column or trigger function missing) - stop';
  END IF;
  SELECT count(*) INTO v_trg0 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  SELECT red_value INTO v_b54 FROM monitoring.checks WHERE id = 'B-54';
  IF v_b54 IS DISTINCT FROM v_trg0 THEN
    RAISE EXCEPTION '089 rollback: B-54 holds % but % triggers are enabled - stop, re-measure', v_b54, v_trg0;
  END IF;
  -- what is lost, named (principle 1): the trip, its fee and its ANODOS part
  SELECT count(*), string_agg(r.code || ' ' || g.partner_rate || '/' || g.partner_rate_anodos, ', ' ORDER BY r.code, g.id)
    INTO v_lost, v_list
    FROM public.rt_vehicle_segments g JOIN public.ct_round_trips r ON r.id = g.rt_id WHERE g.partner_rate_anodos IS NOT NULL;
  -- the functions first: plan_h_seg_json (sql) names the column in its body
${blocks}
  DROP TRIGGER plan_seg_rate_split ON public.rt_vehicle_segments;
  DROP FUNCTION public.plan_seg_rate_split();
  ALTER TABLE public.rt_vehicle_segments DROP CONSTRAINT seg_partner_rate_anodos;
  ALTER TABLE public.rt_vehicle_segments DROP COLUMN partner_rate_anodos;
  SELECT count(*) INTO v_trg1 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  IF v_trg1 <> v_trg0 - 1 THEN RAISE EXCEPTION '089 rollback proof: triggers % -> % (one less)', v_trg0, v_trg1; END IF;
  UPDATE monitoring.checks SET red_value = v_trg1 WHERE id = 'B-54';
  RAISE NOTICE '089 ROLLBACK OK: % splits dropped (the fees stay): %; triggers %', v_lost, coalesce(v_list, 'none'), v_trg1;
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '089_plan_partner_rate_anodos_rollback_dryrun.sql', name: 'DRY RUN 089 ROLLBACK',
  header: `-- 089 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-089.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "089 ROLLBACK OK ..." then ERROR: P0001: DRY RUN 089 ROLLBACK finished - EVERYTHING UNDONE ...
--   update LIVE_UPDATE, seg_json LIVE_SEGJSON`,
  epilogue: DRY.epilogue.replace('089 ran:', 'rollback ran:'),
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const f = facts(src);
  const rb = buildRollback(src);
  // the dry runs' headers name the md5 the run must end on (one fact each: PART 2 / PART 0 of the source)
  const gen = Object.fromEntries(f.gen.map((g) => [g.sig, g.m]));
  const dry = { ...DRY, header: DRY.header.replace('GEN_UPDATE', gen[UPDATE]).replace('GEN_SEGJSON', gen[SEGJSON]) };
  const rbDry = { ...RB_DRY, header: RB_DRY.header.replace('LIVE_UPDATE', f.live[UPDATE]).replace('LIVE_SEGJSON', f.live[SEGJSON]) };
  return { [DRY.target]: buildDryRun(src, dry), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, rbDry) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
