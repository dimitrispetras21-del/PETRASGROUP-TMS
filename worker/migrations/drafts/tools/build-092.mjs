export function buildRollback(src) {
  const f = facts(src);
  const blocks = f.gen.map((g) => `  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${g.sig}');
  IF md5(p.prosrc) <> '${g.m}' THEN
    RAISE EXCEPTION '092 rollback: ${g.sig} is not the text 092 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '092 rollback: a hunk of 092 is not in ${g.sig} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live[g.sig]}' THEN
    RAISE EXCEPTION '092 rollback: ${g.sig} would not be its live text (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE plpgsql %s %s SET search_path = public AS %L',
    split_part('${g.sig}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  IF ${md5Of(g.sig)} <> '${f.live[g.sig]}'
     OR (SELECT proacl::text FROM pg_proc WHERE oid = p.oid) IS DISTINCT FROM p.proacl::text THEN
    RAISE EXCEPTION '092 rollback proof: ${g.sig} is not back to its live text with its rights';
  END IF;`).join('\n');
  return `-- 092 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-092.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. plan_vs_set_day and plan_vs_state back to their live texts of 1/11 byte for byte (the hunks of
-- 092 in reverse, md5-proven): the national desk sets the Veroia day only again (no pallets), and /plan/vs-state
-- answers no cross_dock_date (the board's mark of a truck on another day goes quiet). Pallets, audit rows and notices
-- already written (vs_pallets_set) STAY: they are what was done and what the desk was told. Only with an explicit yes.
-- ASCII. ONE DO block.
-- EXPECTED: NOTICE "092 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
${blocks}
  RAISE NOTICE '092 ROLLBACK OK';
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '092_plan_vs_pallets_day_rollback_dryrun.sql', name: 'DRY RUN 092 ROLLBACK',
  header: `-- 092 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-092.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "092 ROLLBACK OK" then ERROR: P0001: DRY RUN 092 ROLLBACK finished - EVERYTHING UNDONE ...
--   set_day c89e5533d8e9f5d0fcfeefcc2674c353, vs_state 99175b659207c5019f1599ed389f1895`,
  epilogue: DRY.epilogue.replace('092 ran:', 'rollback ran:'),
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const rb = buildRollback(src);
  // the dry run's header names the md5 the run must end on (one fact: PART 1 + 2 of the source)
  const [d, s] = facts(src).gen.map((g) => g.m);
  const dry = { ...DRY, header: DRY.header.replace('GEN_D', d).replace('GEN_S', s) };
  return { [DRY.target]: buildDryRun(src, dry), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, RB_DRY) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
