// Generates the two 069 dry runs FROM their sources:
//   069_hub_day_once.sql        -> 069_hub_day_once_dryrun.sql
//   069_hub_day_once_repair.sql -> 069_hub_day_once_repair_dryrun.sql
//   node worker/migrations/drafts/tools/build-069-dryruns.mjs          (writes both)
//   node worker/migrations/drafts/tools/build-069-dryruns.mjs --check  (exit 1 if a committed file drifted)
// Why generated, never hand-copied (principle 3): a dry run is only worth anything if it runs EXACTLY the
// statements the owner will run. tests/sql-069-drafts.test.js fails when a committed dry run differs.
// Shape (as 063/066): ONE DO $dry$ block - the source's DO block VERBATIM as a nested block (its guards and
// proofs raise their own messages and stop everything), a read of what it did, and a final RAISE EXCEPTION
// that carries the result line and undoes all of it. The sources are ASCII only, so the outputs are.
