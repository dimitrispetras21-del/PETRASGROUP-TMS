// Generates the four dry runs of 097 / 097b FROM their sources:
//   node worker/migrations/drafts/tools/build-097.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-097.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): a dry run is worth something only if it runs EXACTLY the owner's statements - the
// source's DO block verbatim, nested (build-073-dryrun.mjs), then a read of what it did, then a deliberate error
// that undoes all of it. tests/sql-097-drafts.test.js fails on drift; tms-auditor/test/rt-097.test.mjs runs every
// file on the production-shaped copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// drafts/ until the owner runs them, then one up (CLAUDE.md rule 5): the builder stays here
const DRAFTS = path.resolve(HERE, '..');
export const DIR = fs.existsSync(path.join(DRAFTS, '097_rt_split_vehicle_recheck.sql')) ? DRAFTS : path.resolve(DRAFTS, '..');

const TRIGGERS = `(SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = c.relnamespace
      WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public')`;
const SPLIT = `(SELECT count(*) FROM public.orders ex
      JOIN public.orders im ON im.legacy_id = ex.matched_import_id AND im.deleted_at IS NULL
      JOIN public.ct_rt_legs le ON le.order_id = ex.id JOIN public.ct_round_trips re ON re.id = le.rt_id AND re.status <> 'cancelled'
      JOIN public.ct_rt_legs li ON li.order_id = im.id JOIN public.ct_round_trips ri ON ri.id = li.rt_id AND ri.status <> 'cancelled'
     WHERE ex.deleted_at IS NULL AND ex.direction = 'Export' AND re.id <> ri.id)`;
const RULE = `res := format('%s: trigger rt_y_link_split_vehicle %s, public triggers %s, B-54 %s',
    '__WHO__', CASE WHEN EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'rt_y_link_split_vehicle') THEN 'yes' ELSE 'no' END,
    ${TRIGGERS}, (SELECT red_value FROM monitoring.checks WHERE id = 'B-54'));`;
const REPAIR = `res := format('%s: split pairs %s, RT-1283 %s, RT-1242 %s',
    '__WHO__', ${SPLIT},
    (SELECT status FROM public.ct_round_trips WHERE id = 285), (SELECT status FROM public.ct_round_trips WHERE id = 244));`;

const head = (src, name, expect) => `-- ${name} - GENERATED by worker/migrations/drafts/tools/build-097.mjs from ${src}.
-- DO NOT EDIT BY HAND: edit the source and regenerate (tests/sql-097-drafts.test.js fails on any drift).
-- WHAT: the source's DO block verbatim (its guards and proofs raise their own messages), a read of what it did, and
--   a DELIBERATE ERROR at the end: ONE DO block = ONE statement, so the error undoes everything (lesson 056).
-- WHEN: after 15:00, right before the source. ASCII only.
-- EXPECTED (the red ERROR is deliberate): ERROR: P0001: ${name} finished - EVERYTHING UNDONE, nothing kept. The block ran
--   to its end  ||  ${expect}
--   Anything else (an ERROR from a guard or proof of the source): do NOT run the source, copy the message.`;

export const PAIRS = [
  { source: '097_rt_split_vehicle_recheck.sql', target: '097_rt_split_vehicle_recheck_dryrun.sql', name: 'DRY RUN 097',
    header: head('097_rt_split_vehicle_recheck.sql', 'DRY RUN 097', '097 ran: trigger rt_y_link_split_vehicle yes, public triggers T+1, B-54 T+1 (T = 60 on 2/11)'),
    epilogue: '  ' + RULE.replace('__WHO__', '097 ran') },
  { source: '097_rt_split_vehicle_recheck_rollback.sql', target: '097_rt_split_vehicle_recheck_rollback_dryrun.sql', name: 'DRY RUN 097 ROLLBACK',
    header: head('097_rt_split_vehicle_recheck_rollback.sql', 'DRY RUN 097 ROLLBACK', 'rollback ran: trigger rt_y_link_split_vehicle no, public triggers T-1, B-54 T-1'),
    epilogue: '  ' + RULE.replace('__WHO__', 'rollback ran') },
  { source: '097b_rt_split_repair.sql', target: '097b_rt_split_repair_dryrun.sql', name: 'DRY RUN 097b',
    header: head('097b_rt_split_repair.sql', 'DRY RUN 097b', '097b ran: split pairs 0, RT-1283 cancelled, RT-1242 cancelled'),
    epilogue: '  ' + REPAIR.replace('__WHO__', '097b ran') },
  { source: '097b_rt_split_repair_rollback.sql', target: '097b_rt_split_repair_rollback_dryrun.sql', name: 'DRY RUN 097b ROLLBACK',
    header: head('097b_rt_split_repair_rollback.sql', 'DRY RUN 097b ROLLBACK', 'rollback ran: split pairs 2, RT-1283 planned, RT-1242 closed'),
    epilogue: '  ' + REPAIR.replace('__WHO__', 'rollback ran') },
];

export const buildAll = (dir = DIR) => PAIRS.map((p) => ({ ...p, out: buildDryRun(fs.readFileSync(path.join(dir, p.source), 'utf8'), p) }));

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let drift = 0;
  for (const p of buildAll()) {
    const target = path.join(DIR, p.target);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== p.out) { console.error('drift: ' + p.target); drift++; }
    } else fs.writeFileSync(target, p.out);
  }
  console.log(check ? `${drift} drift` : `wrote ${PAIRS.length} dry runs`);
  process.exit(drift ? 1 : 0);
}
