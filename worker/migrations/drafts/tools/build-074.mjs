const md5 = (x) => crypto.createHash('md5').update(x, 'utf8').digest('hex');
const b64 = (x) => Buffer.from(x, 'utf8').toString('base64');
const txt = (x) => (x == null ? 'NULL' : /^[\x20-\x7e\n]*$/.test(x) && !x.includes('$m$') ? `$m$${x}$m$`
  : `convert_from(decode('${b64(x)}', 'base64'), 'UTF8')`);
const list = (xs) => xs.map((x) => `'${x}'`).join(', ');
const num = (v) => { if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`); return String(v); };

export function build074b() {
  const { checks, errors } = loadChecks();
  if (errors.length) throw new Error('catalog lint: ' + errors.join('; '));
  for (const [id, o] of Object.entries(OLD)) {
    if (md5(o.sql) !== o.md5 || md5(o.ids_sql || '') !== o.ids_md5) throw new Error(`${id}: the kept live text is not the measured one`);
  }
  const mine = NEW_IDS.map((id) => checks.find((c) => c.id === id));
  const changed = REWRITTEN_IDS.map((id) => checks.find((c) => c.id === id));
  if ([...mine, ...changed].some((c) => !c)) throw new Error('missing check file');
  const all8 = [...mine, ...changed];
  const rows = mine.map((c) => `    (${[txt(c.id), txt(c.title), `ARRAY[${c.flows.map(txt).join(',')}]::text[]`, txt(c.sql), txt(c.ids_sql),
    txt(c.entity_table), txt(c.red_op), num(c.red_value), c.baseline == null ? 'NULL' : num(c.baseline), txt(c.severity), txt(c.schedule),
    c.is_queue, txt(c.impact), txt(c.next_step), txt(c.exceptions), txt(c.tolerance), c.enabled, txt(c.disabled_reason)].join(',\n     ')})`);
  const updates = changed.map((c) => `  UPDATE monitoring.checks SET sql_text = ${txt(c.sql)},
         ids_sql = ${txt(c.ids_sql)}, exceptions = ${txt(c.exceptions)}
   WHERE id = '${c.id}' AND md5(sql_text) = '${OLD[c.id].md5}' AND md5(coalesce(ids_sql, '')) = '${OLD[c.id].ids_md5}';
  GET DIAGNOSTICS v_k = ROW_COUNT;
  IF v_k <> 1 THEN RAISE EXCEPTION '074b: ${c.id} is not the live text measured 28/10 (md5 ${OLD[c.id].md5}) - stop, re-measure'; END IF;`).join('\n');
  const proof = all8.map((c) => `      ('${c.id}', '${md5(c.sql)}', '${md5(c.ids_sql || '')}', ${c.enabled})`).join(',\n');
  const done = `074b OK: ${NEW_IDS.length} new checks (B-95..B-99), ${REWRITTEN_IDS.length} rewritten (${REWRITTEN_IDS.join(', ')}), the runner reads day L, every check 0 today`;
  const body = `DECLARE
  v_k int; v_trg0 int; v_g record; v_v numeric; v_sql text; v_ids text; v_a text[];
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  -- 0. GUARDS: 074 applied (the checks read its day L and its bridges); none of the new checks exists yet
  IF to_regclass('public.plan_cutover_log') IS NULL OR to_regprocedure('public.plan_bridge_sync(bigint,text)') IS NULL
     OR NOT EXISTS (SELECT 1 FROM public.plan_config WHERE id = 1) THEN
    RAISE EXCEPTION '074b: 074 must be applied first (day L in plan_config)';
  END IF;
  IF EXISTS (SELECT 1 FROM monitoring.checks WHERE id IN (${list(NEW_IDS)})) THEN
    RAISE EXCEPTION '074b: already applied (a check B-95..B-99 exists) - stop, re-measure';
  END IF;
  SELECT count(*) INTO v_trg0 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';

  -- 1. THE AUDITOR READS DAY L. plan_config is RLS on (074a): without SELECT and a read policy the runner reads 0
  --    rows, day L is NULL inside every check, and B-95..B-99 stay green for ever (principle 1). 074a's Task B1 gives
  --    both; they are made sure of here (idempotent), and proven below by READING the row as the runner.
  GRANT SELECT ON public.plan_config TO tms_check_runner, tms_reader;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'plan_config' AND policyname = 'monitor_read') THEN
    CREATE POLICY monitor_read ON public.plan_config FOR SELECT TO tms_check_runner, tms_reader USING (true);
  END IF;

  -- 2. THE ${NEW_IDS.length} NEW CHECKS (text = tms-auditor/checks/<id>.sql, generated; md5-proven below)
  INSERT INTO monitoring.checks (id, title, flows, sql_text, ids_sql, entity_table, red_op, red_value, baseline, severity,
    schedule_tag, is_queue, impact, next_step, exceptions, tolerance, enabled, disabled_reason) VALUES
${rows.join(',\n')};
  GET DIAGNOSTICS v_k = ROW_COUNT;
  IF v_k <> ${NEW_IDS.length} THEN RAISE EXCEPTION '074b: % checks inserted, expected ${NEW_IDS.length}', v_k; END IF;

  -- 3. E17: ${REWRITTEN_IDS.join(', ')} learn day L (each only from its live text: md5 guard in the WHERE)
${updates}

  -- 4. PROOFS: the text and the on/off are the file's; each check passes the guard of monitoring.run_checks, runs as
  --    the auditor's role and says 0 today; its ids too (073b's proof, the same rules)
  FOR v_g IN SELECT * FROM (VALUES
${proof}
    ) p(id, m_sql, m_ids, on_) LOOP
    IF (SELECT md5(sql_text) <> v_g.m_sql OR md5(coalesce(ids_sql, '')) <> v_g.m_ids OR enabled <> v_g.on_
          FROM monitoring.checks WHERE id = v_g.id) THEN
      RAISE EXCEPTION '074b proof: % is not the text (or the on/off) of its file', v_g.id;
    END IF;
    SELECT sql_text, ids_sql INTO v_sql, v_ids FROM monitoring.checks WHERE id = v_g.id;
    PERFORM monitoring.check_sql_guard(v_sql);
    IF v_ids IS NOT NULL THEN PERFORM monitoring.check_sql_guard(v_ids); END IF;
    SET LOCAL ROLE tms_check_runner;
    EXECUTE v_sql INTO v_v;
    v_a := '{}';
    IF v_ids IS NOT NULL THEN EXECUTE v_ids INTO STRICT v_a; END IF;
    RESET ROLE;
    IF v_v IS DISTINCT FROM 0 THEN RAISE EXCEPTION '074b proof: % gives % today, expected 0', v_g.id, v_v; END IF;
    IF v_a IS NULL THEN RAISE EXCEPTION '074b proof: % ids returned NULL', v_g.id; END IF;
    IF cardinality(v_a) IS DISTINCT FROM 0 THEN RAISE EXCEPTION '074b proof: % names % today, expected none', v_g.id, v_a; END IF;
  END LOOP;
  -- measured, not only the catalog (principle 2): the runner reads the one row of plan_config
  SET LOCAL ROLE tms_check_runner;
  SELECT count(*) INTO v_k FROM public.plan_config WHERE cutover_day IS NOT NULL;
  RESET ROLE;
  IF v_k <> 1 THEN RAISE EXCEPTION '074b proof: the runner reads % rows of plan_config (0 = RLS without its policy)', v_k; END IF;
  IF (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = c.relnamespace
       WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public') <> v_trg0 THEN
    RAISE EXCEPTION '074b proof: a trigger appeared';
  END IF;
  RAISE NOTICE '${done}';
`;
  const head = `-- 074b - NATIONAL v5, PHASE F5: THE AUDITOR LEARNS DAY L (plan Task C, spec 8). GENERATED by
-- worker/migrations/drafts/tools/build-074.mjs from tms-auditor/checks/B-95..B-99 (new) and ${REWRITTEN_IDS.join(', ')} (E17).
-- DO NOT EDIT BY HAND (tests/sql-074-drafts.test.js fails on drift). ASCII only (Greek texts are base64). ONE DO block.
-- Runbook R-6, right after 074 and its verify, Friday L-1 after 15:00, with the owner's explicit yes:
--   1. 074b_plan_cutover_monitoring_dryrun.sql   (this block + a deliberate error: NOTHING kept)
--   2. 074b_plan_cutover_monitoring.sql          (this file)
-- Who learns: every new check notifies owner + national desk through 048, as every P1 / P2 of the catalog.
-- REVERSE: 074b_plan_cutover_monitoring_rollback.sql (BEFORE 074's rollback).
-- EXPECTED: NOTICE "${done}".
`;
  const main = `${head}\nDO $do$\n${body}END $do$;\n`;
  const dry = `-- 074b DRY RUN - GENERATED by worker/migrations/drafts/tools/build-074.mjs. DO NOT EDIT BY HAND.
-- 074b's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "074b OK: ..." then ERROR: P0001: DRY RUN 074b finished - EVERYTHING UNDONE, nothing kept.

DO $dry$
${body}  RAISE EXCEPTION 'DRY RUN 074b finished - EVERYTHING UNDONE, nothing kept.';
END
$dry$;
`;
  const openOf = `state IN ('new', 'confirmed', 'recurred')
     AND (check_id IN (${list(NEW_IDS)})
          OR incident_key IN (${list(NEW_IDS.flatMap((id) => [`MECH:check:${id}`, `MECH:stale:${id}`]))}))`;
  const restores = REWRITTEN_IDS.map((id) => `  UPDATE monitoring.checks SET sql_text = ${txt(OLD[id].sql)},
         ids_sql = ${txt(OLD[id].ids_sql)}, exceptions = ${txt(OLD[id].exceptions)} WHERE id = '${id}';
  IF (SELECT md5(sql_text) <> '${OLD[id].md5}' OR md5(coalesce(ids_sql, '')) <> '${OLD[id].ids_md5}' FROM monitoring.checks WHERE id = '${id}') THEN
    RAISE EXCEPTION '074b rollback proof: ${id} is not back to its live text';
  END IF;`).join('\n');
  const rollback = `-- 074b ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-074.mjs. DO NOT EDIT BY HAND.
-- B-95..B-99 out of the catalog (results removed, open incidents closed, as 073b's rollback), ${REWRITTEN_IDS.join(', ')} back to
-- their live text of 28/10 (md5-proven). The read of plan_config stays (074a's table; a read grant is harmless and
-- 074a's own rollback owns the table). BEFORE 074's rollback. Only with an explicit yes, after 15:00. ASCII. ONE DO block.
-- EXPECTED: NOTICE "074b ROLLBACK OK".
DO $do$
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  UPDATE monitoring.incidents SET state = 'resolved', resolved_verified_at = clock_timestamp(),
         state_changed_by = '074b rollback (check removed)', state_changed_at = clock_timestamp()
   WHERE ${openOf};
  DELETE FROM monitoring.results WHERE check_id IN (${list(NEW_IDS)});
  DELETE FROM monitoring.checks WHERE id IN (${list(NEW_IDS)});
${restores}
  IF EXISTS (SELECT 1 FROM monitoring.checks WHERE id IN (${list(NEW_IDS)})) THEN
    RAISE EXCEPTION '074b rollback proof: a check of 074b is left';
  END IF;
  IF EXISTS (SELECT 1 FROM monitoring.incidents WHERE ${openOf}) THEN
    RAISE EXCEPTION '074b rollback proof: an incident of B-95..B-99 is still open';
  END IF;
  RAISE NOTICE '074b ROLLBACK OK';
END $do$;
`;
  return { [FILES_074B[0]]: main, [FILES_074B[1]]: dry, [FILES_074B[2]]: rollback };
}

export function buildAll() {
  const out = {};
  for (const p of PAIRS) out[p.target] = buildDryRun(fs.readFileSync(path.join(DIR, p.source), 'utf8'), p);
  Object.assign(out, build074b());
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
