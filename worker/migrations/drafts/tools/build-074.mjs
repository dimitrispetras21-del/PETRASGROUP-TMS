//   node worker/migrations/drafts/tools/build-074.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): a dry run is only worth anything if it runs EXACTLY the statements the owner will run,
// and the check files are the ONE source of a check (047b, 073b). tests/sql-074-drafts.test.js fails on drift.
