export function buildVerify(src) {
  const f = facts(src);
  return `-- 098 VERIFY - GENERATED by worker/migrations/drafts/tools/build-098.mjs from ${SOURCE}. Read only (SELECT), one row.
-- DO NOT EDIT BY HAND (the md5 below are the migration's own; tests/sql-098-drafts.test.js fails on drift).
-- EXPECTED right after 098: applied = '098 in place', changed_texts 0, transfer_columns 4, transfer_stops 0,
--   linked_stops 0, waiting_at_point 0, shipments_refused 0, b54_matches true.
--   After 099 is in use: transfer_stops = the points where a truck handed a load over (each with its reason);
--   linked_stops = the loadings there (another truck's, or the same truck's for a part it keeps); waiting_at_point =
--   transfer stops that say "waits there".
SELECT CASE WHEN ${md5Of(PATCHED[0])} = '${f.gen[0].m}' THEN '098 in place' ELSE '098 NOT APPLIED' END AS applied,
       (SELECT count(*) FROM (VALUES
${f.gen.map((g) => `          ('${g.sig}', '${g.m}')`).join(',\n')}) v(sig, m)
         WHERE (SELECT md5(prosrc) FROM pg_proc WHERE oid = to_regprocedure(v.sig)) IS DISTINCT FROM v.m) AS changed_texts,
       ${N_COLUMNS} AS transfer_columns,
       (SELECT count(*) FROM public.rt_stops WHERE transfer_reason IS NOT NULL AND deleted_at IS NULL) AS transfer_stops,
       (SELECT count(*) FROM public.rt_stops WHERE transfer_from_stop_id IS NOT NULL AND deleted_at IS NULL) AS linked_stops,
       (SELECT count(*) FROM public.rt_stops WHERE transfer_waits AND deleted_at IS NULL) AS waiting_at_point,
       (SELECT count(*) FROM public.shipments s WHERE s.deleted_at IS NULL AND public.plan_shipment_problem(s.id) IS NOT NULL) AS shipments_refused,
       (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = c.relnamespace
         WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public') = (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') AS b54_matches;
`;
}

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const f = facts(src);
  const rb = buildRollback(src);
  const fill = (h, tag, arr) => ['L', 'S', 'P', 'U', 'C'].reduce((s, k, i) => s.replace(`${tag}_${k}`, arr[i]), h);
  const dry = { ...DRY, header: fill(DRY.header, 'GEN', f.gen.map((g) => g.m)) };
  const rbd = { ...RB_DRY, header: fill(RB_DRY.header, 'LIVE', PATCHED.map((s) => f.live[s])) };
  return { [DRY.target]: buildDryRun(src, dry), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, rbd), [VERIFY]: buildVerify(src) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
