const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;
const SIG = String.raw`public\.[a-z_]+\([a-z,\[\]]*\)`;
export const PATCHED = ['public.plan_leg_problem(bigint)', 'public.plan_shipment_problem(bigint)',
  'public.plan_split_piece(jsonb,text,text)', 'public.plan_rt_update(jsonb,text,text)', 'public.plan_h_vs_carriers(bigint,jsonb)'];
export const COLUMNS = ['transfer_reason', 'transfer_note', 'transfer_waits', 'transfer_from_stop_id'];
const N_COLUMNS = `(SELECT count(*) FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'rt_stops'
      AND column_name IN (${COLUMNS.map((c) => `'${c}'`).join(', ')}))`;

// The facts of the source, read once: the hunk constants, the live md5 (PART 0) and the generated md5 (PART 2)
export function facts(src) {
  const consts = Object.fromEntries([...src.matchAll(/^ {2}([a-z0-9_]+) CONSTANT text := \$h\$([\s\S]*?)\$h\$;$/gm)].map((m) => [m[1], m[2]]));
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part2 = src.slice(src.indexOf('===== PART 2'), src.indexOf('===== PART 3'));
  const live = Object.fromEntries([...part0.matchAll(new RegExp(`\\('(${SIG})', '([0-9a-f]{32})'\\)`, 'g'))].map((m) => [m[1], m[2]]));
  const gen = [...part2.matchAll(new RegExp(`\\('(${SIG})', ARRAY\\[([a-z0-9_, ]+)\\], ARRAY\\[([a-z0-9_, ]+)\\], '([0-9a-f]{32})'\\)`, 'g'))]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (gen.length !== PATCHED.length || gen.some((g, i) => g.sig !== PATCHED[i] || !live[g.sig] || g.a.length !== g.b.length
                                      || [...g.a, ...g.b].some((k) => !(k in consts)))) {
    throw new Error(`${SOURCE}: PART 0 / PART 2 are not the five functions with their measured hunks`);
  }
  const a = src.indexOf('  -- the hunks:'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the hunk block was not found`);
  return { consts, live, gen, hunks: src.slice(a, b) };
}

// The text 098 writes, from a live text (the PGlite test derives the md5 of PART 2 with it)
export function applyHunks(text, g, consts) {
  let out = text;
  g.a.forEach((k, i) => {
    const n = out.split(consts[k]).length - 1;
    if (n !== 1) throw new Error(`${g.sig}: hunk ${k} found ${n} times`);
    out = out.replace(consts[k], () => consts[g.b[i]]);
  });
  return out;
}

// what a run left: the five texts and the transfer columns (after a rollback: 0, so nothing else is read from them)
const epilogue = (label) => `  res := format('${label} leg %s, shipment %s, split %s, rt_update %s, carriers %s, transfer columns %s',
    ${PATCHED.map(md5Of).join(',\n    ')},
    ${N_COLUMNS});`;

