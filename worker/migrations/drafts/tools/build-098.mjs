export function buildRollback(src) {
  const f = facts(src);
  const blocks = f.gen.map((g) => `  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${g.sig}');
  SELECT lanname INTO v_lang FROM pg_language WHERE oid = p.prolang;
  IF md5(p.prosrc) <> '${g.m}' THEN
    RAISE EXCEPTION '098 rollback: ${g.sig} is not the text 098 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '098 rollback: a hunk of 098 is not in ${g.sig} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live[g.sig]}' THEN
    RAISE EXCEPTION '098 rollback: ${g.sig} would not be its live text (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE %s %s %s SET search_path = public AS %L',
    split_part('${g.sig}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid), v_lang,
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  IF ${md5Of(g.sig)} <> '${f.live[g.sig]}'
     OR (SELECT proacl::text FROM pg_proc WHERE oid = p.oid) IS DISTINCT FROM p.proacl::text THEN
    RAISE EXCEPTION '098 rollback proof: ${g.sig} is not back to its live text with its rights';
  END IF;`).join('\n');
  return `-- 098 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-098.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. The five functions back to the texts production held on 2/11, byte for byte (the hunks of 098 in
-- reverse, md5-proven), then the four columns of rt_stops dropped (their CHECKs and the index go with them). REFUSED
-- while any stop holds a transfer value: a transfer written by 099 would lose its reason and its link - roll back 099
-- first and move those loads back. Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "098 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype; v_lang text;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF ${N_COLUMNS} <> ${COLUMNS.length} THEN
    RAISE EXCEPTION '098 rollback: rt_stops does not have the four transfer columns - nothing to undo';
  END IF;
  IF EXISTS (SELECT 1 FROM public.rt_stops WHERE transfer_reason IS NOT NULL OR transfer_note IS NOT NULL OR transfer_waits
               OR transfer_from_stop_id IS NOT NULL) THEN
    RAISE EXCEPTION '098 rollback: a stop holds a transfer value - roll back 099 first, nothing changed';
  END IF;
${blocks}
  ALTER TABLE public.rt_stops ${COLUMNS.map((c) => `DROP COLUMN ${c}`).join(', ')};
  IF ${N_COLUMNS} <> 0 OR to_regclass('public.rt_stops_transfer_from') IS NOT NULL THEN
    RAISE EXCEPTION '098 rollback proof: a transfer column or its index is still there';
  END IF;
  PERFORM pg_notify('pgrst', 'reload schema');
  RAISE NOTICE '098 ROLLBACK OK';
END $do$;
`;
}

