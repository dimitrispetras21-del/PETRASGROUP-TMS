// Generates the dry run and the rollback of 077 FROM its source (077_plan_order_edit.sql):
//   node worker/migrations/drafts/tools/build-077.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-077.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 077 applied - it reads them (and the md5 before / after) from the source, never a hand copy.
// tests/sql-077-drafts.test.js fails on drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// The folder that holds the 077 files. 077 was executed 28/10 and left drafts/ (CLAUDE.md rule 5): the source and the
// generated files are one up, the builder stays here.
export const DIR = path.resolve(HERE, '..', '..');
export const SOURCE = '077_plan_order_edit.sql';
const SIG = 'public.plan_order_update(jsonb,text,text)';
const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;

// The facts of the source, read once: the hunk constants, the live md5 (PART 0) and the generated md5 (PART 2)
export function facts(src) {
  const a = src.indexOf('  -- the hunks:'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the hunk block was not found`);
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part2 = src.slice(src.indexOf('===== PART 2'), src.indexOf('===== PART 3'));
  const live = [...part0.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', '([0-9a-f]{32})'\)/g)].map((m) => ({ sig: m[1], m: m[2] }));
  const gen = [...part2.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', ARRAY\[([a-z0-9_, ]+)\], ARRAY\[([a-z0-9_, ]+)\], '([0-9a-f]{32})'\)/g)]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (live.length !== 1 || live[0].sig !== SIG || gen.length !== 1 || gen[0].sig !== SIG || gen[0].a.length !== gen[0].b.length) {
    throw new Error(`${SOURCE}: PART 0 / PART 2 are not plan_order_update with its hunks`);
  }
  return { hunks: src.slice(a, b), live: live[0].m, gen: gen[0] };
}

export const DRY = {
  source: SOURCE, target: '077_plan_order_edit_dryrun.sql', name: 'DRY RUN 077',
  header: `-- 077 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-077.mjs from 077_plan_order_edit.sql.
-- DO NOT EDIT BY HAND (tests/sql-077-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056). ASCII only.
-- EXPECTED (the red ERROR is deliberate): NOTICE "077 OK: plan_order_read (closed, Worker only), ..." and then
--   ERROR: P0001: DRY RUN 077 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  077 ran:
--   read yes, update 39d38711...
--   Anything else: do NOT run 077, copy the message to the coordinator.`,
  epilogue: `  res := format('077 ran: read %s, update %s',
    CASE WHEN to_regprocedure('public.plan_order_read(bigint,text)') IS NOT NULL THEN 'yes' ELSE 'NO' END, ${md5Of(SIG)});`,
};

export function buildRollback(src) {
  const f = facts(src);
  return `-- 077 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-077.mjs from 077_plan_order_edit.sql.
-- DO NOT EDIT BY HAND. plan_order_update back to its live text after 075 byte for byte (the hunks of 077 in reverse,
-- md5-proven), plan_order_read dropped. Points already added or removed through the form STAY (they are the user's
-- data, and the text of 075 edits them as any other point). The Worker route GET /plan/orders/:id then answers 503
-- schema_behind: roll the Worker back first. Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "077 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF to_regprocedure('public.plan_order_read(bigint,text)') IS NULL THEN
    RAISE EXCEPTION '077 rollback: 077 is not applied';
  END IF;
  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${SIG}');
  IF md5(p.prosrc) <> '${f.gen.m}' THEN
    RAISE EXCEPTION '077 rollback: ${SIG} is not the text 077 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...f.gen.b].reverse().join(', ')}], ARRAY[${[...f.gen.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '077 rollback: a hunk of 077 is not in ${SIG} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live}' THEN
    RAISE EXCEPTION '077 rollback: ${SIG} would not be its live text (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE plpgsql %s %s SET search_path = public AS %L',
    split_part('${SIG}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  DROP FUNCTION public.plan_order_read(bigint,text);
  PERFORM pg_notify('pgrst', 'reload schema');
  RAISE NOTICE '077 ROLLBACK OK';
END $do$;
`;
}

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  return { [DRY.target]: buildDryRun(src, DRY), '077_plan_order_edit_rollback.sql': buildRollback(src) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
