// Generates the 105 dry runs FROM their sources (the same shape as 073 / 101: buildDryRun):
//   105_rt_pnl_complete.sql          -> 105_rt_pnl_complete_dryrun.sql
//   105_rt_pnl_complete_rollback.sql -> 105_rt_pnl_complete_rollback_dryrun.sql
//   node worker/migrations/drafts/tools/build-105.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-105.mjs --check  (exit 1 if a committed file drifted)
// Why generated, never hand-copied (principle 3): a dry run is only worth anything if it runs EXACTLY the statements
// the owner will run. tests/sql-105-drafts.test.js fails on drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// drafts/ until the owner runs them, then one up (CLAUDE.md rule 5)
const dirOf = (f) => [path.resolve(HERE, '..'), path.resolve(HERE, '..', '..')].find((d) => fs.existsSync(path.join(d, f)));
const SOURCE = '105_rt_pnl_complete.sql', ROLLBACK = '105_rt_pnl_complete_rollback.sql';
const READ = `  res := format('105 ran: views %s, round trips %s, complete %s, loads that do not add up %s',
    (SELECT count(*) FROM pg_class WHERE oid IN (to_regclass('public.ct_v_rt_revenue_legs'), to_regclass('public.ct_v_rt_cost_cat'),
      to_regclass('public.ct_v_rt_complete'))),
    (SELECT count(*) FROM public.ct_v_rt_pnl),
    (SELECT count(*) FILTER (WHERE complete) FROM public.ct_v_rt_complete),
    (SELECT count(*) FROM (SELECT rt_id, sum(rev_intl + rev_natl) s FROM public.ct_v_rt_revenue_legs GROUP BY rt_id) a
      JOIN public.ct_v_rt_revenue r USING (rt_id) WHERE COALESCE(a.s, 0) <> r.revenue));`;
const RB_READ = `  res := format('105 rollback ran: 105 views left %s, ct_v_rt_revenue md5 %s',
    (SELECT count(*) FROM pg_class WHERE oid IN (to_regclass('public.ct_v_rt_revenue_legs'), to_regclass('public.ct_v_rt_cost_cat'),
      to_regclass('public.ct_v_rt_complete'))),
    md5(pg_get_viewdef('public.ct_v_rt_revenue'::regclass, true)));`;
export const DRY = {
  source: SOURCE, target: '105_rt_pnl_complete_dryrun.sql', name: 'DRY RUN 105', epilogue: READ,
  header: `-- 105 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-105.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND (tests/sql-105-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
--   undoes everything inside it. ASCII only.
-- WHAT: 105's own DO block, statement for statement (guards, the three views, ct_v_rt_revenue from its loads, the
--   rights, the before = after proofs), a read of the result, ENDING WITH A DELIBERATE ERROR: NOTHING is kept.
-- WHEN: AFTER 15:00 (the team works 05:30-14:30), BEFORE ${SOURCE}.
-- EXPECTED (the red ERROR is deliberate): a NOTICE "105 OK: ..." and then
--   ERROR: P0001: DRY RUN 105 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  105 ran:
--   views 3, round trips <as today>, complete <n>, loads that do not add up 0
--   Anything else (an ERROR from one of 105's guards or proofs): do NOT run 105, copy the message to the coordinator.`,
};
export const RB_DRY = {
  source: ROLLBACK, target: '105_rt_pnl_complete_rollback_dryrun.sql', name: 'DRY RUN 105 ROLLBACK', epilogue: RB_READ,
  header: `-- 105 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-105.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND (tests/sql-105-drafts.test.js fails on drift). ONE DO block = ONE statement. ASCII only.
-- WHEN: only after 105 ran, and only on the coordinator's word.
-- EXPECTED: NOTICE "105 ROLLBACK OK: ..." then ERROR: P0001: DRY RUN 105 ROLLBACK finished - EVERYTHING UNDONE ...
--   105 rollback ran: 105 views left 0, ct_v_rt_revenue md5 4b6fd9a9674d57d87c303d6500940f36`,
};

export function build() {
  const out = {};
  for (const pair of [DRY, RB_DRY]) {
    const dir = dirOf(pair.source);
    if (!dir) throw new Error('no source: ' + pair.source);
    out[path.join(dir, pair.target)] = buildDryRun(fs.readFileSync(path.join(dir, pair.source), 'utf8'), pair);
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let drift = 0;
  for (const [target, text] of Object.entries(build())) {
    if (check) { if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) { drift++; console.error('drift: ' + path.basename(target)); } }
    else fs.writeFileSync(target, text);
  }
  console.log(check ? `${drift} drift` : 'written');
  process.exit(drift ? 1 : 0);
}
