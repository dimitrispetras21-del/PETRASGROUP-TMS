export function buildRollback(src) {
  const f = facts(src);
  const blocks = f.gen.map((g) => `  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${g.sig}');
  IF md5(p.prosrc) <> '${g.m}' THEN
    RAISE EXCEPTION '087 rollback: ${g.sig} is not the text 087 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '087 rollback: a hunk of 087 is not in ${g.sig} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live[g.sig]}' THEN
    RAISE EXCEPTION '087 rollback: ${g.sig} would not be its live text (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE plpgsql %s %s SET search_path = public AS %L',
    split_part('${g.sig}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  IF ${md5Of(g.sig)} <> '${f.live[g.sig]}'
     OR (SELECT proacl::text FROM pg_proc WHERE oid = p.oid) IS DISTINCT FROM p.proacl::text THEN
    RAISE EXCEPTION '087 rollback proof: ${g.sig} is not back to its live text with its rights';
  END IF;`).join('\n');
  return `-- 087 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-087.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. plan_board (live text of 1/11) and plan_move_pieces (086's text) back byte for byte (the hunks
-- of 087 in reverse, md5-proven), then the helper plan_h_last_change dropped: the board loses last_change /
-- waiting_weeks / rate_history and target.hub is refused again. Marks set or cleared by target.hub STAY: they are
-- what the users did (a VS sent to the panel stays there). Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "087 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
${blocks}
  DROP FUNCTION public.plan_h_last_change(bigint);
  RAISE NOTICE '087 ROLLBACK OK';
END $do$;
`;
}

