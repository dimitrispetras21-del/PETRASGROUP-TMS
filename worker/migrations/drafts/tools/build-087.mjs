// Generates the dry run, the rollback and the rollback's dry run of 087 FROM its source (087_plan_board_reads_hub_mark.sql):
//   node worker/migrations/drafts/tools/build-087.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-087.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 087 applied - it reads them (and the md5 before / after) from the source, never a hand copy.
// tests/sql-087-drafts.test.js fails on drift; tms-auditor/test/plan-087.test.mjs runs them on the production-shaped copy.
