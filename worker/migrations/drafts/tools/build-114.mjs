const IN_DRAFTS = path.resolve(HERE, '..');
export const SOURCE = '114_plan_split_at_loading.sql';
export const DIR = fs.existsSync(path.join(IN_DRAFTS, SOURCE)) ? IN_DRAFTS : path.resolve(HERE, '..', '..');
