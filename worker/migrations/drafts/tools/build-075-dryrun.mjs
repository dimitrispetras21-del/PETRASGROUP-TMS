// node worker/migrations/drafts/tools/build-075-dryrun.mjs
// 075's dry run = 075's DO block verbatim + a deliberate error, so nothing is kept. Generated, never edited by hand:
// worker/test/migration-075.test.mjs fails when the two drift (principle 3).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function build075Dryrun(main) {
  // from the statement_timeout line: the dry run is bounded like 075
  const block = main.slice(main.indexOf("SET statement_timeout"));
  if (!block.startsWith("SET statement_timeout = '5s';\nDO $m$")) throw new Error('075: SET statement_timeout must precede the block');
  const end = 'END\n$m$;';
  if (!block.endsWith(end + '\n')) throw new Error('075: the block must end with END $m$;');
  return [
    "-- 075 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-075-dryrun.mjs. DO NOT EDIT BY HAND.",
    "-- 075's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.",
    '-- EXPECTED: NOTICE "075 OK | ..." then ERROR: P0001: DRY RUN 075 finished - EVERYTHING UNDONE, nothing kept.',
    '',
  ].join('\n') + block.replace(end, "  RAISE EXCEPTION 'DRY RUN 075 finished - EVERYTHING UNDONE, nothing kept';\n" + end);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const main = fs.readFileSync(path.join(DIR, '075_audit_actions.sql'), 'utf8');
  fs.writeFileSync(path.join(DIR, '075_audit_actions_dryrun.sql'), build075Dryrun(main));
  console.log('075_audit_actions_dryrun.sql written');
}
