// Generates worker/migrations/drafts/066_rt_group_base_join_dryrun.sql FROM 066_rt_group_base_join.sql.
//   node worker/migrations/drafts/tools/build-066-dryrun.mjs          (writes the file)
//   node worker/migrations/drafts/tools/build-066-dryrun.mjs --check  (exit 1 if the committed file drifted)
// Why generated, never hand-copied (principle 3): the dry run is only worth anything if it runs EXACTLY the
// statements 066 will run. A hand copy drifts the first time 066 is edited and then "proves" a migration nobody
// will execute. tms-auditor/test/dryrun-066.test.mjs fails when the committed file differs.
// Same shape as build-063-dryrun.mjs: ONE DO $dry$ block - a prologue that fingerprints data 066 must not touch,
// 066's DO block VERBATIM as a nested block (its guards and proofs raise their own messages and stop everything),
// an epilogue of scenarios that each report ok / FAIL / ERROR without stopping the others, and a final RAISE
// EXCEPTION that carries the result line and undoes all of it. 066 is ASCII only, so the whole file is.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = path.join(DRAFTS, '066_rt_group_base_join.sql');
export const TARGET = path.join(DRAFTS, '066_rt_group_base_join_dryrun.sql');

const OPEN = '\nDO $do$\n';
const CLOSE = '\nEND $do$;\n';

const HEADER = `-- 066 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-066-dryrun.mjs from 066_rt_group_base_join.sql.
-- DO NOT EDIT BY HAND: edit 066 and regenerate (tms-auditor/test/dryrun-066.test.mjs fails on any drift).
--
-- WHAT: 066's own DO block, statement for statement (every guard, change and proof, B-54 and B-77 run as
--   tms_check_runner), wrapped in ONE outer DO block that first fingerprints data 066 must not touch, then
--   checks the result, and ENDS WITH A DELIBERATE ERROR. The error rolls the whole block back: NOTHING it did
--   is kept (no function text, no B-77 row).
-- WHEN: the same evening, AFTER 15:00 (the team works 05:30-14:30), BEFORE 066_rt_group_base_join.sql. It
--   uses the same lock_timeout as 066 (5 s, then it gives up - run it again a little later).
-- WHY ONE DO BLOCK: the Supabase SQL editor is NOT atomic across statements (lesson 056), but ONE DO
--   block is ONE statement: its final error undoes everything inside it.
-- EXPECTED (the red ERROR is deliberate):
--   ERROR: P0001: DRY RUN 066 finished - EVERYTHING UNDONE, nothing kept. Result: 4 OK, 0 FAIL  ||  A ok ... | B ok triggers T = T, B-54 T | C ok ... | D ok B-77 = catalog, value 0 (ids )
--   (T = the live trigger count = B-54: 35 since 057 + 060 + 063.) D's value is B-77 on production - 0
--   after the 7/10 repair; another value is not a FAIL of the dry run (it measures data, not 066): copy it.
--   Anything with FAIL or ERROR in it: do NOT run 066, copy the panel to the coordinator.
--   ONE exception: "3 OK, 1 FAIL" where the FAIL is C alone (A, B, D ok). C fingerprints the orders, round
--   trips, legs, the auditor rows and every public sequence while the block runs, so ONE save by someone else
--   in those seconds turns it red - it fails closed, nothing was kept. Wait 5 minutes and run the dry run once
--   more; if C fails again, copy the panel to the coordinator.
--   A different message altogether ("066: ...", "066 proof: ...", a lock timeout) is the guard or proof of
--   066 that stopped - exactly what 066 itself would have said. Do NOT run 066.
-- AFTER: SELECT that nothing was kept - md5(pg_get_functiondef('public.rt_create_from_order()'::regprocedure))
--   is still 3f3a01204f7f4a4b6546e965fc231ae3, rt_link_split still 6189950c70b289fd5075afd17e28ecec, no B-77 row.
-- Scenarios: A 066's changes exist inside the block; B the trigger count did not move and B-54 equals it;
--   C data 066 must not touch is unchanged (orders, round trips, legs, every auditor row but B-77, every public
--   sequence's last_value); D B-77 is the catalog row and runs as tms_check_runner (its value reported).
`;

// Whole rows (to_jsonb), not a column list: the fingerprint must not name a column 066 does not guard, or a
// renamed column would kill the dry run before 066's own guard could speak.
const FP = `(SELECT md5(
    coalesce((SELECT string_agg(md5(to_jsonb(x)::text), ',' ORDER BY x.id) FROM public.orders x), '')
 || coalesce((SELECT string_agg(to_jsonb(x)::text, ',' ORDER BY x.id) FROM public.ct_round_trips x), '')
 || coalesce((SELECT string_agg(to_jsonb(x)::text, ',' ORDER BY x.id) FROM public.ct_rt_legs x), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, md5(sql_text), md5(coalesce(ids_sql, '')), red_value, baseline, enabled), ',' ORDER BY id) FROM monitoring.checks WHERE id <> 'B-77'), '')
 || coalesce((SELECT string_agg(s.sequencename || '=' || coalesce(s.last_value::text, '-'), ',' ORDER BY s.sequencename) FROM pg_sequences s WHERE s.schemaname = 'public'), '')))`;

const PROLOGUE = `DO $dry$
DECLARE
  ok int := 0; bad int := 0; res text[] := '{}';
  dry_fp_before text; dry_b54_before int; dry_trg_before int; dry_n int; dry_v numeric; dry_ids text[]; dry_sql text; dry_ids_sql text;
BEGIN
  -- the B-54 value and the trigger count 066 will meet, and the data it must leave alone
  SELECT red_value INTO dry_b54_before FROM monitoring.checks WHERE id = 'B-54';
  SELECT count(*) INTO dry_trg_before FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  SELECT ${FP} INTO dry_fp_before;

  -- ===== 066_rt_group_base_join.sql, its DO block verbatim (a nested block: its errors stop everything) =====
`;

