export function buildDryRun(src) {
  const a = src.indexOf(OPEN), b = src.lastIndexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) throw new Error('066 DO $do$ ... END $do$; not found');
  const body = src.slice(a + OPEN.length, b);                          // DECLARE ... BEGIN ... (no END)
  if (!/^DECLARE\n/.test(body)) throw new Error('066 body does not start with DECLARE - not found where measured');
  if (body.includes('$dry$')) throw new Error('066 uses $dry$ - choose other tags');
  if (/\bdry_(fp_before|b54_before|trg_before|n|v|ids|sql|ids_sql)\b|\b(ok|bad|res)\b\s*(int|text\[\])/.test(body)) throw new Error('066 declares a name the dry run uses - choose other tags');
  const out = HEADER + '\n' + PROLOGUE + body + '\nEND;\n' + EPILOGUE;
  const bad = [...out].findIndex((c) => c.charCodeAt(0) > 127);
  if (bad >= 0) throw new Error('non-ASCII at ' + bad);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = buildDryRun(fs.readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (cur !== out) { console.error('066_rt_group_base_join_dryrun.sql drifted from 066 - regenerate'); process.exit(1); }
    console.log('066 dry run matches 066');
  } else {
    fs.writeFileSync(TARGET, out);
    console.log('wrote', path.relative(process.cwd(), TARGET), out.length, 'chars');
  }
}
