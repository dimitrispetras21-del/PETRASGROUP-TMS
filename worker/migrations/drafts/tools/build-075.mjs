// Generates the dry run and the rollback of 075 FROM its source (075_plan_order_side.sql):
//   node worker/migrations/drafts/tools/build-075.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-075.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 075 applied - it reads them (and the md5 before / after) from the source, never a hand copy.
// tests/sql-075-drafts.test.js fails on drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDryRun } from './build-073-dryrun.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// The folder that holds the 075 files. 075 was executed 28/10 and left drafts/ (CLAUDE.md rule 5): the source and the
// generated files are one up, the builder stays here.
export const DIR = path.resolve(HERE, '..', '..');
export const SOURCE = '075_plan_order_side.sql';
const md5Of = (sig) => `(SELECT md5(prosrc) FROM pg_proc WHERE oid = '${sig}'::regprocedure)`;
const SIGS = ['public.plan_orders_create(jsonb,text,text)', 'public.plan_order_update(jsonb,text,text)', 'public.plan_board(date,text)'];

// The facts of the source, read once: the hunk constants, the live md5 (PART 0) and the generated md5 (PART 2)
export function facts(src) {
  const a = src.indexOf('  -- the hunks:'), b = src.indexOf('  v_g record;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the hunk block was not found`);
  const part0 = src.slice(src.indexOf('===== PART 0'), src.indexOf('===== PART 1'));
  const part2 = src.slice(src.indexOf('===== PART 2'), src.indexOf('===== PART 3'));
  const live = Object.fromEntries([...part0.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', '([0-9a-f]{32})'\)/g)].map((m) => [m[1], m[2]]));
  const gen = [...part2.matchAll(/\('(public\.[a-z_]+\([a-z,]*\))', ARRAY\[([a-z0-9_, ]+)\], ARRAY\[([a-z0-9_, ]+)\], '([0-9a-f]{32})'\)/g)]
    .map((m) => ({ sig: m[1], a: m[2].split(',').map((x) => x.trim()), b: m[3].split(',').map((x) => x.trim()), m: m[4] }));
  if (SIGS.some((s) => !live[s]) || gen.length !== 3 || gen.some((g) => !live[g.sig] || g.a.length !== g.b.length)) {
    throw new Error(`${SOURCE}: PART 0 / PART 2 lists are not the three functions with their hunks`);
  }
  return { hunks: src.slice(a, b), live, gen };
}

export const DRY = {
  source: SOURCE, target: '075_plan_order_side_dryrun.sql', name: 'DRY RUN 075',
  header: `-- 075 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-075.mjs from 075_plan_order_side.sql.
-- DO NOT EDIT BY HAND (tests/sql-075-drafts.test.js fails on drift). ONE DO block = ONE statement: its final error
-- undoes everything inside it (lesson 056). ASCII only.
-- EXPECTED (the red ERROR is deliberate): NOTICE "075 OK: 2 helpers (closed), 3 functions patched ..." and then
--   ERROR: P0001: DRY RUN 075 finished - EVERYTHING UNDONE, nothing kept. The block ran to its end  ||  075 ran:
--   helpers yes, create b0c6b0ac..., update b614c9b9..., board 670f72f6...
--   Anything else: do NOT run 075, copy the message to the coordinator.`,
  epilogue: `  res := format('075 ran: helpers %s, create %s, update %s, board %s',
    CASE WHEN to_regprocedure('public.plan_h_side_dir(text)') IS NOT NULL AND to_regprocedure('public.plan_h_dir_side(text)') IS NOT NULL
         THEN 'yes' ELSE 'NO' END,
    ${md5Of(SIGS[0])}, ${md5Of(SIGS[1])}, ${md5Of(SIGS[2])});`,
};

export function buildRollback(src) {
  const f = facts(src);
  const loop = f.gen.map((g) => `      ('${g.sig}', ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}], '${g.m}', '${f.live[g.sig]}')`).join(',\n');
  return `-- 075 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-075.mjs from 075_plan_order_side.sql.
-- DO NOT EDIT BY HAND. The three functions back to their live text of 28/10 byte for byte (the hunks of 075 in
-- reverse, md5-proven), the two helpers dropped. The directions already stored in national_orders.direction STAY
-- (they are the user's data; the board then reads the hub rule again). Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "075 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_g record; v_h record; v_new text; p pg_proc%rowtype;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  IF to_regprocedure('public.plan_h_side_dir(text)') IS NULL OR to_regprocedure('public.plan_h_dir_side(text)') IS NULL THEN
    RAISE EXCEPTION '075 rollback: 075 is not applied';
  END IF;
  FOR v_g IN SELECT * FROM (VALUES
${loop}) g(sig, b, a, m_now, m_live) LOOP
    SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure(v_g.sig);
    IF md5(p.prosrc) <> v_g.m_now THEN
      RAISE EXCEPTION '075 rollback: % is not the text 075 wrote (md5 %) - stop', v_g.sig, md5(p.prosrc);
    END IF;
    v_new := p.prosrc;
    FOR v_h IN SELECT * FROM unnest(v_g.b, v_g.a) h(b, a) LOOP
      IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
        RAISE EXCEPTION '075 rollback: a hunk of 075 is not in % exactly once - stop', v_g.sig;
      END IF;
      v_new := replace(v_new, v_h.b, v_h.a);
    END LOOP;
    IF md5(v_new) <> v_g.m_live THEN
      RAISE EXCEPTION '075 rollback: % would not be its live text (md5 %)', v_g.sig, md5(v_new);
    END IF;
    EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE plpgsql %s %s SET search_path = public AS %L',
      split_part(v_g.sig, '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
      CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
      CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  END LOOP;
  DROP FUNCTION public.plan_h_side_dir(text);
  DROP FUNCTION public.plan_h_dir_side(text);
  RAISE NOTICE '075 ROLLBACK OK';
END $do$;
`;
}

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  return { [DRY.target]: buildDryRun(src, DRY), '075_plan_order_side_rollback.sql': buildRollback(src) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
