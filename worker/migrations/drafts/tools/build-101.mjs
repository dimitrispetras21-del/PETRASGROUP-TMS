export function buildRollback(src) {
  const f = facts(src);
  return `-- 101 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-101.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. Everything 101 did, reversed: B-11 / B-12, the two triggers and invoice_mark_guard() back to
-- their texts of 2/11 (md5-proven), both views rebuilt without self_delivery (DROP + CREATE: a view cannot lose a
-- column in place; owner and rights put back exactly as they were), then the column dropped from orders and
-- national_orders. If another object depends on a view the DROP refuses (no CASCADE) and nothing is kept.
-- ORDER: the front end reverted and the Worker rolled back FIRST (the Worker of 101 reads self_delivery from both views:
-- after this rollback it is a 500 on every read).
-- It STOPS (nothing changed) and names them while a live order is invoiced as a self delivery: 043 refuses those without
-- a TPY. Undo them from the screen first ("Anairesi timologisis"), then run it again. Audit rows already written STAY.
-- Only with an explicit yes. ASCII. ONE DO block.
-- EXPECTED: NOTICE "101 ROLLBACK OK".
DO $do$
DECLARE
${f.block}  v_cur text; v_owd text; v_nowd text; v_bad text; v_acl aclitem[]; v_own oid; v_fn_acl text;
  r record; g record; k int; trg_before int; trg_after int;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  PERFORM set_config('search_path', 'public', true);
  IF (SELECT count(*) FROM pg_attribute WHERE attname = 'self_delivery' AND NOT attisdropped
        AND attrelid IN ('public.orders'::regclass, 'public.national_orders'::regclass)) <> 2 THEN
    RAISE EXCEPTION '101 rollback: self_delivery is not on both tables - 101 has not run, nothing to reverse';
  END IF;
  SELECT string_agg(x, ', ') INTO v_bad FROM (
    SELECT 'order ' || id AS x FROM public.orders WHERE deleted_at IS NULL AND invoiced AND self_delivery
    UNION ALL SELECT 'national order ' || id FROM public.national_orders WHERE deleted_at IS NULL AND invoiced AND self_delivery) s;
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION '101 rollback: invoiced as self deliveries (043 refuses them without a TPY) - undo them from the screen first: %', v_bad;
  END IF;
  SELECT prosrc, proacl::text INTO v_cur, v_fn_acl FROM pg_proc WHERE oid = 'public.invoice_mark_guard()'::regprocedure;
  IF (length(v_cur) - length(replace(v_cur, fn_b, ''))) <> length(fn_b) OR md5(replace(v_cur, fn_b, fn_a)) <> c_fn_live THEN
    RAISE EXCEPTION '101 rollback: invoice_mark_guard() is not the text 101 wrote - stop';
  END IF;
  IF (SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal AND tgenabled = 'O'
        AND ((tgrelid = 'public.orders'::regclass AND pg_get_triggerdef(oid) = replace(c_trg_o, 'price ON', 'price, self_delivery ON'))
          OR (tgrelid = 'public.national_orders'::regclass AND pg_get_triggerdef(oid) = replace(c_trg_n, 'price ON', 'price, self_delivery ON')))) <> 2 THEN
    RAISE EXCEPTION '101 rollback: the two triggers are not the ones 101 wrote - stop';
  END IF;
  v_owd := pg_get_viewdef('public.orders_with_derived'::regclass);
  v_nowd := pg_get_viewdef('public.national_orders_with_derived'::regclass);
  IF (length(v_owd) - length(replace(v_owd, owd_b, ''))) <> length(owd_b) OR md5(replace(v_owd, owd_b, owd_a)) <> c_owd_live
     OR (length(v_nowd) - length(replace(v_nowd, nowd_b, ''))) <> length(nowd_b) OR md5(replace(v_nowd, nowd_b, nowd_a)) <> c_nowd_live THEN
    RAISE EXCEPTION '101 rollback: a view is not the text 101 wrote - stop';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM monitoring.checks WHERE id = 'B-11' AND md5(replace(sql_text, chk_b, chk_a)) = c_b11_sql AND md5(replace(ids_sql, chk_b, chk_a)) = c_b11_ids)
     OR NOT EXISTS (SELECT 1 FROM monitoring.checks WHERE id = 'B-12' AND md5(replace(sql_text, chk_b, chk_a)) = c_b12_sql AND md5(replace(ids_sql, chk_b, chk_a)) = c_b12_ids) THEN
    RAISE EXCEPTION '101 rollback: B-11 / B-12 are not the texts 101 wrote - stop';
  END IF;
  SELECT count(*) INTO trg_before FROM pg_trigger t JOIN pg_class cl ON cl.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = cl.relnamespace
   WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';

  UPDATE monitoring.checks SET sql_text = replace(sql_text, chk_b, chk_a), ids_sql = replace(ids_sql, chk_b, chk_a) WHERE id IN ('B-11', 'B-12');
  GET DIAGNOSTICS k = ROW_COUNT;
  IF k <> 2 THEN RAISE EXCEPTION '101 rollback: B-11 / B-12 not both restored (% rows)', k; END IF;
  CREATE OR REPLACE TRIGGER orders_invoice_mark_guard
    BEFORE INSERT OR UPDATE OF invoiced, invoice_number, price ON public.orders
    FOR EACH ROW EXECUTE FUNCTION invoice_mark_guard();
  CREATE OR REPLACE TRIGGER national_orders_invoice_mark_guard
    BEFORE INSERT OR UPDATE OF invoiced, invoice_number, price ON public.national_orders
    FOR EACH ROW EXECUTE FUNCTION invoice_mark_guard();
  EXECUTE format('CREATE OR REPLACE FUNCTION public.invoice_mark_guard() RETURNS trigger LANGUAGE plpgsql AS %L', replace(v_cur, fn_b, fn_a));

  -- the two views: same name, the text of 2/11, the owner and the rights read before the DROP put back one by one
  -- (a new view in public gets Supabase's default grants - anon, authenticated - which are taken away again)
  FOR r IN SELECT * FROM (VALUES ('public.orders_with_derived', replace(v_owd, owd_b, owd_a)),
                                 ('public.national_orders_with_derived', replace(v_nowd, nowd_b, nowd_a))) x(rel, def) LOOP
    SELECT relacl, relowner INTO v_acl, v_own FROM pg_class WHERE oid = r.rel::regclass;
    EXECUTE 'DROP VIEW ' || r.rel;
    EXECUTE 'CREATE VIEW ' || r.rel || ' AS ' || rtrim(r.def, E'; \\n');
    EXECUTE format('ALTER VIEW %s OWNER TO %I', r.rel, pg_get_userbyid(v_own));
    FOR g IN SELECT DISTINCT e.grantee FROM pg_class c, aclexplode(c.relacl) e WHERE c.oid = r.rel::regclass AND e.grantee <> v_own LOOP
      EXECUTE format('REVOKE ALL ON %s FROM %s', r.rel, CASE WHEN g.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(g.grantee)) END);
    END LOOP;
    FOR g IN SELECT e.grantee, e.privilege_type, e.is_grantable FROM aclexplode(v_acl) e WHERE e.grantee <> v_own LOOP
      EXECUTE format('GRANT %s ON %s TO %s%s', g.privilege_type, r.rel,
        CASE WHEN g.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(g.grantee)) END,
        CASE WHEN g.is_grantable THEN ' WITH GRANT OPTION' ELSE '' END);
    END LOOP;
    IF (SELECT relacl::text FROM pg_class WHERE oid = r.rel::regclass) IS DISTINCT FROM v_acl::text
       OR (SELECT relowner FROM pg_class WHERE oid = r.rel::regclass) <> v_own THEN
      RAISE EXCEPTION '101 rollback proof: % did not get its owner and rights back', r.rel;
    END IF;
  END LOOP;
  ALTER TABLE public.orders DROP COLUMN self_delivery;
  ALTER TABLE public.national_orders DROP COLUMN self_delivery;

  IF (SELECT md5(prosrc) FROM pg_proc WHERE oid = 'public.invoice_mark_guard()'::regprocedure) <> c_fn_live
     OR (SELECT proacl::text FROM pg_proc WHERE oid = 'public.invoice_mark_guard()'::regprocedure) IS DISTINCT FROM v_fn_acl THEN
    RAISE EXCEPTION '101 rollback proof: invoice_mark_guard() is not 043''s text with its rights';
  END IF;
  IF (SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal AND tgenabled = 'O'
        AND ((tgrelid = 'public.orders'::regclass AND pg_get_triggerdef(oid) = c_trg_o)
          OR (tgrelid = 'public.national_orders'::regclass AND pg_get_triggerdef(oid) = c_trg_n))) <> 2 THEN
    RAISE EXCEPTION '101 rollback proof: the two triggers are not 043''s';
  END IF;
  IF md5(pg_get_viewdef('public.orders_with_derived'::regclass)) <> c_owd_live
     OR md5(pg_get_viewdef('public.national_orders_with_derived'::regclass)) <> c_nowd_live THEN
    RAISE EXCEPTION '101 rollback proof: a view is not its text of 2/11';
  END IF;
  IF (SELECT count(*) FROM monitoring.checks WHERE (id = 'B-11' AND md5(sql_text) = c_b11_sql AND md5(ids_sql) = c_b11_ids)
                                               OR (id = 'B-12' AND md5(sql_text) = c_b12_sql AND md5(ids_sql) = c_b12_ids)) <> 2 THEN
    RAISE EXCEPTION '101 rollback proof: B-11 / B-12 are not their texts of 2/11';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_attribute WHERE attname = 'self_delivery' AND NOT attisdropped
              AND attrelid IN ('public.orders'::regclass, 'public.national_orders'::regclass)) THEN
    RAISE EXCEPTION '101 rollback proof: self_delivery is still there';
  END IF;
  SELECT count(*) INTO trg_after FROM pg_trigger t JOIN pg_class cl ON cl.oid = t.tgrelid JOIN pg_namespace ns ON ns.oid = cl.relnamespace
   WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  IF trg_after <> trg_before THEN
    RAISE EXCEPTION '101 rollback proof: trigger count % -> % (expected unchanged)', trg_before, trg_after;
  END IF;
  RAISE NOTICE '101 ROLLBACK OK';
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '101_self_delivery_rollback_dryrun.sql', name: 'DRY RUN 101 ROLLBACK',
  header: `-- 101 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-101.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "101 ROLLBACK OK" then ERROR: P0001: DRY RUN 101 ROLLBACK finished - EVERYTHING UNDONE ...
--   columns 0, guard LIVE_FN, triggers on self_delivery 0, views end on it 0,
--   b11 LIVE_B11, b12 LIVE_B12`,
  epilogue: EPI.replace('101 ran:', 'rollback ran:'),
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const f = facts(src);
  const rb = buildRollback(src);
  const h = DRY.header.replace('GEN_FN', GEN_MD5.fn).replace('GEN_B11', GEN_MD5.b11).replace('GEN_B12', GEN_MD5.b12);
  const rh = RB_DRY.header.replace('LIVE_FN', f.consts.c_fn_live).replace('LIVE_B11', f.consts.c_b11_sql).replace('LIVE_B12', f.consts.c_b12_sql);
  return { [DRY.target]: buildDryRun(src, { ...DRY, header: h }), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, { ...RB_DRY, header: rh }) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
