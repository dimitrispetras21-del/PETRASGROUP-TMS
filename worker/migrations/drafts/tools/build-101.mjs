// Generates the dry run, the rollback and the rollback's dry run of 101 FROM its source (101_self_delivery.sql):
//   node worker/migrations/drafts/tools/build-101.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-101.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 101 applied - it declares the source's own constants block (live md5, trigger texts, hunks), never a hand copy.
// tests/sql-101-drafts.test.js fails on drift; tms-auditor/test/plan-101.test.mjs runs them on a PGlite copy.
