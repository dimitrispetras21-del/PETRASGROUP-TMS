const HERE = path.dirname(fileURLToPath(import.meta.url));
// drafts/ until the owner runs 101, then one up (CLAUDE.md rule 5): the builder stays here
const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = '101_self_delivery.sql';
export const DIR = fs.existsSync(path.join(DRAFTS, SOURCE)) ? DRAFTS : path.resolve(DRAFTS, '..');
export const ROLLBACK = '101_self_delivery_rollback.sql';
// md5 of the texts 101 writes (invoice_mark_guard, B-11 and B-12 sql_text): the dry run's header names them, verify
// reads them. tms-auditor/test/plan-101.test.mjs derives them from the live texts (043's file, the 047b seed) with
// generated() below and from the run itself, and fails if these differ.
export const GEN_MD5 = { fn: '670400a6032afeaa247787464533704f', b11: 'a75afea135d5685718c62c44b0f1ebcf', b12: '34da2de0eedfbdbbfaf20a705c125c3c' };

export function facts(src) {
  const a = src.indexOf('  -- the live texts read 2/11/2026'), b = src.indexOf('  v_src text;');
  if (a < 0 || b < a) throw new Error(`${SOURCE}: the constants block was not found`);
  const consts = Object.fromEntries([...src.slice(a, b).matchAll(/^ {2}([a-z0-9_]+) CONSTANT text := (?:'([^']*)'|\$h\$([\s\S]*?)\$h\$);$/gm)]
    .map((m) => [m[1], m[2] ?? m[3]]));
  for (const k of ['c_fn_live', 'c_owd_live', 'c_nowd_live', 'c_b11_sql', 'c_b11_ids', 'c_b12_sql', 'c_b12_ids', 'c_trg_o', 'c_trg_n',
    'fn_a', 'fn_b', 'owd_a', 'owd_b', 'nowd_a', 'nowd_b', 'chk_a', 'chk_b']) {
    if (!(k in consts)) throw new Error(`${SOURCE}: constant ${k} missing`);
  }
  return { consts, block: src.slice(a, b) };
}

// The texts 101 writes, from live texts (the PGlite test derives GEN_MD5 with it)
export function generated(liveFn, liveB11, liveB12) {
  const { consts: c } = facts(fs.readFileSync(path.join(DIR, SOURCE), 'utf8'));
  return { fn: liveFn.replace(c.fn_a, () => c.fn_b), b11: liveB11.split(c.chk_a).join(c.chk_b), b12: liveB12.split(c.chk_a).join(c.chk_b) };
}

