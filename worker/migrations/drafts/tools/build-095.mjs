// Generates the dry run, the rollback and the rollback's dry run of 095 FROM its source (095_plan_small_relaxed.sql):
//   node worker/migrations/drafts/tools/build-095.mjs          (writes them)
//   node worker/migrations/drafts/tools/build-095.mjs --check  (exit 1 if a committed file drifted)
// Why generated (principle 3): the dry run runs EXACTLY the owner's statements, and the rollback reverses EXACTLY the
// hunks 095 applied - it reads them (and the md5 before / after) from the source, never a hand copy. The shape is
// 092's (build-092.mjs), plus the two CHECKs and B-93 that 095 changes.
// tests/sql-095-drafts.test.js fails on drift; tms-auditor/test/plan-095.test.mjs runs them on the production-shaped copy.
