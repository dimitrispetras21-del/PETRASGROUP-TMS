export function buildRollback(src) {
  const f = facts(src);
  const blocks = f.gen.map((g) => `  SELECT * INTO p FROM pg_proc WHERE oid = to_regprocedure('${g.sig}');
  IF md5(p.prosrc) <> '${g.m}' THEN
    RAISE EXCEPTION '095 rollback: ${g.sig} is not the text 095 wrote (md5 %) - stop', md5(p.prosrc);
  END IF;
  v_new := p.prosrc;
  FOR v_h IN SELECT * FROM unnest(ARRAY[${[...g.b].reverse().join(', ')}], ARRAY[${[...g.a].reverse().join(', ')}]) h(b, a) LOOP
    IF (length(v_new) - length(replace(v_new, v_h.b, ''))) <> length(v_h.b) THEN
      RAISE EXCEPTION '095 rollback: a hunk of 095 is not in ${g.sig} exactly once - stop';
    END IF;
    v_new := replace(v_new, v_h.b, v_h.a);
  END LOOP;
  IF md5(v_new) <> '${f.live[g.sig]}' THEN
    RAISE EXCEPTION '095 rollback: ${g.sig} would not be its live text (md5 %)', md5(v_new);
  END IF;
  EXECUTE format('CREATE OR REPLACE FUNCTION %s(%s) RETURNS %s LANGUAGE plpgsql %s %s SET search_path = public AS %L',
    split_part('${g.sig}', '(', 1), pg_get_function_arguments(p.oid), pg_get_function_result(p.oid),
    CASE p.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
    CASE WHEN p.prosecdef THEN 'SECURITY DEFINER' ELSE 'SECURITY INVOKER' END, v_new);
  IF ${md5Of(g.sig)} <> '${f.live[g.sig]}'
     OR (SELECT proacl::text FROM pg_proc WHERE oid = p.oid) IS DISTINCT FROM p.proacl::text THEN
    RAISE EXCEPTION '095 rollback proof: ${g.sig} is not back to its live text with its rights';
  END IF;`).join('\n');
  return `-- 095 ROLLBACK - GENERATED by worker/migrations/drafts/tools/build-095.mjs from ${SOURCE}.
-- DO NOT EDIT BY HAND. The six functions back to their live texts of 2/11 byte for byte (the hunks of 095 in reverse,
-- md5-proven), CHECK seg_change_pair and seg_other_note as 072b made them, B-93 enabled again: a local loading on its
-- stop's day only, a vehicle change with a point AND a reason, "other" with its note.
-- It STOPS (nothing changed) and names them when the base holds what the old rules refuse: a live local loading on
-- another day than its stop, a segment with a point and no reason, an "other" without a note. Correct those first
-- (from the screen), then run it again. Audit rows already written STAY. Only with an explicit yes.
-- ASCII. ONE DO block.
-- EXPECTED: NOTICE "095 ROLLBACK OK".
DO $do$
DECLARE
${f.hunks}  v_h record; v_new text; p pg_proc%rowtype; v_bad text;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  SELECT string_agg(DISTINCT 'local_move ' || lm.id, ', ') INTO v_bad
    FROM public.local_moves lm JOIN public.rt_stops s ON s.id = lm.rt_stop_id
   WHERE lm.move_kind = 'nat_loading' AND lm.deleted_at IS NULL AND lm.status <> 'Cancelled' AND s.deleted_at IS NULL
     AND lm.move_date <> (s.planned_from AT TIME ZONE 'Europe/Athens')::date;
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION '095 rollback: local loadings on another day than their stop (071 refuses them) - stop: %', v_bad;
  END IF;
  SELECT string_agg(DISTINCT r.code, ', ') INTO v_bad
    FROM public.rt_vehicle_segments g JOIN public.ct_round_trips r ON r.id = g.rt_id
   WHERE NOT ((${OLD_PAIR}) AND (${OLD_OTHER}));
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION '095 rollback: segments with a point and no reason, or "other" without a note (the CHECKs of 072b refuse them) - stop: %', v_bad;
  END IF;
  ALTER TABLE public.rt_vehicle_segments DROP CONSTRAINT seg_change_pair,
    ADD CONSTRAINT seg_change_pair CHECK (${OLD_PAIR}),
    ADD CONSTRAINT seg_other_note CHECK (${OLD_OTHER});
  IF (SELECT md5(pg_get_constraintdef(oid)) FROM pg_constraint WHERE conrelid = 'public.rt_vehicle_segments'::regclass
        AND conname = 'seg_change_pair') IS DISTINCT FROM '0a84a8c84651dea65eb8d7447c47eca3'
     OR (SELECT md5(pg_get_constraintdef(oid)) FROM pg_constraint WHERE conrelid = 'public.rt_vehicle_segments'::regclass
        AND conname = 'seg_other_note') IS DISTINCT FROM '176a16938a0aad6164d3c3d6419cdd11' THEN
    RAISE EXCEPTION '095 rollback proof: seg_change_pair / seg_other_note are not the CHECKs of 072b';
  END IF;
  UPDATE monitoring.checks SET enabled = true, disabled_reason = NULL WHERE id = 'B-93';
${blocks}
  RAISE NOTICE '095 ROLLBACK OK';
END $do$;
`;
}

export const RB_DRY = {
  source: ROLLBACK, target: '095_plan_small_relaxed_rollback_dryrun.sql', name: 'DRY RUN 095 ROLLBACK',
  header: `-- 095 ROLLBACK DRY RUN - GENERATED by worker/migrations/drafts/tools/build-095.mjs from ${ROLLBACK}.
-- DO NOT EDIT BY HAND. The rollback's block verbatim, ending with a deliberate error: NOTHING is kept. ASCII. ONE DO block.
-- EXPECTED: NOTICE "095 ROLLBACK OK" then ERROR: P0001: DRY RUN 095 ROLLBACK finished - EVERYTHING UNDONE ...
--   problem LIVE_K, local LIVE_L, rt_update LIVE_U,
--   seg_problem LIVE_P, seg_change LIVE_C, seg_fix LIVE_F,
--   pair CHECK (((reason IS NULL) = (place_note IS NULL))), b93 t`,
  epilogue: EPI.replace('095 ran:', 'rollback ran:'),
};

export function buildAll() {
  const src = fs.readFileSync(path.join(DIR, SOURCE), 'utf8');
  const f = facts(src);
  const rb = buildRollback(src);
  const keys = ['K', 'L', 'U', 'P', 'C', 'F'];
  // the dry runs' headers name the md5 the run must end on (one fact: PART 2 of the source, PART 0 for the rollback)
  let h = DRY.header, rh = RB_DRY.header;
  f.gen.forEach((g, i) => { h = h.replace('GEN_' + keys[i], g.m); rh = rh.replace('LIVE_' + keys[i], f.live[g.sig]); });
  return { [DRY.target]: buildDryRun(src, { ...DRY, header: h }), [ROLLBACK]: rb, [RB_DRY.target]: buildDryRun(rb, { ...RB_DRY, header: rh }) };
}

// realpath: through a symlink path.resolve would differ and --check could not fail (found on 072b's tool)
if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  for (const [f, s] of Object.entries(out)) if (/[^\x00-\x7f]/.test(s)) { console.error(`${f}: non-ASCII`); process.exit(1); }
  if (process.argv.includes('--check')) {
    const drift = Object.entries(out).filter(([f, s]) => !fs.existsSync(path.join(DIR, f)) || fs.readFileSync(path.join(DIR, f), 'utf8') !== s);
    if (drift.length) { console.error('drift: ' + drift.map(([f]) => f).join(', ')); process.exit(1); }
    console.log('0 drift');
    process.exit(0);
  }
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(DIR, f), s);
  console.log('wrote: ' + Object.keys(out).join(', '));
}
