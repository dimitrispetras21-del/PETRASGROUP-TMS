// Generates worker/migrations/drafts/065_temp_per_cmr_dryrun.sql FROM 065_temp_per_cmr.sql.
//   node worker/migrations/drafts/tools/build-065-dryrun.mjs          (writes the file)
//   node worker/migrations/drafts/tools/build-065-dryrun.mjs --check  (exit 1 if the committed file drifted)
// Why generated, never hand-copied (principle 3): the dry run is only worth anything if it runs EXACTLY the
// statements 065 will run. A hand copy drifts the first time 065 is edited and then "proves" a migration nobody
// will execute. tms-auditor/test/dryrun-065.test.mjs fails when the committed file differs.
// Same shape as build-063-dryrun.mjs: ONE DO $dry$ block - a prologue that fingerprints data 065 must not touch,
// 065's DO block VERBATIM as a nested block (its guards and proofs raise their own messages and stop everything),
// an epilogue of scenarios that each report ok / FAIL / ERROR without stopping the others, and a final RAISE
// EXCEPTION that carries the result line and undoes all of it. 065 is ASCII only, so the whole file is.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DRAFTS = path.resolve(HERE, '..');
export const SOURCE = path.join(DRAFTS, '065_temp_per_cmr.sql');
export const TARGET = path.join(DRAFTS, '065_temp_per_cmr_dryrun.sql');
// orders_with_derived after 065 (measured on the PGlite copy of production; 065's header says the same).
export const OWD_MD5_AFTER = '55736818891a8f4e06193b23265cacf4';

const OPEN = '\nDO $do$\n';
const CLOSE = '\nEND $do$;\n';

const HEADER = `-- 065 DRY RUN - GENERATED by worker/migrations/drafts/tools/build-065-dryrun.mjs from 065_temp_per_cmr.sql.
-- DO NOT EDIT BY HAND: edit 065 and regenerate (tms-auditor/test/dryrun-065.test.mjs fails on any drift).
--
-- WHAT: 065's own DO block, statement for statement (every guard, change and proof, B-54 run as
--   tms_check_runner), wrapped in ONE outer DO block that first fingerprints data 065 must not touch, then
--   checks the result, and ENDS WITH A DELIBERATE ERROR. The error rolls the whole block back: NOTHING it did
--   is kept (no column, no view change).
-- WHEN: the same evening, AFTER 15:00 (the team works 05:30-14:30), BEFORE 065_temp_per_cmr.sql. It takes the
--   same locks as 065 (lock_timeout 5 s, then it gives up - run it again a little later).
-- WHY ONE DO BLOCK: the Supabase SQL editor is NOT atomic across statements (lesson 056), but ONE DO block is
--   ONE statement: its final error undoes everything inside it.
-- EXPECTED (the red ERROR is deliberate):
--   ERROR: P0001: DRY RUN 065 finished - EVERYTHING UNDONE, nothing kept. Result: 3 OK, 0 FAIL  ||  A ok ... | B ok triggers 35 = 35, B-54 35 | C ok ...
--   Anything with FAIL or ERROR in it: do NOT run 065, copy the panel to the coordinator.
--   ONE exception: "2 OK, 1 FAIL" where the FAIL is C alone (A ok, B ok). C fingerprints every order, every
--   row of orders_with_derived, the auditor rows and every public sequence while the block runs, so ONE save
--   by someone else in those seconds turns it red - it fails closed, nothing was kept. Wait 5 minutes and run
--   the dry run once more; if C fails again, copy the panel to the coordinator.
--   A different message altogether ("065: ...", "065 proof: ...", a lock timeout) is the guard or proof of 065
--   that stopped - exactly what 065 itself would have said. Do NOT run 065.
-- AFTER: 065_temp_per_cmr_verify.sql V0 again - nothing was kept: orders has no temp_per_cmr and
--   orders_with_derived is still the 057 text (md5 4f82b738847c4770ccc379b1d558d542, 137 columns).
-- Scenarios: A 065's column and view exist inside the block (view md5 = the one measured after 065);
--   B the trigger count did not move and B-54 equals it (35); C data 065 must not touch is unchanged (every
--   order and every orders_with_derived row without the new key, every auditor row, every public sequence).
`;

// Whole rows (to_jsonb) minus the ONE new key, not a column list: the fingerprint must say "every value that
// existed before is still there, identical" for the table AND for the view the Worker reads, whatever columns
// they have. Before 065 the key is absent, so "- 'temp_per_cmr'" is a no-op there.
const FP = `(SELECT md5(
    coalesce((SELECT string_agg((to_jsonb(x) - 'temp_per_cmr')::text, ',' ORDER BY x.id) FROM public.orders x), '')
 || coalesce((SELECT string_agg((to_jsonb(x) - 'temp_per_cmr')::text, ',' ORDER BY x.id) FROM public.orders_with_derived x), '')
 || coalesce((SELECT string_agg(concat_ws(':', id, md5(sql_text), md5(coalesce(ids_sql, '')), red_value, baseline, enabled), ',' ORDER BY id) FROM monitoring.checks), '')
 || coalesce((SELECT string_agg(s.sequencename || '=' || coalesce(s.last_value::text, '-'), ',' ORDER BY s.sequencename) FROM pg_sequences s WHERE s.schemaname = 'public'), '')))`;

const PROLOGUE = `DO $dry$
DECLARE
  ok int := 0; bad int := 0; res text[] := '{}';
  dry_fp_before text; dry_b54_before numeric; dry_trg_before int; dry_n int;
BEGIN
  -- the B-54 value and the trigger count 065 will meet, and the data it must leave alone
  SELECT red_value INTO dry_b54_before FROM monitoring.checks WHERE id = 'B-54';
  SELECT count(*) INTO dry_trg_before FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
  SELECT ${FP} INTO dry_fp_before;

  -- ===== 065_temp_per_cmr.sql, its DO block verbatim (a nested block: its errors stop everything) =====
`;

const EPILOGUE = `  -- ===== end of 065 =====

  -- A: what 065 adds is there (its own proofs already raised if not; this names it in the result). 065 pinned
  --    search_path to "public, extensions" for this transaction, so the md5 is the one measured after 065.
  BEGIN
    SELECT count(*) INTO dry_n FROM public.orders WHERE temp_per_cmr;
    IF dry_n = 0
       AND (SELECT attname FROM pg_attribute WHERE attrelid = 'public.orders_with_derived'::regclass AND attnum = 138 AND NOT attisdropped) = 'temp_per_cmr'
       AND md5(pg_get_viewdef('public.orders_with_derived'::regclass)) = '${OWD_MD5_AFTER}' THEN
      ok := ok + 1; res := res || 'A ok orders.temp_per_cmr (0 marked), orders_with_derived 138 columns ending with it, view md5 as measured'::text;
    ELSE bad := bad + 1; res := res || format('A FAIL marked %s, column 138 %s, view md5 %s', dry_n,
           (SELECT attname FROM pg_attribute WHERE attrelid = 'public.orders_with_derived'::regclass AND attnum = 138),
           md5(pg_get_viewdef('public.orders_with_derived'::regclass))); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('A ERROR ' || SQLERRM);
  END;

  -- B: a column adds no trigger: the count and B-54 did not move
  BEGIN
    SELECT count(*) INTO dry_n FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
      JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE NOT t.tgisinternal AND t.tgenabled <> 'D' AND ns.nspname = 'public';
    IF dry_n = dry_trg_before AND (SELECT red_value FROM monitoring.checks WHERE id = 'B-54') = dry_n AND dry_b54_before = dry_trg_before THEN
      ok := ok + 1; res := res || format('B ok triggers %s = %s, B-54 %s', dry_trg_before, dry_n, dry_b54_before);
    ELSE bad := bad + 1; res := res || format('B FAIL triggers %s -> %s, B-54 %s -> %s', dry_trg_before, dry_n, dry_b54_before,
                                             (SELECT red_value FROM monitoring.checks WHERE id = 'B-54')); END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('B ERROR ' || SQLERRM);
  END;

  -- C: data 065 must not touch - same fingerprint after the block as before it. A save by someone else
  --    during these seconds also changes it (fails closed): the FAIL text says what to do.
  BEGIN
    IF ${FP} = dry_fp_before THEN
      ok := ok + 1; res := res || 'C ok orders, orders_with_derived rows, auditor rows, sequences unchanged'::text;
    ELSE bad := bad + 1; res := res || 'C FAIL data changed during the dry run - 065 itself, or a save by someone else in those seconds: if A and B are ok, wait 5 minutes and run the dry run once more; if C fails again, stop and copy the panel to the coordinator'::text; END IF;
  EXCEPTION WHEN others THEN bad := bad + 1; res := res || ('C ERROR ' || SQLERRM);
  END;

  RAISE EXCEPTION 'DRY RUN 065 finished - EVERYTHING UNDONE, nothing kept. Result: % OK, % FAIL  ||  %', ok, bad, array_to_string(res, '  |  ');
END
$dry$;
`;

export function buildDryRun(src) {
  const a = src.indexOf(OPEN), b = src.lastIndexOf(CLOSE);
  if (a < 0 || b < 0 || b < a) throw new Error('065 DO $do$ ... END $do$; not found');
  const body = src.slice(a + OPEN.length, b);                          // DECLARE ... BEGIN ... (no END)
  if (!/^DECLARE\n/.test(body)) throw new Error('065 body does not start with DECLARE - not found where measured');
  if (body.includes('$dry$')) throw new Error('065 uses $dry$ - choose other tags');
  if (/\bdry_(fp_before|b54_before|trg_before|n)\b|\b(ok|bad|res)\b\s*(int|text\[\])/.test(body)) throw new Error('065 declares a name the dry run uses - choose other tags');
  const out = HEADER + '\n' + PROLOGUE + body + '\nEND;\n' + EPILOGUE;
  const bad = [...out].findIndex((c) => c.charCodeAt(0) > 127);
  if (bad >= 0) throw new Error('non-ASCII at ' + bad);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = buildDryRun(fs.readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (cur !== out) { console.error('065_temp_per_cmr_dryrun.sql drifted from 065 - regenerate'); process.exit(1); }
    console.log('065 dry run matches 065');
  } else {
    fs.writeFileSync(TARGET, out);
    console.log('wrote', path.relative(process.cwd(), TARGET), out.length, 'chars');
  }
}
