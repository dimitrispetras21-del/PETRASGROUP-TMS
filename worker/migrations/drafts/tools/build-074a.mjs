// Generates the 074a dry run, rollback AND verify FROM the migration itself:
//   074a_plan_reads.sql -> 074a_plan_reads_dryrun.sql, 074a_plan_reads_rollback.sql, 074a_plan_reads_verify.sql
//   node worker/migrations/drafts/tools/build-074a.mjs          (writes the three)
//   node worker/migrations/drafts/tools/build-074a.mjs --check  (exit 1 if a committed file drifted)
// Why generated, never hand-copied (principle 3): the dry run is only worth anything if it runs EXACTLY the
// statements the owner will run; the rollback only undoes the hooks byte for byte if it holds EXACTLY the hook texts
// the migration put in (the same DECLARE lines, copied by this tool); the verify only proves "in place" against the
// md5 the migration measured. tests/sql-074a-drafts.test.js fails on any drift. Shapes as 072b (build-072b.mjs).
// ASCII in, ASCII out.
