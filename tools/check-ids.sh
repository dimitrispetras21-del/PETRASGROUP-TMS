#!/usr/bin/env bash
# Δύο επίπεδα, σκόπιμα: ΚΟΒΕΙ μόνο σε βεβαιότητα, ΑΝΑΦΕΡΕΙ την υποψία.
# Έλεγχος που φωνάζει ψεύτικα εκπαιδεύει τον κόσμο να τον αγνοεί.
#
# Γιατί: το rec-id δεν υπάρχει στη βάση — το κατασκευάζει ο Worker για να μοιάζει
# με το Airtable API. Δεν αναζητείται, δεν γράφεται, δεν είναι σε κανένα χαρτί.
# Βρέθηκαν 28/8: costs.js (μετρητής συμφωνίας) και orders_intl.js (διπλή
# παραγγελία) — και τα δύο ζητούσαν ενέργεια δίνοντας κωδικό που δεν βρίσκεται.
set -u
cd "$(dirname "$0")/.."
fail=0

# ── ΚΟΒΕΙ: .id.slice() = μορφοποίηση για ανθρώπινο μάτι. Κανείς δεν κόβει id
#    για λογική. Το αριστερό μέλος είναι συχνά πεδίο που ΔΕΝ υπάρχει στον χάρτη
#    ('Order Number' → 0 εμφανίσεις), άρα η «εφεδρεία» είναι η μόνη διαδρομή.
hard=$(grep -rnE '\.id\.slice\(' modules/ core/ 2>/dev/null | grep -vE ':[0-9]+:\s*(//|\*)')
if [ -n "$hard" ]; then
  fail=1
  echo "✗ rec-id κομμένο για εμφάνιση ($(echo "$hard" | grep -c .) σημεία):"
  echo "$hard" | sed 's/^/    /'
  echo "    → Χρησιμοποίησε 'Reference', ή πελάτη + ημερομηνία."
  echo "      Πρότυπο: ctOrderLabel() στο modules/costs.js"
fi

# ── ΑΝΑΦΕΡΕΙ: εφεδρεία σε id. Συχνά νόμιμη (κλειδί ομαδοποίησης) — γι' αυτό
#    δεν κόβει. Αν το αριστερό μέλος είναι όνομα πεδίου, έλεγξε τον χάρτη.
soft=$(grep -rnoE "\|\|\s*[a-zA-Z_$]+\??\.id\b" modules/ core/ 2>/dev/null | grep -c .)
echo "ℹ $soft εφεδρείες «|| x.id» — νόμιμες ως κλειδιά, ύποπτες σε κείμενο."
echo "   grep -rn '|| .*\.id' modules/ core/"

[ $fail -eq 0 ] && echo "✓ κανένα rec-id κομμένο για εμφάνιση"
exit $fail
